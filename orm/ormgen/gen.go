// Package ormgen generates the code of an application from a velox schema graph: one entity package
// holding every entity, and one small package per entity holding its field
// and edge descriptors.
package ormgen

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	vgen "github.com/syssam/velox/compiler/gen"
	"github.com/syssam/velox/schema/field"
)

// Config says where the generated packages go.
type Config struct {
	// Target is the output directory.
	Target string
	// Package is the import path of Target.
	Package string
	// GraphQL, when set, also generates the GraphQL schema and the Go types
	// an engine binds it to.
	GraphQL *GraphQL
}

const (
	ormPath = "github.com/syssam/velox/orm"
	// veloxPath is the library's root package: the database handle, the
	// errors and the types of a paged list that generated code names.
	veloxPath = "github.com/syssam/velox"
	// gqlinputPath is the runtime of the GraphQL layer: what the generated
	// where and order inputs, and the node lookup, call.
	gqlinputPath = "github.com/syssam/velox/contrib/graphql/gqlinput"
	header       = "// Code generated by velox-gen. DO NOT EDIT.\n\n"
)

// fld is one column of an entity: a schema field, the id, or a foreign key
// that has no schema field.
type fld struct {
	F      *vgen.Field
	GoName string // struct field name
	Col    string
	Base   string // Go type without the pointer of a nillable field
	Ptr    bool   // the struct field is *Base
	IsID   bool
	Hidden bool   // foreign key without a schema field: unexported struct field
	Null   bool   // the column accepts NULL
	JSON   string // json key of the struct field
	Enum   string // name of the generated enum type in the entity package, when the field is an enum without a Go type
	Desc   string // descriptor variable name in the entity package ("" for hidden)
}

func (f *fld) goType() string {
	if f.Ptr {
		return "*" + f.Base
	}
	return f.Base
}

type edg struct {
	E      *vgen.Edge
	GoName string // struct field name in Edges
	Target *ent
	Type   string // per-edge descriptor type in the entity package
	Desc   string // descriptor variable name in the entity package
	Index  int
}

type ent struct {
	T      *vgen.Type
	Name   string
	Pkg    string
	ID     *fld
	Fields []*fld // id first, then schema fields, then hidden foreign keys
	Edges  []*edg
	linked bool      // some edge targets the entity
	alias  string    // name package entity imports the entity package under
	pnames [2]string // its Setter and OrderTerm types in the predicate package
}

// The types of the predicate package that belong to the entity. They are in a
// package of their own, below the per-entity packages and package entity, so that an
// entity package can name the types of its edge targets without importing
// them (or package entity), and does not change when another entity does.
// The types of an entity in the predicate package. Its predicate type is
// named like the entity, as in velox (predicate.User): the package name says
// what it is. The others carry a suffix, and give way to an entity that is
// named like one of them (the setters of Purchase and an entity called
// PurchaseSetter).
func (e *ent) pred() string  { return "predicate." + e.Name }
func (e *ent) set() string   { return "predicate." + e.pnames[0] }
func (e *ent) order() string { return "predicate." + e.pnames[1] }

type generator struct {
	cfg   Config
	ents  []*ent
	by    map[string]*ent
	taken map[string]bool // identifiers of package entity

	// The GraphQL layer, when Config.GraphQL asks for it.
	gql       map[*ent]*gqlEnt
	enumOwner map[*fld]*ent
	enumType  map[*fld]string
	filterIm  *imports
}

// predicateNames names the derived types of every entity in the predicate
// package.
func (g *generator) predicateNames() {
	taken := map[string]bool{}
	for _, e := range g.ents {
		taken[e.Name] = true
	}
	for _, e := range g.ents {
		// UserSetter, not UserSet: a set of users is what that would read
		// as. UserOrderTerm, not UserOrder: entity.UserOrder is the order a
		// request asks for, and its Term method returns this.
		for i, suffix := range [...]string{"Setter", "OrderTerm"} {
			name := e.Name + suffix
			for taken[name] {
				name += "Type"
			}
			taken[name] = true
			e.pnames[i] = name
		}
	}
}

// Generate writes package entity, one package per entity and the
// schemainit package for graph into cfg.Target.
func Generate(graph *vgen.Graph, cfg Config) error {
	// A graph that was loaded from a package (and not built by a test) has
	// source to read.
	if graph.Config != nil && graph.Schema != "" {
		if err := checkAssertions(graph.Schema); err != nil {
			return err
		}
	}
	g := &generator{cfg: cfg, by: map[string]*ent{}, taken: map[string]bool{}}
	for _, t := range graph.Nodes {
		g.taken[t.Name] = true
	}
	// The names every entity gets are reserved before any derived name (an
	// enum type, an edge type) is made, so the derived one gives way.
	for _, t := range graph.Nodes {
		for _, s := range reservedNames(t.Name) {
			if g.taken[s] {
				return fmt.Errorf("velox: generated name %s collides with an entity", s)
			}
			g.taken[s] = true
		}
	}
	for _, t := range graph.Nodes {
		e, err := g.entity(t)
		if err != nil {
			return fmt.Errorf("velox: %s: %w", t.Name, err)
		}
		g.ents = append(g.ents, e)
		g.by[t.Name] = e
	}
	switch root := rootPackage(cfg.Package); root {
	case "entity", "predicate", "migrate", "schemainit", "orm", "context":
		return fmt.Errorf("velox: the output directory cannot be called %q: the root package would be named like a package it imports or contains", root)
	}
	g.packages()
	g.predicateNames()
	for _, e := range g.ents {
		if err := g.edges(e); err != nil {
			return fmt.Errorf("velox: %s: %w", e.Name, err)
		}
	}
	files := map[string][]byte{}
	var schema map[string]string
	if cfg.GraphQL != nil {
		// The enum types are named, and every field knows its own, before
		// the schema is read: a where input names them.
		g.enumOwner, g.enumType = map[*fld]*ent{}, map[*fld]string{}
		for _, e := range g.ents {
			_, types, _, _ := g.enumNames(e)
			for f, t := range types {
				g.enumOwner[f], g.enumType[f] = e, t
			}
		}
		g.filterIm = g.imports()
		var err error
		if schema, err = g.graphql(graph); err != nil {
			return err
		}
		filters, err := g.filters()
		if err != nil {
			return err
		}
		for name, src := range filters {
			files[filepath.Join("filter", name)] = src
		}
	}
	model, err := g.model()
	if err != nil {
		return err
	}
	for name, src := range model {
		files[filepath.Join("entity", name)] = src
	}
	// The package of an entity is written from that entity alone.
	leaves := make([]map[string][]byte, len(g.ents))
	err = each(len(g.ents), func(i int) error {
		src, leafErr := g.leaf(g.ents[i])
		if leafErr != nil {
			return fmt.Errorf("velox: %s: %w", g.ents[i].Name, leafErr)
		}
		leaves[i] = src
		return nil
	})
	if err != nil {
		return err
	}
	for i, e := range g.ents {
		for name, src := range leaves[i] {
			files[filepath.Join(e.Pkg, name)] = src
		}
	}
	pr, err := g.predicates()
	if err != nil {
		return err
	}
	files["predicate/predicate.go"] = pr
	cl, err := g.client()
	if err != nil {
		return err
	}
	for name, src := range cl {
		files[name] = src
	}
	init, err := g.schemaInit(graph)
	if err != nil {
		return err
	}
	for name, src := range init {
		files[filepath.Join("schemainit", name)] = src
	}
	slots, err := g.slots()
	if err != nil {
		return err
	}
	if slots != nil {
		files["internal/slots/slots.go"] = slots
	}
	if err := g.migrate(graph, files); err != nil {
		return err
	}
	for name, src := range files {
		path := filepath.Join(cfg.Target, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			return err
		}
		// An unchanged file keeps its mtime.
		if _, err := vgen.WriteFileIfChanged(path, src, 0o644); err != nil {
			return err
		}
	}
	if err := prune(cfg.Target, files); err != nil {
		return err
	}
	if cfg.GraphQL != nil {
		return g.writeSchema(schema)
	}
	return nil
}

// prune removes what an earlier generation left in target and this one did
// not write: the package of an entity that is gone from the schema would
// otherwise stay, name types that no longer exist and break the build of the
// tree. Only files carrying a generator's header are removed, and only
// directories that are empty afterwards.
func prune(target string, files map[string][]byte) error {
	// Every path is resolved inside target: a symlink in the tree cannot
	// lead a removal out of it.
	root, err := os.OpenRoot(target)
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	var dirs, stale []string
	err = fs.WalkDir(root.FS(), ".", func(rel string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if rel != "." {
				dirs = append(dirs, rel)
			}
			return nil
		}
		if _, ok := files[filepath.FromSlash(rel)]; ok || filepath.Ext(rel) != ".go" {
			return nil
		}
		f, err := root.Open(rel)
		if err != nil {
			return err
		}
		head := make([]byte, 64)
		n, _ := f.Read(head)
		_ = f.Close()
		if bytes.HasPrefix(head[:n], []byte(strings.TrimSpace(header))) {
			stale = append(stale, rel)
		}
		return nil
	})
	if err != nil {
		return err
	}
	for _, rel := range stale {
		if err := root.Remove(rel); err != nil {
			return err
		}
	}
	// Children before parents.
	for i := len(dirs) - 1; i >= 0; i-- {
		d, err := root.Open(dirs[i])
		if err != nil {
			continue
		}
		entries, err := d.ReadDir(1)
		_ = d.Close()
		if err == io.EOF && len(entries) == 0 {
			if err := root.Remove(dirs[i]); err != nil {
				return err
			}
		}
	}
	return nil
}

// hiddenName is the unexported struct field of a column without a schema
// field (a foreign key): user_posts is userPosts, post_author_id is
// postAuthorID. A name that would be a Go keyword or collide with the
// struct's Edges takes a suffix.
func hiddenName(column string) string {
	var b strings.Builder
	for _, word := range strings.Split(column, "_") {
		switch {
		case word == "":
		case b.Len() == 0:
			b.WriteString(strings.ToLower(word[:1]) + word[1:])
		case word == "id":
			b.WriteString("ID")
		default:
			b.WriteString(strings.ToUpper(word[:1]) + word[1:])
		}
	}
	name := b.String()
	if name == "" || goKeywords[name] {
		name += "Key"
	}
	return name
}

// rootPackage is the name of the package at the root of the generated tree,
// where every query starts: the last element of its import path, as a Go
// identifier. The application chooses it by choosing the directory (db, data,
// store, ...), so that it does not collide with the variable names it uses.
func rootPackage(importPath string) string {
	name := importPath[strings.LastIndex(importPath, "/")+1:]
	var b strings.Builder
	for i, r := range name {
		switch {
		case r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z', i > 0 && r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return b.String()
}

var goKeywords = map[string]bool{
	"break": true, "default": true, "func": true, "interface": true, "select": true, "case": true, "defer": true,
	"go": true, "map": true, "struct": true, "chan": true, "else": true, "goto": true, "package": true, "switch": true,
	"const": true, "fallthrough": true, "if": true, "range": true, "type": true, "continue": true, "for": true,
	"import": true, "return": true, "var": true,
	// Names the generated packages themselves use.
	"entity": true, "orm": true, "init": true, "main": true, "schemainit": true, "predicate": true, "migrate": true, "filter": true,
	// The library's root package, which generated code and the application
	// import for the database handle and the errors.
	"velox": true,
	// A directory called internal can be imported from the generated tree
	// only: the application could not name the entity's columns.
	"internal": true,
}

func (g *generator) entity(t *vgen.Type) (*ent, error) {
	if t.ID == nil {
		return nil, fmt.Errorf("entities without a single-column id are not supported yet")
	}
	e := &ent{T: t, Name: t.Name, Pkg: t.PackageDir()}
	add := func(f *vgen.Field, id bool) error {
		// Refused here, with the reason, rather than generated into code
		// that does not build or cannot write a row.
		if f.HasValueScanner() {
			return fmt.Errorf("field %q: an external ValueScanner is not supported yet; give the field's Go type Scan and Value methods instead", f.Name)
		}
		// A time field of a Go type that is not time.Time is written and
		// read by that type's own Value and Scan: without them (type Stamp
		// time.Time) every create would fail, at run time.
		if f.Type != nil && f.Type.Type == field.TypeTime && f.HasGoType() && f.Type.RType != nil && f.Type.RType.Ident != "time.Time" && (!f.Type.Valuer() || !f.Type.ValueScanner()) {
			return fmt.Errorf("field %q: a time field of the Go type %s needs that type to have Value and Scan methods (driver.Valuer and sql.Scanner)", f.Name, f.Type.RType.Ident)
		}
		base, enum, err := g.baseType(e, f)
		if err != nil {
			return fmt.Errorf("field %q: %w", f.Name, err)
		}
		if ref, rerr := goTypeOf(f); rerr == nil {
			if pkg := unknownPackage(ref); pkg != "" {
				return fmt.Errorf("field %q: its Go type %s names package %q, whose import path the schema does not record; declare a named type for the field", f.Name, ref.Expr, pkg)
			}
		}
		c := &fld{F: f, GoName: f.StructField(), Col: f.StorageKey(), Base: base, Ptr: f.Nillable, IsID: id, Enum: enum}
		// velox's tables: a column is nullable for a Nillable field, for an
		// Optional JSON field (it has no zero value to store) and for the
		// key of an optional edge.
		c.Null = f.Nillable || (f.Optional && (f.IsJSON() || f.IsEdgeField()))
		// The JSON key is the field's schema name, as in velox: the id of a
		// table whose key column is order_id is still "id".
		c.JSON = f.Name
		if id {
			c.GoName, c.Ptr, c.Null = "ID", false, false
		}
		for _, o := range e.Fields {
			if o.Col == c.Col {
				return fmt.Errorf("fields %q and %q are stored in the same column %q", o.F.Name, f.Name, c.Col)
			}
		}
		e.Fields = append(e.Fields, c)
		if id {
			e.ID = c
		}
		return nil
	}
	if err := add(t.ID, true); err != nil {
		return nil, err
	}
	for _, f := range t.Fields {
		if err := add(f, false); err != nil {
			return nil, err
		}
	}
	for _, fk := range t.UnexportedForeignKeys() {
		base, _, err := g.baseType(e, fk.Field)
		if err != nil {
			return nil, fmt.Errorf("foreign key %q: %w", fk.Field.Name, err)
		}
		e.Fields = append(e.Fields, &fld{F: fk.Field, GoName: hiddenName(fk.Field.Name), Col: fk.Field.Name, Base: base, Ptr: true, Hidden: true})
	}
	return e, nil
}

// packages gives every entity a package of its own. A name the generated
// tree or Go itself uses gets an "x" appended, and keeps getting one until no
// other entity has that package ("Model" next to "Modelx").
func (g *generator) packages() {
	// The root package is named after its directory; an entity package of the
	// same name could not be imported next to it without an alias.
	taken := func(name string) bool { return goKeywords[name] || name == rootPackage(g.cfg.Package) }
	used := map[string]bool{}
	for _, e := range g.ents {
		if !taken(e.Pkg) {
			used[e.Pkg] = true
		}
	}
	for _, e := range g.ents {
		if !taken(e.Pkg) {
			continue
		}
		for e.Pkg += "x"; used[e.Pkg]; {
			e.Pkg += "x"
		}
		used[e.Pkg] = true
	}
}

func (g *generator) edges(e *ent) error {
	for i, x := range e.T.Edges {
		t := g.by[x.Type.Name]
		if t == nil {
			return fmt.Errorf("edge %q: unknown target %s", x.Name, x.Type.Name)
		}
		e.Edges = append(e.Edges, &edg{E: x, GoName: x.StructField(), Target: t, Index: i})
	}
	// Members of the Edges struct: a field per edge and its OrErr method.
	members := map[string]bool{}
	for _, x := range e.Edges {
		for members[x.GoName] || members[x.GoName+"OrErr"] {
			x.GoName += "Edge"
		}
		members[x.GoName], members[x.GoName+"OrErr"] = true, true
	}
	// Members of the entity struct: Edges, a Query<Edge> method per edge,
	// and the fields, which give way to those and to each other.
	members = map[string]bool{"Edges": true}
	for _, x := range e.Edges {
		members["Query"+x.GoName] = true
	}
	for _, f := range e.Fields {
		if f.IsID {
			members[f.GoName] = true
		}
	}
	for _, f := range e.Fields {
		if f.IsID {
			continue
		}
		if members[f.GoName] {
			base := f.GoName
			if !f.Hidden {
				base += "Field"
			}
			if f.JSON == "edges" {
				f.JSON = "edges_field" // "edges" is the key of the loaded edges
			}
			f.GoName = base
			for i := 2; members[f.GoName]; i++ {
				f.GoName = fmt.Sprintf("%s%d", base, i)
			}
		}
		members[f.GoName] = true
	}
	return nil
}

// imports collects the imports of one generated file.
type imports struct {
	byPath map[string]string
	byName map[string]string
	// tree is the import path of the generated tree: its packages are
	// named like their directories.
	tree string
}

// imports starts the imports of a generated file.
func (g *generator) imports() *imports {
	return &imports{byPath: map[string]string{}, byName: map[string]string{}, tree: g.cfg.Package}
}

// importSpec is the line of an import declaration: the path alone where the
// package is known to be named like the last element of its path (the
// standard library, the library, the generated tree) and is imported under
// that name, as a person writes it; with the name otherwise. A package of the
// application (the type of a field, the schema) keeps the name: what its
// package clause says is not the generator's to assume.
func importSpec(name, path, tree string) string {
	plain := name == path[strings.LastIndex(path, "/")+1:] &&
		(!strings.Contains(strings.SplitN(path, "/", 2)[0], ".") ||
			path == veloxPath || strings.HasPrefix(path, veloxPath+"/") ||
			tree != "" && (path == tree || strings.HasPrefix(path, tree+"/")))
	if plain {
		return strconv.Quote(path)
	}
	return name + " " + strconv.Quote(path)
}

// use records an import and returns the name to qualify identifiers with.
func (im *imports) use(path, name string) string {
	if n, ok := im.byPath[path]; ok {
		return n
	}
	if name == "" {
		name = path[strings.LastIndex(path, "/")+1:]
	}
	n := name
	for i := 2; im.byName[n] != "" && im.byName[n] != path; i++ {
		n = fmt.Sprintf("%s%d", name, i)
	}
	im.byPath[path], im.byName[n] = n, path
	return n
}

func (im *imports) block() string {
	specs := make(map[string]string, len(im.byPath))
	for p, name := range im.byPath {
		specs[p] = importSpec(name, p, im.tree)
	}
	return importDecl(specs)
}

// importDecl writes an import declaration from the line of each path: the
// standard library first, then the rest, each sorted by path.
func importDecl(specs map[string]string) string {
	var std, rest []string
	for p := range specs {
		if strings.Contains(strings.SplitN(p, "/", 2)[0], ".") {
			rest = append(rest, p)
		} else {
			std = append(std, p)
		}
	}
	sort.Strings(std)
	sort.Strings(rest)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, p := range std {
		b.WriteString("\t" + specs[p] + "\n")
	}
	if len(std) > 0 && len(rest) > 0 {
		b.WriteString("\n")
	}
	for _, p := range rest {
		b.WriteString("\t" + specs[p] + "\n")
	}
	b.WriteString(")\n")
	return b.String()
}

// typeRef is a Go type as written in generated code, with the import it needs.
type typeRef struct {
	Expr    string // e.g. "time.Time", "[]types.Label"
	PkgPath string
	PkgName string
}

// goTypeOf returns the Go type of a field as velox's own generator computes
// it, without the pointer of a nillable field.
func goTypeOf(f *vgen.Field) (typeRef, error) {
	if f.Type == nil {
		return typeRef{Expr: "any"}, nil
	}
	clean := func(s string) string {
		s = strings.ReplaceAll(s, "interface {}", "any")
		return strings.ReplaceAll(s, "interface{}", "any")
	}
	if f.HasGoType() && f.Type.Ident != "" {
		return typeRef{Expr: clean(strings.TrimPrefix(f.Type.Ident, "*")), PkgPath: f.Type.PkgPath, PkgName: f.Type.PkgName}, nil
	}
	switch f.Type.Type {
	case field.TypeString, field.TypeEnum:
		return typeRef{Expr: "string"}, nil
	case field.TypeBool:
		return typeRef{Expr: "bool"}, nil
	case field.TypeTime:
		return typeRef{Expr: "time.Time", PkgPath: "time", PkgName: "time"}, nil
	case field.TypeUUID:
		return typeRef{Expr: "uuid.UUID", PkgPath: "github.com/google/uuid", PkgName: "uuid"}, nil
	case field.TypeBytes:
		return typeRef{Expr: "[]byte"}, nil
	case field.TypeJSON, field.TypeOther:
		if f.Type.Ident != "" {
			return typeRef{Expr: clean(f.Type.Ident), PkgPath: f.Type.PkgPath, PkgName: f.Type.PkgName}, nil
		}
		return typeRef{Expr: "any"}, nil
	}
	if f.Type.Type.Numeric() {
		return typeRef{Expr: f.Type.Type.String()}, nil
	}
	return typeRef{}, fmt.Errorf("unsupported field type %s", f.Type.Type)
}

var qualifier = regexp.MustCompile(`\b([A-Za-z_][A-Za-z0-9_]*)\.[A-Z]`)

// unknownPackage returns a package a type expression names that is neither
// the one the schema recorded for the field. A map keyed by a type of another package is such a type: the
// schema records the package of a type's elements, not of its keys.
func unknownPackage(ref typeRef) string {
	for _, m := range qualifier.FindAllStringSubmatch(ref.Expr, -1) {
		if m[1] != ref.PkgName {
			return m[1]
		}
	}
	return ""
}

// baseType resolves the Go type of a field for package entity. An enum
// without a Go type gets a generated type in the entity package; enum is
// non-empty for it and holds the name that package gives the type once
// enumNames has run.
func (g *generator) baseType(_ *ent, f *vgen.Field) (base, enum string, err error) {
	if f.IsEnum() && !f.HasGoType() {
		name := f.StructField() + "Enum"
		return name, name, nil
	}
	ref, err := goTypeOf(f)
	return ref.Expr, "", err
}

func formatted(src *bytes.Buffer, what string) ([]byte, error) {
	out, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("velox: generated %s does not parse: %w\n%s", what, err, numbered(src.String()))
	}
	return out, nil
}

func numbered(s string) string {
	var b strings.Builder
	for i, l := range strings.Split(s, "\n") {
		fmt.Fprintf(&b, "%4d  %s\n", i+1, l)
	}
	return b.String()
}

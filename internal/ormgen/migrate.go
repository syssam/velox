package ormgen

import (
	"bytes"
	"fmt"
	"regexp"

	vgen "github.com/syssam/velox/compiler/gen"
	vsql "github.com/syssam/velox/compiler/gen/sql"
)

// tableVarRx matches the line that declares the table of an entity or of a
// join.
var tableVarRx = regexp.MustCompile(`^var (\w+Table) = &schema\.Table\{\n$`)

// tableRx matches the line velox's migration generator starts the columns
// of a table with, which is where the table's declarations start.
var tableRx = regexp.MustCompile(`^// \w+ holds the columns for the "([^"]+)" table\.`)

// initChunk is how many statements an init function of the migrate package
// has at most.
const initChunk = 64

// arrangeTables rewrites what velox's migration generator wrote, which is one
// file, into what the migrate package is here. It works on the text, line by
// line, because that generator is the old one's and is not changed for this:
// what it relies on of the text is checked, and a table it does not
// recognize is an error and not a table left as it was.
//
//   - The declarations of a table go to the file of its entity (tableFile, by
//     table name), behind a file marker for split. What is no entity's stays
//     in schema.go: the tables that join two entities, the list of them all,
//     and what connects the foreign keys.
//
//   - A table is built by a function of its own. As a variable's initializer
//     its expression, which indexes the columns of this table and of the ones
//     its keys point at, is compiled into the one function that initializes
//     the package's variables, and the compiler is quadratic in the size of a
//     function: the package took 1.4 CPU-s for 450 entities and 45 for 2,000.
//
//   - What connects the foreign keys is one statement per key in one init
//     function, 2,900 statements for 2,000 entities. It is cut into functions
//     of initChunk statements, for the same reason; a package may have any
//     number of init functions, and they run in order.
func arrangeTables(src []byte, tableFile map[string]string) ([]byte, error) {
	var out bytes.Buffer
	inInit, depth, stmts := false, 0, 0
	inTable := false
	declared, built := 0, 0
	for _, line := range bytes.SplitAfter(src, []byte("\n")) {
		if m := tableVarRx.FindSubmatch(line); m != nil {
			fmt.Fprintf(&out, "var %[1]s = new%[1]s()\n\nfunc new%[1]s() *schema.Table {\n\treturn &schema.Table{\n", m[1])
			inTable = true
			built++
			continue
		}
		if inTable && bytes.HasPrefix(line, []byte("}")) {
			out.WriteString("}\n}\n")
			inTable = false
			continue
		}
		switch {
		case tableRx.Match(line):
			// Empty for a table of no entity: back to schema.go.
			fmt.Fprintf(&out, "%s%s\n", fileMarker, tableFile[string(tableRx.FindSubmatch(line)[1])])
			declared++
		case bytes.HasPrefix(line, []byte("// Tables holds ")):
			fmt.Fprintf(&out, "%s\n", fileMarker)
		case bytes.HasPrefix(line, []byte("func init()")):
			fmt.Fprintf(&out, "%s\n", fileMarker)
			inInit, depth, stmts = true, 0, 0
			out.Write(line)
			continue
		}
		if inInit {
			if depth == 0 && bytes.HasPrefix(line, []byte("}")) {
				inInit = false
			} else {
				if depth == 0 && stmts == initChunk {
					out.WriteString("}\n\nfunc init() {\n")
					stmts = 0
				}
				depth += bytes.Count(line, []byte("{")) - bytes.Count(line, []byte("}"))
				if depth == 0 {
					stmts++
				}
			}
		}
		out.Write(line)
	}
	if declared != built || declared < len(tableFile) {
		return nil, fmt.Errorf("the migration generator's output was not recognized: %d tables announced, %d declared, %d entities", declared, built, len(tableFile))
	}
	return out.Bytes(), nil
}

// migrate generates the migrate package: the tables of the schema and the
// functions that create them.
//
// The table definitions are rendered by velox's own migration generator, not
// by a second one written here: a database that velox migrated must be seen
// as up to date, column for column and constraint name for constraint name,
// and two generators of the same DDL drift (velox's two did, on the action
// and on the name of a foreign key).
func (g *Generator) migrate(graph *vgen.Graph, files map[string][]byte) error {
	out, err := vsql.NewDialect(vgen.NewJenniferGenerator(graph, g.cfg.Target)).GenMigrate()
	if err != nil {
		return fmt.Errorf("velox: migrate: %w", err)
	}
	if out.Schema == nil {
		return nil
	}
	src, err := vgen.FormatJenFile(out.Schema, "migrate/schema.go")
	if err != nil {
		return fmt.Errorf("velox: migrate: %w", err)
	}
	// One header, this generator's: prune recognizes its files by it.
	src = bytes.TrimPrefix(src, []byte("// Code generated by velox. DO NOT EDIT.\n"))
	src = bytes.TrimPrefix(src, []byte("// Code generated by velox. DO NOT EDIT.\n"))
	src = append([]byte(header), bytes.TrimLeft(src, "\n")...)
	// The table of each entity goes to a file of its own, as everything else
	// of an entity does: in one file the tables of a 455-entity schema were
	// 2.6 MB and 89,000 lines, which an editor does not highlight and takes
	// seconds to outline (see split). What is no entity's stays in
	// schema.go: the tables that join two entities, the list of them all,
	// and what connects the foreign keys.
	tableFile := map[string]string{}
	for _, e := range g.ents {
		tableFile[e.T.Table()] = fileName(e)
	}
	marked, err := arrangeTables(src, tableFile)
	if err != nil {
		return fmt.Errorf("velox: migrate: %w", err)
	}
	parts, err := split(marked, "schema")
	if err != nil {
		return fmt.Errorf("velox: migrate: %w", err)
	}
	for name, part := range parts {
		// The file of an entity called Migrate is the package's own.
		if name == "migrate.go" {
			name = "migrate_table.go"
		}
		files["migrate/"+name] = part
	}

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString(`// Package migrate creates and updates the tables of the schema.
//
//	if err := migrate.Create(ctx, conn); err != nil { ... }
//
// Create compares the tables in the database with Tables and applies the
// difference; it adds and never drops unless asked to (WithDropColumn,
// WithDropIndex). WriteTo prints the statements instead of running them, to
// review them or to keep them as a migration file.
package migrate

import (
	"context"
	"fmt"
	"io"

	"` + veloxPath + `"
	"github.com/syssam/velox/dialect/sql/schema"
)

var (
	// WithDropColumn lets the migration drop columns the schema no longer has.
	WithDropColumn = schema.WithDropColumn
	// WithDropIndex lets the migration drop indexes the schema no longer has.
	WithDropIndex = schema.WithDropIndex
	// WithForeignKeys says whether foreign keys are created (the default).
	WithForeignKeys = schema.WithForeignKeys
	// WithGlobalUniqueID gives every table its own range of ids.
	WithGlobalUniqueID = schema.WithGlobalUniqueID
)

// Create brings the tables of db up to date with the schema.
func Create(ctx context.Context, db *velox.DB, opts ...schema.MigrateOption) error {
	m, err := schema.NewMigrate(db.Driver(), opts...)
	if err != nil {
		return fmt.Errorf("migrate: %w", err)
	}
	return m.Create(ctx, Tables...)
}

// WriteTo writes the statements Create would run to w, and runs none.
func WriteTo(ctx context.Context, db *velox.DB, w io.Writer, opts ...schema.MigrateOption) error {
	m, err := schema.NewMigrate(&schema.WriteDriver{Driver: db.Driver(), Writer: w}, opts...)
	if err != nil {
		return fmt.Errorf("migrate: %w", err)
	}
	return m.Create(ctx, Tables...)
}
`)
	files["migrate/migrate.go"] = b.Bytes()
	return nil
}

// testing generates package veloxtest: a database for a test in one call,
// with the tables of the schema, closed when the test ends. Every test of an
// application otherwise starts with the same five lines, and the copy that
// forgets to close, or to fail the test when the tables cannot be created,
// is found late. (Ent generates enttest for the same reason.)
//
// It is a package of its own so that only tests link the migrate package.
func (g *Generator) testing() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(header)
	fmt.Fprintf(&out, `// Package veloxtest opens a database for a test.
package veloxtest

import (
	"context"
	"testing"

	"github.com/syssam/velox"
	"github.com/syssam/velox/dialect/sql/schema"

	"%[1]s/migrate"
)

// Open opens a database for the test, creates the tables of the schema in it,
// and closes it when the test and its subtests end. A failure of either is
// the test's: it stops there.
//
//	db := veloxtest.Open(t, "sqlite", "file:orders?mode=memory&cache=shared&_pragma=foreign_keys(1)")
//
// The driver of the dialect is the test's to import, as for velox.Open. A
// test that must not share rows with another gives each a data source name
// of its own.
func Open(t testing.TB, dialectName, dsn string, opts ...schema.MigrateOption) *velox.DB {
	t.Helper()
	db, err := velox.Open(dialectName, dsn)
	if err != nil {
		t.Fatalf("veloxtest: opening the database: %%v", err)
	}
	t.Cleanup(func() { _ = db.Close() })
	if err := migrate.Create(context.Background(), db, opts...); err != nil {
		t.Fatalf("veloxtest: creating the tables: %%v", err)
	}
	return db
}
`, g.cfg.Package)
	return formatted(&out, "veloxtest")
}

// Package genrun is velox-gen's generate: it loads a schema package, builds
// the generated package and the plugins' files, and writes them, all or
// nothing. Package generate is its public face, and cmd/velox-gen's verify,
// describe and migrate use its loader and its writer.
package genrun

import (
	"bufio"
	"bytes"
	"cmp"
	"context"
	"errors"
	"fmt"
	"go/token"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"

	"github.com/syssam/velox/internal/codegen"
)

// DefaultSchema is the schema package when none is named.
const DefaultSchema = "./veloxschema"

// DefaultOut is the output directory when none is named.
const DefaultOut = "./veloxgen"

// Header is the first line of every file velox-gen writes. velox-gen deletes
// a file that starts with it when no entity produces that file any more, and
// never overwrites a file that does not.
const Header = "// Code generated by velox-gen. DO NOT EDIT."

// graphqlHeader is the header of a .graphql file, whose comments start
// with #.
const graphqlHeader = "# Code generated by velox-gen. DO NOT EDIT."

// ErrStale is the error of a check that finds a generated file out of date,
// missing or left over.
var ErrStale = errors.New("generated files are out of date")

// ErrInterrupted is the error of a run that SIGINT or SIGTERM reached while
// it wrote.
var ErrInterrupted = errors.New("interrupted")

// headerFor is the header line a file at path starts with, by its extension;
// "" for an extension velox-gen does not write.
func headerFor(path string) string {
	switch filepath.Ext(path) {
	case ".go", ".proto":
		return Header
	case ".graphql":
		return graphqlHeader
	}
	return ""
}

// IsGenerated reports whether the file at path starts with the header of its
// kind.
func IsGenerated(path string) bool {
	h := headerFor(path)
	if h == "" {
		return false
	}
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	line, _ := bufio.NewReader(f).ReadString('\n')
	return line == h+"\n"
}

// SchemaPackage is the schema package the command works on: the one pattern
// named, or DefaultSchema when none is; the caller refuses more than one, as
// a usage error. The package must declare schemas; an error is a package that
// cannot be read, as go list says it, or one that declares none.
func SchemaPackage(dir string, patterns, env []string) (string, error) {
	pattern := DefaultSchema
	if len(patterns) == 1 {
		pattern = patterns[0]
	}
	importPath, _, schemas, err := codegen.Inspect(dir, pattern, env)
	if err != nil {
		return "", RelErrors(dir, err)
	}
	if len(schemas) == 0 {
		return "", codegen.NoSchemas(importPath)
	}
	return pattern, nil
}

// OutDir is the absolute path of the output directory out, relative to dir
// unless it is absolute. It is absolute so that go list reads it as a
// directory: a relative "gen" would be an import path. Symlinks in dir are
// resolved, as RelPath does, so that paths print relative.
func OutDir(dir, out string) string {
	if filepath.IsAbs(out) {
		return filepath.Clean(out)
	}
	abs, err := filepath.Abs(dir)
	if err != nil {
		abs = dir
	} else if r, err := filepath.EvalSymlinks(abs); err == nil {
		abs = r
	}
	return filepath.Join(abs, out)
}

// PackageName is pkg, or the base name of out, the absolute output
// directory, when pkg is "". It must be an identifier.
func PackageName(out, pkg string) (string, error) {
	name := pkg
	if name == "" {
		name = filepath.Base(out)
	}
	if !token.IsIdentifier(name) {
		return "", fmt.Errorf("%q is not a package name; name it with -package", name)
	}
	return name, nil
}

// Model is the generator's view of a schema package: what Lower made of its
// graph, and the names of every generated entity, join entities included.
type Model struct {
	Graph      *codegen.Graph
	Out        *codegen.Out // what Lower made of Graph, for the plugins' model
	ImportPath string
	Name       string   // the schema package's name
	Names      []string // every generated entity's name
	Rels       []string // every relation's handle, e.g. "Users.Posts", join entities included
}

// ExplainLoad is err, the failure to read the schema package at pattern,
// or the reason velox-gen finds for it. A schema package that reaches the
// generated package at out makes an import cycle once that package imports
// the schema, which go list reports with no chain: the reason names the
// chain. A behaviour method of a shape velox-gen does not bind, such as an
// older velox's typed one, may not compile: when schemas, the schemas'
// names, are known, the reason names the shape velox-gen binds.
func ExplainLoad(dir, pattern, out string, env []string, err error, schemas []string) error {
	genPath, perr := DirImportPath(out, env)
	if perr != nil {
		return err
	}
	var cerr error
	switch {
	case schemas != nil:
		_, cerr = codegen.Behaviour(dir, pattern, genPath, env, schemas)
	case strings.Contains(err.Error(), "import cycle not allowed"):
		// go list's words for the cycle: another failure to list the
		// package, such as a file only some builds include, is its own.
		cerr = codegen.CheckGenImports(dir, pattern, genPath, env)
	}
	if cerr != nil {
		return RelErrors(dir, cerr)
	}
	return err
}

// FieldOrder gives an entity's declared fields their order; see
// Config.FieldOrder.
type FieldOrder func(entity string, fields []string) []string

// LoadModel loads and builds the schema package at pattern, puts each
// entity's fields in the order order gives (when it is not nil), and lowers
// the graph to the names of its generated entities.
func LoadModel(dir, pattern, out, pkg string, env []string, order FieldOrder) (*Model, error) {
	importPath, name, schemas, err := codegen.Inspect(dir, pattern, env)
	if err != nil {
		return nil, ExplainLoad(dir, pattern, out, env, RelErrors(dir, err), nil)
	}
	m, err := codegen.Load(dir, pattern, env)
	if err != nil {
		return nil, ExplainLoad(dir, pattern, out, env, RelErrors(dir, err), schemas)
	}
	g, err := codegen.Build(m)
	if err != nil {
		return nil, RelErrors(dir, err)
	}
	if order != nil {
		if err := orderFields(g, order); err != nil {
			return nil, err
		}
	}
	o, err := codegen.Lower(g, codegen.Config{Package: pkg, SchemaPath: importPath, SchemaName: name})
	if err != nil {
		return nil, err
	}
	gm := &Model{Graph: g, Out: o, ImportPath: importPath, Name: name}
	for _, e := range o.Entities {
		gm.Names = append(gm.Names, e.Name)
		for _, r := range e.Rels {
			gm.Rels = append(gm.Rels, e.Handles+"."+r.GoName)
		}
	}
	return gm, nil
}

// orderFields puts the declared fields of each entity of g in the order
// order gives them: every field but the ID, Fields[0], and the foreign keys
// velox adds for edges, which keep their places. order must return a
// permutation of the names it is given; anything else is an error that
// names the entity.
func orderFields(g *codegen.Graph, order FieldOrder) error {
	for _, e := range g.Entities {
		byName := map[string]*codegen.Field{}
		var names []string
		var implicit []*codegen.Field
		for _, f := range e.Fields[1:] {
			if f.Implicit != "" {
				implicit = append(implicit, f)
				continue
			}
			byName[f.Name] = f
			names = append(names, f.Name)
		}
		got := order(e.Name, slices.Clone(names))
		if err := checkPermutation(names, got); err != nil {
			return fmt.Errorf("FieldOrder of schema %s: %w", e.Name, err)
		}
		fields := make([]*codegen.Field, 0, len(e.Fields))
		fields = append(fields, e.Fields[0])
		for _, n := range got {
			fields = append(fields, byName[n])
		}
		e.Fields = append(fields, implicit...)
	}
	return nil
}

// checkPermutation reports how got is not a permutation of want: a name
// it repeats, one that want lacks, or one it leaves out.
func checkPermutation(want, got []string) error {
	left := make(map[string]bool, len(want))
	for _, n := range want {
		left[n] = true
	}
	seen := make(map[string]bool, len(got))
	for _, n := range got {
		switch {
		case seen[n]:
			return fmt.Errorf("field %q is returned twice", n)
		case !left[n]:
			return fmt.Errorf("field %q is not a declared field of the schema", n)
		}
		seen[n] = true
	}
	for _, n := range want {
		if !seen[n] {
			return fmt.Errorf("field %q is left out", n)
		}
	}
	return nil
}

// Log is where a run reports: the lines it prints to Stderr, as velox-gen
// prints them, and the warnings among them.
type Log struct {
	Stderr   io.Writer
	Warnings []string // each warning's text, a plugin's as "plugin <name>: <text>"
}

// warn prints the warning text and keeps it.
func (l *Log) warn(text string) {
	_, _ = fmt.Fprintf(l.Stderr, "velox-gen: warning: %s\n", text)
	l.Warnings = append(l.Warnings, text)
}

// pluginWarn prints the plugin name's warning text and keeps it.
func (l *Log) pluginWarn(name, text string) {
	_, _ = fmt.Fprintf(l.Stderr, "velox-gen: plugin %s: warning: %s\n", name, text)
	l.Warnings = append(l.Warnings, "plugin "+name+": "+text)
}

// genConfig is the codegen.Config of the package at out, named pkg, for the
// schema package at pattern: the import path of out, the Hooks and Policy
// methods the schema package declares (codegen.Behaviour), the behaviour of
// the entities' mixins (codegen.MixinBehaviour), and the relations that
// behaviour names (codegen.CheckBehaviour), whose warnings go to log
// with codegen.SoftDeleteWarnings' and codegen.DefaultWarnings'.
// UserDoc is left for the caller.
func genConfig(gm *Model, dir, pattern, out, pkg string, env []string, log *Log) (codegen.Config, error) {
	cfg := codegen.Config{Package: pkg, SchemaPath: gm.ImportPath, SchemaName: gm.Name}
	genPath, err := DirImportPath(out, env)
	if err != nil {
		return cfg, err
	}
	bound, err := codegen.Behaviour(dir, pattern, genPath, env, gm.Names)
	if err != nil {
		return cfg, err
	}
	cfg.GenPath = genPath
	cfg.Bound = bound
	mixins, err := codegen.MixinBehaviour(dir, pattern, gm.Graph, env)
	if err != nil {
		return cfg, RelErrors(dir, err)
	}
	cfg.Mixins = mixins
	warnings, err := codegen.CheckBehaviour(dir, pattern, gm.Graph, bound, mixins, env)
	warnings = append(warnings, codegen.SoftDeleteWarnings(gm.Graph)...)
	warnings = append(warnings, codegen.DefaultWarnings(gm.Graph)...)
	for _, w := range warnings {
		log.warn(RelWarning(dir, w))
	}
	if err != nil {
		return cfg, RelErrors(dir, err)
	}
	if cfg.Funcs, err = codegen.FuncPackages(dir, gm.Graph, cfg, env); err != nil {
		return cfg, err
	}
	return cfg, nil
}

// Output is what one run of velox-gen writes below out.
type Output struct {
	GenPath string            // the generated package's import path
	Want    map[string][]byte // every file, velox-gen's and the plugins', by absolute path
	Plugin  map[string][]byte // the plugins' files, by absolute path
	Owners  map[string]string // the plugin that wrote each of Plugin
}

// BuildOutput generates the files of the package at out, named pkg, for the
// schema package at pattern, and runs the plugins on the model. The files of
// the user's in out are checked against what velox-gen writes. Nothing is
// written.
func BuildOutput(ctx context.Context, plugins []Plugin, gm *Model, pattern, dir, out, pkg string, env []string, log *Log) (*Output, error) {
	cfg, err := genConfig(gm, dir, pattern, out, pkg, env, log)
	if err != nil {
		return nil, err
	}
	if err := codegen.CheckUserFiles(out, gm.Names); err != nil {
		return nil, err
	}
	if cfg.UserDoc, err = codegen.HasPackageDoc(out); err != nil {
		return nil, err
	}
	files, err := codegen.Generate(gm.Graph, cfg)
	if err != nil {
		return nil, RelErrors(dir, err)
	}
	o := &Output{GenPath: cfg.GenPath, Want: make(map[string][]byte, len(files))}
	for _, file := range files {
		o.Want[filepath.Join(out, filepath.FromSlash(file.Name))] = file.Data
	}
	// The plugins run after velox-gen's own files are built and before
	// anything is written.
	o.Plugin, o.Owners, err = pluginFiles(ctx, plugins, gm, pattern, dir, out, pkg, cfg.GenPath, env, log)
	if err != nil {
		return nil, err
	}
	if err := mergePluginFiles(dir, out, o.Want, o.Plugin, o.Owners); err != nil {
		return nil, err
	}
	return o, nil
}

// Config is one run of Run; package generate's Config documents it.
type Config struct {
	Schema, Out, Package string
	Plugins              []Plugin
	Check                bool
	Env                  []string
	FieldOrder           FieldOrder
	Stdout, Stderr       io.Writer
}

// Result is what Run did, each path relative to the working directory when
// it is inside it.
type Result struct {
	Written, Removed, Stale, Warnings []string
}

// Run generates the package c.Out of the schema package c.Schema, both
// relative to dir, and writes it, or with c.Check, reports what is stale.
// It prints each path it writes or removes to c.Stdout, and the rest to
// c.Stderr, as velox-gen does. A check that finds a stale file returns
// ErrStale; a signal while it writes returns ErrInterrupted, joined with the
// write's own error.
func Run(ctx context.Context, dir string, c Config) (Result, error) {
	dir = cmp.Or(dir, ".")
	stdout, stderr := c.Stdout, c.Stderr
	if stdout == nil {
		stdout = io.Discard
	}
	if stderr == nil {
		stderr = os.Stderr
	}
	log := &Log{Stderr: stderr}
	var res Result
	done := func(err error) (Result, error) {
		res.Warnings = log.Warnings
		return res, err
	}
	pattern := cmp.Or(c.Schema, DefaultSchema)
	out := OutDir(dir, cmp.Or(c.Out, DefaultOut))
	if err := ctx.Err(); err != nil {
		return done(err)
	}
	if _, err := SchemaPackage(dir, []string{pattern}, c.Env); err != nil {
		return done(ExplainLoad(dir, pattern, out, c.Env, err, nil))
	}
	pkg, err := PackageName(out, c.Package)
	if err != nil {
		return done(err)
	}
	gm, err := LoadModel(dir, pattern, out, pkg, c.Env, c.FieldOrder)
	if err != nil {
		return done(err)
	}
	o, err := BuildOutput(ctx, c.Plugins, gm, pattern, dir, out, pkg, c.Env, log)
	if err != nil {
		return done(relFileError(dir, err))
	}
	want, owners := o.Want, o.Owners
	warnOldDirs(dir, out, pkg, log)
	if err := checkWantPaths(dir, out, want); err != nil {
		return done(err)
	}
	sw, err := staleFiles(out, want, owners, !c.Check)
	reportSwept(dir, sw.swept, stderr)
	if err != nil {
		return done(err)
	}
	stale, remove := sw.write, sw.remove
	changed := append(slices.Clone(stale), remove...)
	slices.Sort(changed)
	if c.Check {
		res.Stale = reportCheck(dir, changed, sw.leftovers, stderr)
		if len(res.Stale) > 0 {
			return done(ErrStale)
		}
		return done(nil)
	}
	if err := ctx.Err(); err != nil {
		return done(err)
	}
	// WriteAll sets the removals aside before it writes: on a
	// case-insensitive file system a file or directory whose name changed
	// only in case is the old one, which goes first. The emptied directories
	// go with the files they held.
	rel := func(p string) string {
		r, _ := filepath.Rel(out, p)
		return filepath.ToSlash(r)
	}
	write := make(map[string][]byte, len(stale))
	for _, p := range stale {
		write[rel(p)] = want[p]
	}
	var gone []string
	for _, p := range slices.Concat(remove, sw.emptied) {
		gone = append(gone, rel(p))
	}
	// A signal waits for the write to finish or be undone.
	interrupted, err := WriteAllHeld(out, write, gone)
	if err == nil {
		removed := make(map[string]bool, len(remove))
		for _, p := range remove {
			removed[p] = true
		}
		for _, p := range changed {
			_, _ = fmt.Fprintln(stdout, RelPath(dir, p))
			if removed[p] {
				res.Removed = append(res.Removed, RelPath(dir, p))
			} else {
				res.Written = append(res.Written, RelPath(dir, p))
			}
		}
	}
	if interrupted {
		if err != nil {
			return done(errors.Join(err, ErrInterrupted))
		}
		return done(ErrInterrupted)
	}
	return done(err)
}

// relFileError shows the paths of err relative to dir: each of joined
// errors (RelErrors), or a *codegen.FileError's, which names a user's file.
func relFileError(dir string, err error) error {
	if _, ok := err.(interface{ Unwrap() []error }); ok {
		return RelErrors(dir, err)
	}
	if fe, ok := errors.AsType[*codegen.FileError](err); ok {
		c := *fe
		c.Path = RelPath(dir, fe.Path)
		return &c
	}
	return err
}

// ModuleDir is the directory of the module that holds the package at pattern.
func ModuleDir(dir, pattern string, env []string) (string, error) {
	cmd := exec.Command("go", "list", "-f", "{{.Module.Dir}}", pattern)
	cmd.Dir = dir
	if env != nil {
		cmd.Env = env
	}
	var so, se bytes.Buffer
	cmd.Stdout, cmd.Stderr = &so, &se
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("go list %s: %w\n%s", pattern, err, strings.TrimRight(se.String(), "\n"))
	}
	mod := strings.TrimSpace(so.String())
	if mod == "" {
		return "", fmt.Errorf("%s is not in a module", pattern)
	}
	return mod, nil
}

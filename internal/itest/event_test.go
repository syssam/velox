package itest

import (
	"testing"
	"time"

	"github.com/syssam/velox2"
	"github.com/syssam/velox2/internal/testmodel"
)

// eventDDL is the table of testmodel.Event: two time columns, the second
// NULL-able.
func eventDDL(d velox.Dialect) string {
	switch d {
	case velox.Postgres:
		return "CREATE TABLE events (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at timestamptz NOT NULL, maybe_at timestamptz)"
	case velox.MySQL:
		return "CREATE TABLE events (id BIGINT AUTO_INCREMENT PRIMARY KEY, at DATETIME(6) NOT NULL, maybe_at DATETIME(6) NULL)"
	}
	return "CREATE TABLE events (id INTEGER PRIMARY KEY, at DATETIME NOT NULL, maybe_at DATETIME)"
}

// A time field whose GoType is defined on time.Time gets its Default from a
// func() time.Time, which the generated code converts: as a value, and as a
// Nillable pointer. Both are written and read back on every dialect.
func TestConvertedTimeDefault(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		tg.exec(t, "DROP TABLE IF EXISTS events")
		tg.exec(t, eventDDL(tg.d))
		t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS events") })
		before := time.Now().Add(-time.Minute)
		e := testmodel.Event{}
		if err := tg.db.Insert(&e).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		recent := func(m testmodel.Moment) bool {
			at := time.Time(m)
			return at.After(before) && at.Before(time.Now().Add(time.Minute))
		}
		if !recent(e.At) || e.MaybeAt == nil || !recent(*e.MaybeAt) {
			t.Fatalf("the defaults were not filled: %+v", e)
		}
		got, err := tg.db.Query[testmodel.Event]().Where(testmodel.Events.ID.EQ(e.ID)).One(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if !recent(got.At) || got.MaybeAt == nil || !recent(*got.MaybeAt) {
			t.Fatalf("read back: %+v", got)
		}
		// A value given is kept.
		given := testmodel.Moment(t0)
		g := testmodel.Event{At: given, MaybeAt: &given}
		if err := tg.db.Insert(&g).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		back, err := tg.db.Query[testmodel.Event]().Where(testmodel.Events.ID.EQ(g.ID)).One(ctx)
		if err != nil || !time.Time(back.At).Equal(t0) || back.MaybeAt == nil || !time.Time(*back.MaybeAt).Equal(t0) {
			t.Fatalf("given: %+v, %v", back, err)
		}
	})
}

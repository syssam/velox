// keysDDL is the tables of Paper, Topic, Remark and their join, as velox-gen
// migrate sql writes them: a UUID key, a string key, and an int64 key with a
// UUID foreign key.
func keysDDL(d velox.Dialect) []string {
	switch d {
	case velox.Postgres:
		return []string{
			`CREATE TABLE papers (id uuid PRIMARY KEY, title text NOT NULL, version bigint NOT NULL)`,
			`CREATE TABLE topics (id varchar(36) PRIMARY KEY, name text NOT NULL)`,
			`CREATE TABLE remarks (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, paper_id uuid NOT NULL REFERENCES papers (id), body text NOT NULL)`,
			`CREATE TABLE paper_topics (paper_id uuid NOT NULL REFERENCES papers (id) ON DELETE CASCADE,
				topic_id varchar(36) NOT NULL REFERENCES topics (id) ON DELETE CASCADE, PRIMARY KEY (paper_id, topic_id))`,
		}
	case velox.MySQL:
		return []string{
			"CREATE TABLE papers (id CHAR(36) PRIMARY KEY, title VARCHAR(255) NOT NULL, version BIGINT NOT NULL) COLLATE=utf8mb4_bin",
			"CREATE TABLE topics (id VARCHAR(36) PRIMARY KEY, name VARCHAR(255) NOT NULL) COLLATE=utf8mb4_bin",
			"CREATE TABLE remarks (id BIGINT AUTO_INCREMENT PRIMARY KEY, paper_id CHAR(36) NOT NULL, body VARCHAR(255) NOT NULL, " +
				"FOREIGN KEY (paper_id) REFERENCES papers (id)) COLLATE=utf8mb4_bin",
			"CREATE TABLE paper_topics (paper_id CHAR(36) NOT NULL, topic_id VARCHAR(36) NOT NULL, PRIMARY KEY (paper_id, topic_id), " +
				"FOREIGN KEY (paper_id) REFERENCES papers (id) ON DELETE CASCADE, FOREIGN KEY (topic_id) REFERENCES topics (id) ON DELETE CASCADE) COLLATE=utf8mb4_bin",
		}
	}
	return []string{
		`CREATE TABLE papers (id TEXT PRIMARY KEY, title TEXT NOT NULL, version INTEGER NOT NULL)`,
		`CREATE TABLE topics (id TEXT PRIMARY KEY, name TEXT NOT NULL)`,
		`CREATE TABLE remarks (id INTEGER PRIMARY KEY AUTOINCREMENT, paper_id TEXT NOT NULL REFERENCES papers (id), body TEXT NOT NULL)`,
		`CREATE TABLE paper_topics (paper_id TEXT NOT NULL REFERENCES papers (id) ON DELETE CASCADE,
			topic_id TEXT NOT NULL REFERENCES topics (id) ON DELETE CASCADE, PRIMARY KEY (paper_id, topic_id))`,
	}
}

// keysTables makes keysDDL's tables, dropped again after the test.
func keysTables(t *testing.T, tg target) {
	t.Helper()
	drop := func() {
		for _, tbl := range []string{"paper_topics", "remarks", "topics", "papers"} {
			tg.exec(t, "DROP TABLE IF EXISTS "+tbl)
		}
	}
	drop()
	for _, s := range keysDDL(tg.d) {
		tg.exec(t, s)
	}
	t.Cleanup(drop)
}

func topicIDs(ts []*testmodel.Topic) []string {
	out := make([]string, len(ts))
	for i := range ts {
		out[i] = ts[i].ID
	}
	slices.Sort(out)
	return out
}

// TestNonIntegerKeys: an entity keyed by a UUID, one keyed by a string the
// application chooses, an int64-keyed entity holding a UUID foreign key, and
// a many-to-many join of UUID and string keys: inserts with and without the
// key, edge links, With in both directions, Of, HasWith, Save, an upsert on
// the key, paging After a UUID key, and a delete that cascades the join.
func TestNonIntegerKeys(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		keysTables(t, tg)
		db := tg.db
		for _, tp := range []testmodel.Topic{{ID: "go", Name: "Go"}, {ID: "db", Name: "Databases"}, {ID: "ops", Name: "Operations"}} {
			if err := db.Insert(&tp).Exec(ctx); err != nil {
				t.Fatal(err)
			}
		}
		given := bindtype.UUID{0x12, 0x3e, 0x45, 0x67, 0xe8, 0x9b, 0x42, 0xd3, 0xa4, 0x56, 0x42, 0x66, 0x14, 0x17, 0x40, 0x00}
		a := testmodel.Paper{ID: given, Title: "A"}
		if err := db.Insert(&a).Set(P.Topics.Add("go", "db")).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		b := testmodel.Paper{Title: "B"} // the key is the default's
		if err := db.Insert(&b).Set(P.Topics.Add("db")).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if b.ID == (bindtype.UUID{}) || b.ID == given {
			t.Fatalf("the default key: %v", b.ID)
		}
		for _, r := range []testmodel.Remark{{PaperID: a.ID, Body: "a1"}, {PaperID: a.ID, Body: "a2"}, {PaperID: b.ID, Body: "b1"}} {
			if err := db.Insert(&r).Exec(ctx); err != nil {
				t.Fatal(err)
			}
			if r.ID == 0 {
				t.Fatal("a remark's int64 key was not read back")
			}
		}

		got, err := db.Query[testmodel.Paper]().Where(P.ID.EQ(given)).With(P.Topics).With(P.Remarks).Limit(2).All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if len(got) != 1 || got[0].ID != given || got[0].Title != "A" {
			t.Fatalf("paper by its UUID: %+v", got)
		}
		tps, _ := got[0].Edges.Topics.Get()
		if ids := topicIDs(tps); !slices.Equal(ids, []string{"db", "go"}) {
			t.Errorf("A's topics %v", ids)
		}
		if rms, ok := got[0].Edges.Remarks.Get(); !ok || len(rms) != 2 {
			t.Errorf("A has %d remarks (loaded %v), want 2", len(rms), ok)
		}

		// The inverse, from string keys to UUID keys, and a to-one by a UUID.
		db1, err := db.Query[testmodel.Topic]().Where(Tp.ID.EQ("db")).With(Tp.Papers).Limit(1).All(ctx)
		if err != nil || len(db1) != 1 {
			t.Fatalf("topic db: %+v, %v", db1, err)
		}
		if ps, _ := db1[0].Edges.Papers.Get(); len(ps) != 2 {
			t.Errorf("topic db has %d papers, want 2", len(ps))
		}
		rs, err := db.Query[testmodel.Remark]().Where(Rm.Body.EQ("b1")).With(Rm.Paper).Limit(1).All(ctx)
		if err != nil || len(rs) != 1 {
			t.Fatalf("remark b1: %+v, %v", rs, err)
		}
		if p, ok := rs[0].Edges.Paper.Get(); !ok || p == nil || p.ID != b.ID {
			t.Errorf("remark b1's paper: %+v", p)
		}

		// Of and HasWith across the join.
		of, err := db.Query[testmodel.Topic]().Where(P.Topics.Of(&a, &b)).OrderBy(Tp.ID.Asc()).Limit(10).All(ctx)
		if err != nil || !slices.Equal(topicIDs(of), []string{"db", "go"}) {
			t.Errorf("topics of A and B: %v, %v", topicIDs(of), err)
		}
		withGo, err := db.Query[testmodel.Paper]().Where(P.Topics.HasWith(Tp.ID.EQ("go"))).Limit(10).All(ctx)
		if err != nil || len(withGo) != 1 || withGo[0].ID != given {
			t.Errorf("papers with topic go: %+v, %v", withGo, err)
		}

		// Save by a UUID key; an upsert on a string key.
		a.Title = "A2"
		if err := db.Save(&a, P.Title).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		up := testmodel.Topic{ID: "go", Name: "Golang"}
		if err := db.Insert(&up).OnConflict(Tp.ID).Update(Tp.Name).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		g, err := db.Query[testmodel.Topic]().Where(Tp.ID.EQ("go")).Limit(1).All(ctx)
		if err != nil || len(g) != 1 || g[0].Name != "Golang" {
			t.Errorf("the upserted topic: %+v, %v", g, err)
		}

		// Paging after a UUID key.
		all, err := db.Query[testmodel.Paper]().OrderBy(P.ID.Asc()).Limit(10).All(ctx)
		if err != nil || len(all) != 2 {
			t.Fatalf("papers: %+v, %v", all, err)
		}
		next, err := db.Query[testmodel.Paper]().OrderBy(P.ID.Asc()).After(all[0]).Limit(10).All(ctx)
		if err != nil || len(next) != 1 || next[0].ID != all[1].ID {
			t.Errorf("after the first paper: %+v, %v", next, err)
		}

		// Unlinking, then a delete that cascades the join.
		if _, err := db.Update[testmodel.Paper]().Set(P.Topics.Remove("go")).Where(P.ID.EQ(given)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if _, err := db.Delete[testmodel.Remark]().Where(Rm.PaperID.EQ(b.ID)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if n, err := db.Delete[testmodel.Paper]().Where(P.ID.EQ(b.ID)).Exec(ctx); err != nil || n != 1 {
			t.Fatalf("delete B: %d, %v", n, err)
		}
		left, err := db.Query[testmodel.Topic]().Where(P.Topics.Of(&a)).Limit(10).All(ctx)
		if err != nil || !slices.Equal(topicIDs(left), []string{"db"}) {
			t.Errorf("A's topics after Remove: %v, %v", topicIDs(left), err)
		}
		if n, err := db.Query[testmodel.Paper]().Where(P.Topics.HasWith(Tp.ID.EQ("db"))).Count(ctx); err != nil || n != 1 {
			t.Errorf("papers with topic db after B's delete: %d, %v", n, err)
		}
	})
}

// TestIDsOfNonIntegerKeys: IDs reads a UUID key and a string key as their
// own types, and refuses a K that is not the key field's type.
func TestIDsOfNonIntegerKeys(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		keysTables(t, tg)
		db := tg.db
		a := testmodel.Paper{ID: bindtype.UUID{1}, Title: "A"}
		b := testmodel.Paper{ID: bindtype.UUID{2}, Title: "B"}
		for _, p := range []*testmodel.Paper{&a, &b} {
			if err := db.Insert(p).Exec(ctx); err != nil {
				t.Fatal(err)
			}
		}
		ids, err := db.Query[testmodel.Paper]().OrderBy(P.Title.Asc()).Limit(5).IDs(ctx)
		if err != nil || !slices.Equal(ids, []bindtype.UUID{a.ID, b.ID}) {
			t.Errorf("paper IDs: %v, %v", ids, err)
		}
		if err := db.Insert(&testmodel.Topic{ID: "go", Name: "Go"}).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		tids, err := db.Query[testmodel.Topic]().Limit(5).IDs(ctx)
		if err != nil || !slices.Equal(tids, []string{"go"}) {
			t.Errorf("topic IDs: %v, %v", tids, err)
		}
		none, err := db.Query[testmodel.Paper]().Where(P.Title.EQ("none")).Limit(5).IDs(ctx)
		if err != nil || none != nil {
			t.Errorf("no rows: %v, %v", none, err)
		}
	})
}

// sampleDDL is the table of testmodel.Sample, with score NULL-able so that an
// aggregate can meet NULLs through a NumberCol.
func sampleDDL(d velox.Dialect) string {
	switch d {
	case velox.Postgres:
		return `CREATE TABLE samples (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, status text NOT NULL,
			prev text, price bigint NOT NULL, ratio double precision, flag boolean NOT NULL, maybe_flag boolean, "when" timestamptz NOT NULL,
			maybe_when timestamptz, blob bytea NOT NULL, parent_id bigint, score bigint)`
	case velox.MySQL:
		return "CREATE TABLE samples (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(64) NOT NULL, status VARCHAR(64) NOT NULL, " +
			"prev VARCHAR(64) NULL, price BIGINT NOT NULL, ratio DOUBLE NULL, flag BOOLEAN NOT NULL, maybe_flag BOOLEAN NULL, `when` DATETIME(6) NOT NULL, " +
			"maybe_when DATETIME(6) NULL, `blob` BLOB NOT NULL, parent_id BIGINT NULL, score BIGINT NULL)"
	}
	return `CREATE TABLE samples (id INTEGER PRIMARY KEY, name TEXT NOT NULL, status TEXT NOT NULL, prev TEXT, price INTEGER NOT NULL,
		ratio REAL, flag BOOLEAN NOT NULL, maybe_flag BOOLEAN, "when" DATETIME NOT NULL, maybe_when DATETIME, blob BLOB NOT NULL,
		parent_id INTEGER, score INTEGER)`
}

// seedSample inserts a sample with the given price and score (nil: NULL).
func seedSample(t *testing.T, tg target, price int64, score any) {
	t.Helper()
	q := "INSERT INTO samples (name, status, price, flag, " + quoted(tg.d, "when") + ", " + quoted(tg.d, "blob") + ", score) VALUES (?, ?, ?, ?, ?, ?, ?)"
	tg.exec(t, q, "s", "new", price, false, t0, []byte("b"), score)
}

// quoted quotes a column name that is a keyword.
func quoted(d velox.Dialect, name string) string {
	if d == velox.MySQL {
		return "`" + name + "`"
	}
	return `"` + name + `"`
}

// Sum, Avg, Min and Max over real columns, an empty match, NULLs, a named
// number type and values at the edge of int64, on every dialect. PostgreSQL
// answers SUM(bigint) with numeric and MySQL with DECIMAL (as bytes); the
// result is still the column's Go type, or an error, never a wrapped value.
func TestAggregatesOnRealDatabases(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		I, It, S := testmodel.Invoices, testmodel.Items, testmodel.Samples
		paid := tg.db.Query[testmodel.Invoice]().Where(I.Paid.EQ(true))
		if v, err := velox.Sum(ctx, paid, I.Total); err != nil || v != 90 {
			t.Errorf("Sum: %v, %v", v, err)
		}
		if v, ok, err := velox.Avg(ctx, paid, I.Total); err != nil || !ok || v != 30 {
			t.Errorf("Avg: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.Min(ctx, paid, I.Total); err != nil || !ok || v != 10 {
			t.Errorf("Min: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.Max(ctx, paid, I.Total); err != nil || !ok || v != 50 {
			t.Errorf("Max: %v, %v, %v", v, ok, err)
		}
		// The ordering, limit and columns of the query do not matter.
		if v, err := velox.Sum(ctx, paid.OrderBy(I.ID.Desc()).Limit(1).Columns(I.Number), I.Total); err != nil || v != 90 {
			t.Errorf("Sum of an ordered, limited query: %v, %v", v, err)
		}

		// An int64 column: numeric on PostgreSQL, DECIMAL on MySQL.
		items := tg.db.Query[testmodel.Item]()
		if v, err := velox.Sum(ctx, items, It.Qty); err != nil || v != 7 {
			t.Errorf("Sum of qty: %v, %v", v, err)
		}
		if v, ok, err := velox.Avg(ctx, items, It.Qty); err != nil || !ok || math.Abs(v-7.0/3) > 1e-3 {
			t.Errorf("Avg of qty: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.Max(ctx, items, It.Qty); err != nil || !ok || v != 5 {
			t.Errorf("Max of qty: %v, %v, %v", v, ok, err)
		}

		// No matching row.
		none := tg.db.Query[testmodel.Invoice]().Where(I.ID.EQ(99))
		if v, err := velox.Sum(ctx, none, I.Total); err != nil || v != 0 {
			t.Errorf("empty Sum: %v, %v", v, err)
		}
		if v, ok, err := velox.Avg(ctx, none, I.Total); err != nil || ok || v != 0 {
			t.Errorf("empty Avg: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.Min(ctx, none, I.Total); err != nil || ok || v != 0 {
			t.Errorf("empty Min: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.Max(ctx, none, I.Total); err != nil || ok || v != 0 {
			t.Errorf("empty Max: %v, %v, %v", v, ok, err)
		}
		if v, err := velox.Sum(ctx, tg.db.Query[testmodel.Item]().Where(It.ID.EQ(99)), It.Qty); err != nil || v != 0 {
			t.Errorf("empty Sum of an int64 column: %v, %v", v, err)
		}

		// A named integer type, on a table the shared setup lacks.
		tg.exec(t, "DROP TABLE IF EXISTS samples")
		tg.exec(t, sampleDDL(tg.d))
		t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS samples") })
		samples := tg.db.Query[testmodel.Sample]()
		if v, err := velox.Sum(ctx, samples, S.Price); err != nil || v != 0 {
			t.Errorf("empty Sum of a Cents: %v, %v", v, err)
		}
		if _, ok, err := velox.Max(ctx, samples, S.Price); err != nil || ok {
			t.Errorf("empty Max of a Cents: %v, %v", ok, err)
		}
		seedSample(t, tg, 100, nil)
		seedSample(t, tg, 250, nil)
		if v, err := velox.Sum(ctx, samples, S.Price); err != nil || v != kind.Cents(350) {
			t.Errorf("Sum of a Cents: %v, %v", v, err)
		}
		if v, ok, err := velox.Min(ctx, samples, S.Price); err != nil || !ok || v != kind.Cents(100) {
			t.Errorf("Min of a Cents: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.Avg(ctx, samples, S.Price); err != nil || !ok || v != 175 {
			t.Errorf("Avg of a Cents: %v, %v, %v", v, ok, err)
		}

		// A column of NULLs: Sum is 0, the others are false. Once a value is
		// there, the NULLs are skipped.
		if v, err := velox.Sum(ctx, samples, S.Score); err != nil || v != 0 {
			t.Errorf("Sum of NULLs: %v, %v", v, err)
		}
		if _, ok, err := velox.Avg(ctx, samples, S.Score); err != nil || ok {
			t.Errorf("Avg of NULLs: %v, %v", ok, err)
		}
		if _, ok, err := velox.Min(ctx, samples, S.Score); err != nil || ok {
			t.Errorf("Min of NULLs: %v, %v", ok, err)
		}
		if _, ok, err := velox.Max(ctx, samples, S.Score); err != nil || ok {
			t.Errorf("Max of NULLs: %v, %v", ok, err)
		}
		seedSample(t, tg, 1, int64(4))
		seedSample(t, tg, 1, int64(8))
		if v, err := velox.Sum(ctx, samples, S.Score); err != nil || v != kind.Score(12) {
			t.Errorf("Sum beside NULLs: %v, %v", v, err)
		}
		if v, ok, err := velox.Avg(ctx, samples, S.Score); err != nil || !ok || v != 6 {
			t.Errorf("Avg beside NULLs: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.Max(ctx, samples, S.Score); err != nil || !ok || v != kind.Score(8) {
			t.Errorf("Max beside NULLs: %v, %v, %v", v, ok, err)
		}

		// Values near int64: a sum that fits is exact, and one that does not
		// is an error, not a wrapped or rounded number.
		tg.exec(t, "DELETE FROM samples")
		seedSample(t, tg, math.MaxInt64-10, nil)
		seedSample(t, tg, 5, nil)
		if v, err := velox.Sum(ctx, samples, S.Price); err != nil || v != kind.Cents(math.MaxInt64-5) {
			t.Errorf("Sum near MaxInt64: %v, %v", v, err)
		}
		if v, ok, err := velox.Max(ctx, samples, S.Price); err != nil || !ok || v != kind.Cents(math.MaxInt64-10) {
			t.Errorf("Max near MaxInt64: %v, %v, %v", v, ok, err)
		}
		seedSample(t, tg, 100, nil)
		if v, err := velox.Sum(ctx, samples, S.Price); err == nil {
			t.Errorf("Sum past MaxInt64 gave %v", v)
		}
		if v, ok, err := velox.Avg(ctx, samples, S.Price); err != nil || !ok || math.Abs(v-float64(math.MaxInt64)/3) > float64(math.MaxInt64)*1e-9 {
			t.Errorf("Avg near MaxInt64: %v, %v, %v", v, ok, err)
		}
		tg.exec(t, "DELETE FROM samples")
		seedSample(t, tg, math.MinInt64, nil)
		seedSample(t, tg, -1, nil)
		if v, err := velox.Sum(ctx, samples, S.Price); err == nil {
			t.Errorf("Sum past MinInt64 gave %v", v)
		}
		if v, ok, err := velox.Min(ctx, samples, S.Price); err != nil || !ok || v != kind.Cents(math.MinInt64) {
			t.Errorf("Min at MinInt64: %v, %v, %v", v, ok, err)
		}
	})
}

// SumNull, AvgNull, MinNull and MaxNull, and their grouped forms, over
// nullable numeric columns (NullNumberCol), on every dialect: the result is the
// element type, as for a NumberCol, with the NULLs skipped; only NULLs sum to
// 0, and the others report none.
func TestAggregatesOnNullableColumns(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		S := testmodel.Samples
		tg.exec(t, "DROP TABLE IF EXISTS samples")
		tg.exec(t, sampleDDL(tg.d))
		t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS samples") })
		add := func(status string, ratio, parent any) {
			t.Helper()
			ins := "INSERT INTO samples (name, status, price, ratio, flag, " + quoted(tg.d, "when") + ", " + quoted(tg.d, "blob") + ", parent_id) VALUES (?, ?, ?, ?, ?, ?, ?, ?)"
			tg.exec(t, ins, "s", status, 1, ratio, false, t0, []byte("b"), parent)
		}
		samples := tg.db.Query[testmodel.Sample]()
		add("a", nil, nil)
		if v, err := velox.SumNull(ctx, samples, S.Ratio); err != nil || v != 0 {
			t.Errorf("Sum of NULLs: %v, %v", v, err)
		}
		if _, ok, err := velox.AvgNull(ctx, samples, S.ParentID); err != nil || ok {
			t.Errorf("Avg of NULLs: %v, %v", ok, err)
		}
		if _, ok, err := velox.MinNull(ctx, samples, S.Ratio); err != nil || ok {
			t.Errorf("Min of NULLs: %v, %v", ok, err)
		}
		if _, ok, err := velox.MaxNull(ctx, samples, S.ParentID); err != nil || ok {
			t.Errorf("Max of NULLs: %v, %v", ok, err)
		}
		add("a", 0.5, int64(3))
		add("b", 1.5, int64(9))
		add("b", nil, int64(6))
		if v, err := velox.SumNull(ctx, samples, S.Ratio); err != nil || v != 2 {
			t.Errorf("Sum: %v, %v", v, err)
		}
		if v, err := velox.SumNull(ctx, samples, S.ParentID); err != nil || v != 18 {
			t.Errorf("Sum of an int64: %v, %v", v, err)
		}
		if v, ok, err := velox.AvgNull(ctx, samples, S.ParentID); err != nil || !ok || v != 6 {
			t.Errorf("Avg: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.MinNull(ctx, samples, S.Ratio); err != nil || !ok || v != 0.5 {
			t.Errorf("Min: %v, %v, %v", v, ok, err)
		}
		if v, ok, err := velox.MaxNull(ctx, samples, S.ParentID); err != nil || !ok || v != 9 {
			t.Errorf("Max: %v, %v, %v", v, ok, err)
		}
		all, key := samples.AllowUnbounded(), S.Status
		sums, err := velox.SumByNull(ctx, all, key, S.Ratio)
		if want := []velox.Group[kind.Status, float64]{{Key: "a", Value: 0.5}, {Key: "b", Value: 1.5}}; err != nil || !slices.Equal(sums, want) {
			t.Errorf("SumBy: %v, %v", sums, err)
		}
		avgs, err := velox.AvgByNull(ctx, all, key, S.ParentID)
		if want := []velox.Group[kind.Status, float64]{{Key: "a", Value: 3}, {Key: "b", Value: 7.5}}; err != nil || !slices.Equal(avgs, want) {
			t.Errorf("AvgBy: %v, %v", avgs, err)
		}
		mins, err := velox.MinByNull(ctx, all, key, S.ParentID)
		if want := []velox.Group[kind.Status, int64]{{Key: "a", Value: 3}, {Key: "b", Value: 6}}; err != nil || !slices.Equal(mins, want) {
			t.Errorf("MinBy: %v, %v", mins, err)
		}
		maxs, err := velox.MaxByNull(ctx, all, key, S.Ratio)
		if want := []velox.Group[kind.Status, float64]{{Key: "a", Value: 0.5}, {Key: "b", Value: 1.5}}; err != nil || !slices.Equal(maxs, want) {
			t.Errorf("MaxBy: %v, %v", maxs, err)
		}
	})
}


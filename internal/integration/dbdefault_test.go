// gadget has columns whose database default the schema declared: status,
// score and note.
type gadget struct {
	ID     int64
	Name   string
	Status string
	Score  int64
	Note   *string
}

var gadgetMeta velox.MetaOnce[gadget]

func (*gadget) VeloxMeta() *velox.Meta[gadget] {
	all := []velox.Dialect{velox.Postgres, velox.MySQL, velox.SQLite}
	return gadgetMeta.Load(func() velox.Descriptor[gadget] {
		return velox.Descriptor[gadget]{
			Table: "gadgets",
			Columns: []velox.ColumnDescriptor{
				{Field: "ID", Name: "id"}, {Field: "Name", Name: "name"},
				{Field: "Status", Name: "status", DBDefault: all},
				{Field: "Score", Name: "score", DBDefault: all},
				{Field: "Note", Name: "note", DBDefault: all},
			},
			PrimaryKey: []int{0},
			FieldPtr: func(x *gadget, i int) any {
				return [...]any{&x.ID, &x.Name, &x.Status, &x.Score, &x.Note}[i]
			},
		}
	})
}

func gadgetDDL(d velox.Dialect) string {
	switch d {
	case velox.Postgres:
		return `CREATE TABLE gadgets (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE,
			status text NOT NULL DEFAULT 'new', score bigint NOT NULL DEFAULT 7, note text DEFAULT 'n')`
	case velox.MySQL:
		return "CREATE TABLE gadgets (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(64) NOT NULL UNIQUE, " +
			"status VARCHAR(16) NOT NULL DEFAULT 'new', score BIGINT NOT NULL DEFAULT 7, note VARCHAR(16) DEFAULT 'n')"
	}
	return `CREATE TABLE gadgets (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE,
		status TEXT NOT NULL DEFAULT 'new', score INTEGER NOT NULL DEFAULT 7, note TEXT DEFAULT 'n')`
}

// TestInsertDatabaseDefaults: on each database, a zero value in a column
// with a declared default is left to the database and read back, a value is
// written, and InsertAll's rows each get their key and their defaults, as a
// row inserted alone would (ADR 0093).
func TestInsertDatabaseDefaults(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		tg.exec(t, "DROP TABLE IF EXISTS gadgets")
		tg.exec(t, gadgetDDL(tg.d))
		t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS gadgets") })

		a := gadget{Name: "a"}
		if err := tg.db.Insert(&a).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if a.ID == 0 || a.Status != "new" || a.Score != 7 || a.Note == nil || *a.Note != "n" {
			t.Errorf("Insert read back %+v", a)
		}
		empty := ""
		b := gadget{Name: "b", Status: "done", Score: 3, Note: &empty}
		if err := tg.db.Insert(&b).Exec(ctx); err != nil {
			t.Fatal(err)
		}

		xs := []gadget{{Name: "c"}, {Name: "d", Score: 5}, {Name: "e", Score: 6}, {Name: "f"}}
		if err := tg.db.InsertAll(xs).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		for i, want := range []int64{7, 5, 6, 7} {
			if xs[i].ID == 0 || xs[i].Score != want || xs[i].Status != "new" || xs[i].Note == nil {
				t.Errorf("InsertAll row %d read back %+v, want score %d", i, xs[i], want)
			}
		}

		got, err := tg.db.Query[gadget]().AllowUnbounded().All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		slices.SortFunc(got, func(x, y gadget) int { return int(x.ID - y.ID) })
		want := append([]gadget{a, b}, xs...)
		if len(got) != len(want) {
			t.Fatalf("stored %d rows, want %d", len(got), len(want))
		}
		for i := range want {
			if g, w := got[i], want[i]; g.ID != w.ID || g.Name != w.Name || g.Status != w.Status || g.Score != w.Score || *g.Note != *w.Note {
				t.Errorf("row %d: stored %+v, the entity holds %+v", i, g, w)
			}
		}
	})
}

// blank has no column that must be written: its key is generated and its
// status has a declared database default.
type blank struct {
	ID     int64
	Status string
}

var blankMeta velox.MetaOnce[blank]

func (*blank) VeloxMeta() *velox.Meta[blank] {
	all := []velox.Dialect{velox.Postgres, velox.MySQL, velox.SQLite}
	return blankMeta.Load(func() velox.Descriptor[blank] {
		return velox.Descriptor[blank]{
			Table:      "blanks",
			Columns:    []velox.ColumnDescriptor{{Field: "ID", Name: "id"}, {Field: "Status", Name: "status", DBDefault: all}},
			PrimaryKey: []int{0},
			FieldPtr: func(x *blank, i int) any {
				if i == 0 {
					return &x.ID
				}
				return &x.Status
			},
		}
	})
}

// freshGadgets creates the gadgets table anew for one test.
func freshGadgets(t *testing.T, tg target) {
	tg.exec(t, "DROP TABLE IF EXISTS gadgets")
	tg.exec(t, gadgetDDL(tg.d))
	t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS gadgets") })
}

// TestInsertAllEmptyUsesDefaults: an insert that leaves every column to the
// database stores the declared default on each database, alone and in an
// InsertAll (ADR 0093).
func TestInsertAllEmptyUsesDefaults(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		ddl := `CREATE TABLE blanks (id INTEGER PRIMARY KEY AUTOINCREMENT, status TEXT NOT NULL DEFAULT 'new')`
		switch tg.d {
		case velox.Postgres:
			ddl = `CREATE TABLE blanks (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status text NOT NULL DEFAULT 'new')`
		case velox.MySQL:
			ddl = "CREATE TABLE blanks (id BIGINT AUTO_INCREMENT PRIMARY KEY, status VARCHAR(16) NOT NULL DEFAULT 'new')"
		}
		tg.exec(t, "DROP TABLE IF EXISTS blanks")
		tg.exec(t, ddl)
		t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS blanks") })

		a := blank{}
		if err := tg.db.Insert(&a).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		xs := []blank{{}, {}, {}}
		if err := tg.db.InsertAll(xs).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		for i, x := range append([]blank{a}, xs...) {
			if x.ID == 0 || x.Status != "new" {
				t.Errorf("entity %d: %+v", i, x)
			}
		}
		got, err := tg.db.Query[blank]().AllowUnbounded().All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if len(got) != 4 {
			t.Fatalf("stored %d rows, want 4", len(got))
		}
		for _, g := range got {
			if g.Status != "new" {
				t.Errorf("stored %+v, want the default", g)
			}
		}
	})
}

// TestInsertAllOneStatementWithDefaultCells: on PostgreSQL and MySQL an
// InsertAll whose rows leave different columns to the database is one
// statement, with DEFAULT cells; SQLite splits it. Every row stores, and
// reads back, what it would alone.
func TestInsertAllOneStatementWithDefaultCells(t *testing.T) {
	var inserts int
	count := velox.WithRewrite(func(_ context.Context, st *velox.Statement) error {
		if st.Op == velox.OpInsert {
			inserts++
		}
		return nil
	})
	each(t, func(t *testing.T, tg target) {
		freshGadgets(t, tg)
		inserts = 0
		xs := make([]gadget, 10)
		for i := range xs {
			xs[i].Name = strings.Repeat("g", i+1)
			if i%2 == 0 {
				xs[i].Score = int64(i + 1)
			}
		}
		if err := tg.db.InsertAll(xs).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if want := map[velox.Dialect]int{velox.Postgres: 1, velox.MySQL: 1, velox.SQLite: 10}[tg.d]; inserts != want {
			t.Errorf("%d INSERT statements, want %d", inserts, want)
		}
		got, err := tg.db.Query[gadget]().AllowUnbounded().All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		byID := map[int64]gadget{}
		for _, g := range got {
			byID[g.ID] = g
		}
		for i, x := range xs {
			want := int64(7)
			if i%2 == 0 {
				want = int64(i + 1)
			}
			g := byID[x.ID]
			if x.ID == 0 || x.Score != want || x.Status != "new" || x.Note == nil || *x.Note != "n" || g.Score != want || g.Name != x.Name {
				t.Errorf("row %d: entity %+v, stored %+v, want score %d", i, x, g, want)
			}
		}
	}, count)
}

// TestUpsertReadsBackDefaults: a single-row upsert gives the entity the
// stored row's defaulted columns, on MySQL too, whose read is by the
// conflict values.
func TestUpsertReadsBackDefaults(t *testing.T) {
	name := velox.StringCol[gadget, string]{I: 1}
	each(t, func(t *testing.T, tg target) {
		freshGadgets(t, tg)
		tg.exec(t, "INSERT INTO gadgets (name, status, score) VALUES ('a', 'done', 3)")
		a := gadget{Name: "a"}
		if err := tg.db.Insert(&a).OnConflict(name).Update(name).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if a.Status != "done" || a.Score != 3 || a.Note == nil || *a.Note != "n" {
			t.Errorf("updated row read back %+v", a)
		}
		b := gadget{Name: "b"}
		if err := tg.db.Insert(&b).OnConflict(name).Update(name).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if b.Status != "new" || b.Score != 7 {
			t.Errorf("inserted row read back %+v", b)
		}
	})
}

// TestUpsertConflictWhereFillsByKey: an upsert whose update branch a
// Rewrite hook conditions writes only some rows; each row read back goes to
// the entity it was written from. MySQL takes no such condition.
func TestUpsertConflictWhereFillsByKey(t *testing.T) {
	rw := velox.WithRewrite(func(_ context.Context, st *velox.Statement) error {
		if st.Conflict != nil && st.Dialect != velox.MySQL {
			st.Conflict.Where = append(st.Conflict.Where, velox.Predicate(velox.Expr[gadget]("1 = 0")))
		}
		return nil
	})
	name := velox.StringCol[gadget, string]{I: 1}
	each(t, func(t *testing.T, tg target) {
		if tg.d == velox.MySQL {
			t.Skip("MySQL's ON DUPLICATE KEY UPDATE takes no condition")
		}
		freshGadgets(t, tg)
		tg.exec(t, "INSERT INTO gadgets (name, status) VALUES ('a', 'done')")
		xs := []gadget{{Name: "a"}, {Name: "b"}}
		if err := tg.db.InsertAll(xs).OnConflict(name).Update(name).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if xs[0].ID != 0 || xs[0].Status != "" || xs[1].ID == 0 || xs[1].Status != "new" {
			t.Errorf("filled %+v", xs)
		}
	}, rw)
}

// TestUpsertOfOnlySkippedColumns: an upsert whose every Update column had
// its setter skipped keeps the existing row through a no-op update of the
// conflict column (ConflictClause.Ignore), and reads its key back, on each
// database.
func TestUpsertOfOnlySkippedColumns(t *testing.T) {
	score := velox.NumberCol[gadget, int64]{I: 3}
	name := velox.StringCol[gadget, string]{I: 1}
	each(t, func(t *testing.T, tg target) {
		tg.exec(t, "DROP TABLE IF EXISTS gadgets")
		tg.exec(t, gadgetDDL(tg.d))
		t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS gadgets") })
		a := gadget{Name: "a", Score: 3}
		if err := tg.db.Insert(&a).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		x := gadget{Name: "a", Score: 9}
		if err := tg.db.Insert(&x).Set(score.SetPtr(nil)).OnConflict(name).Update(score).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if x.ID != a.ID {
			t.Errorf("key read back %d, want %d", x.ID, a.ID)
		}
		got, err := tg.db.Query[gadget]().Where(name.EQ("a")).One(ctx)
		if err != nil || got.Score != 3 {
			t.Errorf("row %+v, %v; want it kept", got, err)
		}
	})
}

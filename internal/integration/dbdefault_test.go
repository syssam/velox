package integration

import (
	"slices"
	"testing"

	"github.com/syssam/velox"
)

// gadget has columns whose database default the schema declared: status,
// score and note.
type gadget struct {
	ID     int64
	Name   string
	Status string
	Score  int64
	Note   *string
}

var gadgetMeta velox.MetaOnce[gadget]

func (*gadget) VeloxMeta() *velox.Meta[gadget] {
	all := []velox.Dialect{velox.Postgres, velox.MySQL, velox.SQLite}
	return gadgetMeta.Load(func() velox.Descriptor[gadget] {
		return velox.Descriptor[gadget]{
			Table: "gadgets",
			Columns: []velox.ColumnDescriptor{
				{Field: "ID", Name: "id"}, {Field: "Name", Name: "name"},
				{Field: "Status", Name: "status", DBDefault: all},
				{Field: "Score", Name: "score", DBDefault: all},
				{Field: "Note", Name: "note", DBDefault: all},
			},
			PrimaryKey: []int{0},
			FieldPtr: func(x *gadget, i int) any {
				return [...]any{&x.ID, &x.Name, &x.Status, &x.Score, &x.Note}[i]
			},
		}
	})
}

func gadgetDDL(d velox.Dialect) string {
	switch d {
	case velox.Postgres:
		return `CREATE TABLE gadgets (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL,
			status text NOT NULL DEFAULT 'new', score bigint NOT NULL DEFAULT 7, note text DEFAULT 'n')`
	case velox.MySQL:
		return "CREATE TABLE gadgets (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(64) NOT NULL, " +
			"status VARCHAR(16) NOT NULL DEFAULT 'new', score BIGINT NOT NULL DEFAULT 7, note VARCHAR(16) DEFAULT 'n')"
	}
	return `CREATE TABLE gadgets (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL,
		status TEXT NOT NULL DEFAULT 'new', score INTEGER NOT NULL DEFAULT 7, note TEXT DEFAULT 'n')`
}

// TestInsertDatabaseDefaults: on each database, a zero value in a column
// with a declared default is left to the database and read back, a value is
// written, and InsertAll's rows each get their key and their defaults, as a
// row inserted alone would (ADR 0093).
func TestInsertDatabaseDefaults(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		tg.exec(t, "DROP TABLE IF EXISTS gadgets")
		tg.exec(t, gadgetDDL(tg.d))
		t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS gadgets") })

		a := gadget{Name: "a"}
		if err := tg.db.Insert(&a).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if a.ID == 0 || a.Status != "new" || a.Score != 7 || a.Note == nil || *a.Note != "n" {
			t.Errorf("Insert read back %+v", a)
		}
		empty := ""
		b := gadget{Name: "b", Status: "done", Score: 3, Note: &empty}
		if err := tg.db.Insert(&b).Exec(ctx); err != nil {
			t.Fatal(err)
		}

		xs := []gadget{{Name: "c"}, {Name: "d", Score: 5}, {Name: "e", Score: 6}, {Name: "f"}}
		if err := tg.db.InsertAll(xs).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		for i, want := range []int64{7, 5, 6, 7} {
			if xs[i].ID == 0 || xs[i].Score != want || xs[i].Status != "new" || xs[i].Note == nil {
				t.Errorf("InsertAll row %d read back %+v, want score %d", i, xs[i], want)
			}
		}

		got, err := tg.db.Query[gadget]().AllowUnbounded().All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		slices.SortFunc(got, func(x, y gadget) int { return int(x.ID - y.ID) })
		want := append([]gadget{a, b}, xs...)
		if len(got) != len(want) {
			t.Fatalf("stored %d rows, want %d", len(got), len(want))
		}
		for i := range want {
			if g, w := got[i], want[i]; g.ID != w.ID || g.Name != w.Name || g.Status != w.Status || g.Score != w.Score || *g.Note != *w.Note {
				t.Errorf("row %d: stored %+v, the entity holds %+v", i, g, w)
			}
		}
	})
}

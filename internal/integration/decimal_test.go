package integration

import (
	"math/big"
	"testing"

	"github.com/syssam/velox"
	"github.com/syssam/velox/internal/testmodel"
)

// ledgerDDL is the table of testmodel.Ledger: two numeric columns.
func ledgerDDL(d velox.Dialect) string {
	switch d {
	case velox.Postgres:
		return `CREATE TABLE ledgers (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount numeric(19,4) NOT NULL, fee numeric(19,4))`
	case velox.MySQL:
		return "CREATE TABLE ledgers (id BIGINT AUTO_INCREMENT PRIMARY KEY, amount DECIMAL(19,4) NOT NULL, fee DECIMAL(19,4) NULL)"
	}
	return `CREATE TABLE ledgers (id INTEGER PRIMARY KEY, amount NUMERIC NOT NULL, fee NUMERIC)`
}

// wantDec fails t unless d is the number want, however the database writes it
// (PostgreSQL's 3.7500, SQLite's 3.75).
func wantDec(t *testing.T, what string, d testmodel.Dec, want string) {
	t.Helper()
	got, ok := new(big.Rat).SetString(string(d))
	if w, _ := new(big.Rat).SetString(want); !ok || got.Cmp(w) != 0 {
		t.Errorf("%s: %q, want %s", what, d, want)
	}
}

// TestDecimalNumberCol: an Other field of a decimal Go type (Scanner and
// Valuer over text) in a numeric column has a NumberCol, whose Sum, Avg, Add
// and Sub run in the database and scan back into the type. MySQL runs it
// also through a DSN with interpolateParams=true (eachJSON), where Add's text
// argument would make the sum a DOUBLE but for its CAST to the column's type.
func TestDecimalNumberCol(t *testing.T) {
	eachJSON(t, func(t *testing.T, tg target) {
		tg.exec(t, "DROP TABLE IF EXISTS ledgers")
		tg.exec(t, ledgerDDL(tg.d))
		t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS ledgers") })

		L := testmodel.Ledgers
		fee := testmodel.Dec("0.25")
		rows := []testmodel.Ledger{{Amount: "1.25", Fee: &fee}, {Amount: "2.5"}}
		if err := tg.db.InsertAll(rows).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		all := tg.db.Query[testmodel.Ledger]()
		sum, err := velox.Sum(ctx, all, L.Amount)
		if err != nil {
			t.Fatal(err)
		}
		wantDec(t, "Sum", sum, "3.75")
		if avg, ok, err := velox.Avg(ctx, all, L.Amount); err != nil || !ok || avg != 1.875 {
			t.Errorf("Avg: %v, %v, %v", avg, ok, err)
		}
		if fees, err := velox.SumNull(ctx, all, L.Fee); err != nil {
			t.Error(err)
		} else {
			wantDec(t, "SumNull", fees, "0.25")
		}

		// Add and Sub bind a value of the type: amount = amount + ?.
		if _, err := tg.db.Update[testmodel.Ledger]().Where(L.ID.EQ(rows[0].ID)).Set(L.Amount.Add("0.5"), L.Fee.Sub("0.05")).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		got, err := tg.db.Query[testmodel.Ledger]().Where(L.ID.EQ(rows[0].ID)).One(ctx)
		if err != nil {
			t.Fatal(err)
		}
		wantDec(t, "Add", got.Amount, "1.75")
		if got.Fee == nil {
			t.Fatal("Sub: fee is NULL")
		}
		wantDec(t, "Sub", *got.Fee, "0.2")

		// Sum as a Term, in a projection.
		var out []testmodel.Dec
		for r, err := range all.Limit(10).Select(L.Amount.Sum()).Rows(ctx) {
			if err != nil {
				t.Fatal(err)
			}
			var d testmodel.Dec
			if err := r.Scan(&d); err != nil {
				t.Fatal(err)
			}
			out = append(out, d)
		}
		if len(out) != 1 {
			t.Fatalf("Sum term: %q", out)
		}
		wantDec(t, "Sum term", out[0], "4.25")

		// Eighteen digits: exact on PostgreSQL and MySQL, interpolated or
		// not. SQLite's NUMERIC stores such a value as a REAL, which holds
		// about sixteen.
		if tg.d == velox.SQLite {
			return
		}
		wide := testmodel.Ledger{Amount: "12345678901234.5678"}
		if err := tg.db.Insert(&wide).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if _, err := tg.db.Update[testmodel.Ledger]().Where(L.ID.EQ(wide.ID)).Set(L.Amount.Add("0.0001")).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		got, err = tg.db.Query[testmodel.Ledger]().Where(L.ID.EQ(wide.ID)).One(ctx)
		if err != nil {
			t.Fatal(err)
		}
		wantDec(t, "Add of 18 digits", got.Amount, "12345678901234.5679")
	})
}

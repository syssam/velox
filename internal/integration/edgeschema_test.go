// rosterDDL creates players, teams and rosters, the edge schema of
// Player.Teams, on each dialect: a key of its own, a unique pair of keys and
// a second unique key, code.
var rosterDDL = map[velox.Dialect][]string{
	velox.Postgres: {
		`CREATE TABLE players (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL)`,
		`CREATE TABLE teams (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL)`,
		`CREATE TABLE rosters (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role text NOT NULL, joined_at timestamptz NOT NULL,
			code varchar(16) NOT NULL UNIQUE, player_id bigint NOT NULL REFERENCES players (id) ON DELETE CASCADE,
			team_id bigint NOT NULL REFERENCES teams (id) ON DELETE CASCADE, CONSTRAINT roster_player_id_team_id UNIQUE (player_id, team_id))`,
	},
	velox.MySQL: {
		"CREATE TABLE players (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(64) NOT NULL)",
		"CREATE TABLE teams (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(64) NOT NULL)",
		"CREATE TABLE rosters (id BIGINT AUTO_INCREMENT PRIMARY KEY, role VARCHAR(64) NOT NULL, joined_at DATETIME(6) NOT NULL, " +
			"code VARCHAR(16) NOT NULL UNIQUE, player_id BIGINT NOT NULL, team_id BIGINT NOT NULL, " +
			"FOREIGN KEY (player_id) REFERENCES players (id) ON DELETE CASCADE, FOREIGN KEY (team_id) REFERENCES teams (id) ON DELETE CASCADE, " +
			"UNIQUE KEY roster_player_id_team_id (player_id, team_id))",
	},
	velox.SQLite: {
		`CREATE TABLE players (id INTEGER PRIMARY KEY, name TEXT NOT NULL)`,
		`CREATE TABLE teams (id INTEGER PRIMARY KEY, name TEXT NOT NULL)`,
		`CREATE TABLE rosters (id INTEGER PRIMARY KEY, role TEXT NOT NULL, joined_at DATETIME NOT NULL, code TEXT NOT NULL UNIQUE,
			player_id INTEGER NOT NULL REFERENCES players (id) ON DELETE CASCADE, team_id INTEGER NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
			CONSTRAINT roster_player_id_team_id UNIQUE (player_id, team_id))`,
	},
}

// rosterSetup creates the tables, and teams 1 "a", 2 "b" and 3 "c".
func rosterSetup(t *testing.T, tg target) {
	t.Helper()
	for _, s := range []string{"rosters", "players", "teams"} {
		tg.exec(t, "DROP TABLE IF EXISTS "+s)
	}
	for _, s := range rosterDDL[tg.d] {
		tg.exec(t, s)
	}
	for _, n := range []string{"a", "b", "c"} {
		if err := tg.db.Insert(&tm.Team{Name: n}).Exec(ctx); err != nil {
			t.Fatal(err)
		}
	}
}

// rosters reads player p's links, by team.
func rosters(t *testing.T, tg target, p int64) map[int64]tm.Roster {
	t.Helper()
	rs, err := tg.db.Query[tm.Roster]().Where(tm.Rosters.PlayerID.EQ(p)).Limit(10).All(ctx)
	if err != nil {
		t.Fatal(err)
	}
	out := map[int64]tm.Roster{}
	for _, r := range rs {
		out[r.TeamID] = r
	}
	return out
}

// wantTeams checks the teams player p links to.
func wantTeams(t *testing.T, tg target, what string, p int64, teams ...int64) map[int64]tm.Roster {
	t.Helper()
	rs := rosters(t, tg, p)
	if len(rs) != len(teams) {
		t.Fatalf("%s: links %+v, want teams %v", what, rs, teams)
	}
	for _, id := range teams {
		if _, ok := rs[id]; !ok {
			t.Fatalf("%s: links %+v, want teams %v", what, rs, teams)
		}
	}
	return rs
}

// TestEdgeSchemaThrough runs the M2M edge setters, With and HasWith on a
// relation whose links are an edge schema's rows. Add fills the rows'
// defaults; adding a link again keeps the row, on MySQL too, where its
// ON DUPLICATE KEY UPDATE holds for the second unique key as well; Remove and
// Clear delete rows, and a link the Write policy hides stays.
func TestEdgeSchemaThrough(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		rosterSetup(t, tg)
		p := tm.Player{Name: "p"}
		if err := tg.db.Insert(&p).Set(tm.Players.Teams.Add(1, 2)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		rs := wantTeams(t, tg, "after insert", p.ID, 1, 2)
		for _, r := range rs {
			if r.Role != "member" || len(r.Code) != 16 || r.JoinedAt.IsZero() || r.ID == 0 {
				t.Errorf("defaults not filled: %+v", r)
			}
		}
		if rs[1].Code == rs[2].Code {
			t.Errorf("two links share a code: %+v", rs)
		}

		// Adding a link again keeps its row and its code.
		if _, err := tg.db.Update[tm.Player]().Set(tm.Players.Teams.Add(1, 3)).Where(tm.Players.ID.EQ(p.ID)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		again := wantTeams(t, tg, "after re-add", p.ID, 1, 2, 3)
		if a, r := again[1], rs[1]; a.ID != r.ID || a.Code != r.Code || a.Role != r.Role || !a.JoinedAt.Equal(r.JoinedAt) {
			t.Errorf("re-add changed the link: %+v, was %+v", again[1], rs[1])
		}

		// With loads both edges; HasWith tests the M2M.
		ps, err := tg.db.Query[tm.Player]().With(tm.Players.Teams.OrderBy(tm.Teams.Name.Asc())).With(tm.Players.Rosters).Limit(5).All(ctx)
		if err != nil || len(ps) != 1 {
			t.Fatalf("with: %v, %v", ps, err)
		}
		teams, _ := ps[0].Edges.Teams.Get()
		links, _ := ps[0].Edges.Rosters.Get()
		if len(teams) != 3 || teams[0].Name != "a" || teams[2].Name != "c" || len(links) != 3 {
			t.Errorf("with: teams %+v, links %+v", teams, links)
		}
		for name, want := range map[string]int64{"b": 1, "d": 0} {
			n, err := tg.db.Query[tm.Player]().Where(tm.Players.Teams.HasWith(tm.Teams.Name.EQ(name))).Count(ctx)
			if err != nil || n != want {
				t.Errorf("HasWith %s: %d, %v", name, n, err)
			}
		}

		if _, err := tg.db.Update[tm.Player]().Set(tm.Players.Teams.Remove(2)).Where(tm.Players.ID.EQ(p.ID)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		wantTeams(t, tg, "after remove", p.ID, 1, 3)

		// Under the policies, Clear keeps the captain's link, which the
		// Write policy hides; without them, it deletes it.
		if _, err := tg.db.Update[tm.Roster]().Set(tm.Rosters.Role.Set("captain")).Where(tm.Rosters.PlayerID.EQ(p.ID), tm.Rosters.TeamID.EQ(1)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		bg := context.Background()
		if _, err := tg.pdb.Update[tm.Player]().Set(tm.Players.Teams.Clear()).Where(tm.Players.ID.EQ(p.ID)).Exec(bg); err != nil {
			t.Fatal(err)
		}
		wantTeams(t, tg, "after clear under the policy", p.ID, 1)
		if _, err := tg.db.Update[tm.Player]().Set(tm.Players.Teams.Clear()).Where(tm.Players.ID.EQ(p.ID)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		wantTeams(t, tg, "after clear", p.ID)
	})
}

// rosterFail is the context key under which the hook on Roster fails.
type rosterFail struct{}

// TestEdgeSchemaHooks: Add and Remove write the edge schema's rows through
// its hooks, and a hook's error undoes the owner's insert.
func TestEdgeSchemaHooks(t *testing.T) {
	var ops []velox.Op
	hook := velox.Before(func(c context.Context, m *velox.Mutation) error {
		if c.Value(rosterFail{}) != nil {
			return errors.New("roster refused")
		}
		ops = append(ops, m.Op())
		return nil
	}, velox.OpInsert, velox.OpDelete)
	each(t, func(t *testing.T, tg target) {
		ops = nil
		rosterSetup(t, tg)
		p := tm.Player{Name: "p"}
		if err := tg.db.Insert(&p).Set(tm.Players.Teams.Add(1, 2)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if _, err := tg.db.Update[tm.Player]().Set(tm.Players.Teams.Remove(1)).Where(tm.Players.ID.EQ(p.ID)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if want := []velox.Op{velox.OpInsert, velox.OpDelete}; !slices.Equal(ops, want) {
			t.Errorf("the hook saw %v, want %v", ops, want)
		}
		q := tm.Player{Name: "q"}
		err := tg.db.Insert(&q).Set(tm.Players.Teams.Add(1)).Exec(context.WithValue(ctx, rosterFail{}, true))
		if err == nil || !strings.Contains(err.Error(), "roster refused") {
			t.Fatalf("insert: %v", err)
		}
		n, err := tg.db.Query[tm.Player]().Where(tm.Players.Name.EQ("q")).Count(ctx)
		if err != nil || n != 0 {
			t.Errorf("the refused insert left %d players, %v", n, err)
		}
	}, velox.WithHooks[tm.Roster](hook))
}

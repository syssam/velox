package integration

import (
	"database/sql"
	"testing"

	"github.com/syssam/velox"
)

// nully has nullable columns with a default, each of one kind: note's
// DEFAULT the schema declared (DBDefault), level's a constant Default,
// which velox-gen also writes as the column's DEFAULT, and code's a
// DefaultFunc, which has no DEFAULT.
type nully struct {
	ID    int64
	Name  string
	Note  *string
	Level *int64
	Code  *string
}

var nullyMeta velox.MetaOnce[nully]

func (*nully) VeloxMeta() *velox.Meta[nully] {
	all := []velox.Dialect{velox.Postgres, velox.MySQL, velox.SQLite}
	return nullyMeta.Load(func() velox.Descriptor[nully] {
		return velox.Descriptor[nully]{
			Table: "nullies",
			Columns: []velox.ColumnDescriptor{
				{Field: "ID", Name: "id"}, {Field: "Name", Name: "name"},
				{Field: "Note", Name: "note", DBDefault: all},
				{Field: "Level", Name: "level", Default: int64(5)},
				{Field: "Code", Name: "code", DefaultFunc: func() any { return "fn" }},
			},
			PrimaryKey: []int{0},
			FieldPtr: func(x *nully, i int) any {
				return [...]any{&x.ID, &x.Name, &x.Note, &x.Level, &x.Code}[i]
			},
		}
	})
}

var nullies = struct {
	Name  velox.StringCol[nully, string]
	Note  velox.NullStringCol[nully, string]
	Level velox.NullNumberCol[nully, int64]
	Code  velox.NullStringCol[nully, string]
}{velox.StringCol[nully, string]{I: 1}, velox.NullStringCol[nully, string]{I: 2}, velox.NullNumberCol[nully, int64]{I: 3}, velox.NullStringCol[nully, string]{I: 4}}

func freshNullies(t *testing.T, tg target) {
	ddl := `CREATE TABLE nullies (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE,
		note TEXT DEFAULT 'n', level INTEGER DEFAULT 5, code TEXT)`
	switch tg.d {
	case velox.Postgres:
		ddl = `CREATE TABLE nullies (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE,
			note text DEFAULT 'n', level bigint DEFAULT 5, code text)`
	case velox.MySQL:
		ddl = "CREATE TABLE nullies (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(64) NOT NULL UNIQUE, " +
			"note VARCHAR(16) DEFAULT 'n', level BIGINT DEFAULT 5, code VARCHAR(16))"
	}
	tg.exec(t, "DROP TABLE IF EXISTS nullies")
	tg.exec(t, ddl)
	t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS nullies") })
}

// nullInput is an Input whose Setters give an explicit null for each
// defaulted column, as a create input's null does.
type nullInput struct{}

func (nullInput) Setters() ([]velox.Setter[nully], error) {
	return []velox.Setter[nully]{nullies.Note.SetNull(), nullies.Level.SetNull(), nullies.Code.SetNull()}, nil
}

// storedNullies reads name's note, level and code as the database holds
// them, without velox.
func storedNullies(t *testing.T, tg target, name string) (note sql.NullString, level sql.NullInt64, code sql.NullString) {
	t.Helper()
	q := "SELECT note, level, code FROM nullies WHERE name = ?"
	if tg.d == velox.Postgres {
		q = "SELECT note, level, code FROM nullies WHERE name = $1"
	}
	if err := tg.direct.QueryRowContext(ctx, q, name).Scan(&note, &level, &code); err != nil {
		t.Fatal(err)
	}
	return note, level, code
}

// TestInsertExplicitNull: an explicit null (SetNull, SetPtr of nil, an
// Input's SetNull) in an insert stores NULL in a nullable column, whatever
// its default: the DEFAULT the schema declared, a constant Default, which
// is the column's DEFAULT too, or a DefaultFunc. A nil field with no setter
// gets the default. Insert, InsertAll and an upsert's inserted rows alike
// (ADR 0124).
func TestInsertExplicitNull(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		freshNullies(t, tg)
		N := nullies
		cases := []struct {
			name string
			run  func(name string) error
		}{
			{"setnull", func(name string) error {
				return tg.db.Insert(&nully{Name: name}).Set(N.Note.SetNull(), N.Level.SetNull(), N.Code.SetNull()).Exec(ctx)
			}},
			{"setptr", func(name string) error {
				return tg.db.Insert(&nully{Name: name}).Set(N.Note.SetPtr(nil), N.Level.SetPtr(nil), N.Code.SetPtr(nil)).Exec(ctx)
			}},
			{"input", func(name string) error {
				return tg.db.Insert(&nully{Name: name}).SetInput(nullInput{}).Exec(ctx)
			}},
			{"upsert", func(name string) error {
				return tg.db.Insert(&nully{Name: name}).Set(N.Note.SetNull(), N.Level.SetNull(), N.Code.SetNull()).
					OnConflict(N.Name).Update(N.Note).Exec(ctx)
			}},
			{"all", func(name string) error {
				return tg.db.InsertAll([]nully{{Name: name}, {Name: name + "2"}}).
					Set(N.Note.SetNull(), N.Level.SetNull(), N.Code.SetNull()).Exec(ctx)
			}},
			{"allupsert", func(name string) error {
				return tg.db.InsertAll([]nully{{Name: name}, {Name: name + "2"}}).
					Set(N.Note.SetPtr(nil), N.Level.SetNull(), N.Code.SetNull()).OnConflict(N.Name).Update(N.Level).Exec(ctx)
			}},
		}
		for _, c := range cases {
			if err := c.run(c.name); err != nil {
				t.Fatalf("%s: %v", c.name, err)
			}
			note, level, code := storedNullies(t, tg, c.name)
			if note.Valid || level.Valid || code.Valid {
				t.Errorf("%s: stored note %v, level %v, code %v; want NULL", c.name, note, level, code)
			}
		}

		// No setter: a nil field gets its default.
		x := nully{Name: "unset"}
		if err := tg.db.Insert(&x).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		note, level, code := storedNullies(t, tg, "unset")
		if note.String != "n" || level.Int64 != 5 || code.String != "fn" {
			t.Errorf("unset: stored note %v, level %v, code %v; want the defaults", note, level, code)
		}
		if x.Note == nil || *x.Note != "n" || x.Level == nil || *x.Level != 5 || x.Code == nil || *x.Code != "fn" {
			t.Errorf("unset: entity %+v", x)
		}

		// A value set after an explicit null wins, as the last setter does.
		v := "v"
		if err := tg.db.Insert(&nully{Name: "later"}).Set(N.Note.SetNull(), N.Note.Set(v)).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if note, _, _ := storedNullies(t, tg, "later"); note.String != "v" {
			t.Errorf("later: stored note %v, want v", note)
		}

		// SetPtr of nil in an upsert stores NULL in the row it inserts and
		// leaves the existing row's column as it is (ADR 0099).
		tg.exec(t, "UPDATE nullies SET note = 'kept' WHERE name = 'unset'")
		if err := tg.db.Insert(&nully{Name: "unset"}).Set(N.Note.SetPtr(nil)).OnConflict(N.Name).Update(N.Note).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if note, _, _ := storedNullies(t, tg, "unset"); note.String != "kept" {
			t.Errorf("upsert of SetPtr(nil): stored note %v, want kept", note)
		}
	})
}

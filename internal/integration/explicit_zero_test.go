package integration

import (
	"testing"

	"github.com/syssam/velox"
)

// zeroy has NOT NULL columns whose declared database default is not the
// zero value: an int, a decimal, a bool and a string.
type zeroy struct {
	ID     int64
	Name   string
	Seats  int64
	Rate   float64
	Active bool
	Plan   string
}

var zeroyMeta velox.MetaOnce[zeroy]

func (*zeroy) VeloxMeta() *velox.Meta[zeroy] {
	all := []velox.Dialect{velox.Postgres, velox.MySQL, velox.SQLite}
	return zeroyMeta.Load(func() velox.Descriptor[zeroy] {
		return velox.Descriptor[zeroy]{
			Table: "zeroies",
			Columns: []velox.ColumnDescriptor{
				{Field: "ID", Name: "id"}, {Field: "Name", Name: "name"},
				{Field: "Seats", Name: "seats", DBDefault: all},
				{Field: "Rate", Name: "rate", DBDefault: all, Decimal: [2]uint8{10, 4}},
				{Field: "Active", Name: "active", DBDefault: all},
				{Field: "Plan", Name: "plan", DBDefault: all},
			},
			PrimaryKey: []int{0},
			FieldPtr: func(x *zeroy, i int) any {
				return [...]any{&x.ID, &x.Name, &x.Seats, &x.Rate, &x.Active, &x.Plan}[i]
			},
		}
	})
}

var zeroies = struct {
	Name   velox.StringCol[zeroy, string]
	Seats  velox.NumberCol[zeroy, int64]
	Rate   velox.NumberCol[zeroy, float64]
	Active velox.Col[zeroy, bool]
	Plan   velox.StringCol[zeroy, string]
}{velox.StringCol[zeroy, string]{I: 1}, velox.NumberCol[zeroy, int64]{I: 2}, velox.NumberCol[zeroy, float64]{I: 3},
	velox.Col[zeroy, bool]{I: 4}, velox.StringCol[zeroy, string]{I: 5}}

func freshZeroies(t *testing.T, tg target) {
	ddl := `CREATE TABLE zeroies (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE,
		seats INTEGER NOT NULL DEFAULT 100, rate NUMERIC NOT NULL DEFAULT 1.5,
		active BOOLEAN NOT NULL DEFAULT true, plan TEXT NOT NULL DEFAULT 'free')`
	switch tg.d {
	case velox.Postgres:
		ddl = `CREATE TABLE zeroies (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE,
			seats bigint NOT NULL DEFAULT 100, rate numeric(10,4) NOT NULL DEFAULT 1.5,
			active boolean NOT NULL DEFAULT true, plan text NOT NULL DEFAULT 'free')`
	case velox.MySQL:
		ddl = "CREATE TABLE zeroies (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(64) NOT NULL UNIQUE, " +
			"seats BIGINT NOT NULL DEFAULT 100, rate DECIMAL(10,4) NOT NULL DEFAULT 1.5, " +
			"active BOOLEAN NOT NULL DEFAULT true, plan VARCHAR(16) NOT NULL DEFAULT 'free')"
	}
	tg.exec(t, "DROP TABLE IF EXISTS zeroies")
	tg.exec(t, ddl)
	t.Cleanup(func() { tg.exec(t, "DROP TABLE IF EXISTS zeroies") })
}

// storedZeroy reads name's row as the database holds it, without velox.
func storedZeroy(t *testing.T, tg target, name string) zeroy {
	t.Helper()
	q := "SELECT seats, rate, active, plan FROM zeroies WHERE name = ?"
	if tg.d == velox.Postgres {
		q = "SELECT seats, rate, active, plan FROM zeroies WHERE name = $1"
	}
	var z zeroy
	if err := tg.direct.QueryRowContext(ctx, q, name).Scan(&z.Seats, &z.Rate, &z.Active, &z.Plan); err != nil {
		t.Fatal(err)
	}
	return z
}

// zeroInput is an Input whose Setters give each column's zero, as a create
// input's present zero fields do.
type zeroInput struct{}

func (zeroInput) Setters() ([]velox.Setter[zeroy], error) {
	Z := zeroies
	return []velox.Setter[zeroy]{Z.Seats.Set(0), Z.Rate.Set(0), Z.Active.Set(false), Z.Plan.Set("")}, nil
}

// TestInsertExplicitZero: a setter's zero is stored over the column's
// declared database default on each database, in Insert, through
// SetInput, in InsertAll and in an upsert's inserted rows; a zero field no
// setter names gets the default (ADR 0136).
func TestInsertExplicitZero(t *testing.T) {
	each(t, func(t *testing.T, tg target) {
		freshZeroies(t, tg)
		Z := zeroies
		zeros := []velox.Setter[zeroy]{Z.Seats.Set(0), Z.Rate.Set(0), Z.Active.Set(false), Z.Plan.Set("")}
		cases := []struct {
			name string
			run  func(name string) error
		}{
			{"set", func(name string) error { return tg.db.Insert(&zeroy{Name: name}).Set(zeros...).Exec(ctx) }},
			{"input", func(name string) error { return tg.db.Insert(&zeroy{Name: name}).SetInput(zeroInput{}).Exec(ctx) }},
			{"upsert", func(name string) error {
				return tg.db.Insert(&zeroy{Name: name}).Set(zeros...).OnConflict(Z.Name).Update(Z.Plan).Exec(ctx)
			}},
			{"all", func(name string) error {
				return tg.db.InsertAll([]zeroy{{Name: name}, {Name: name + "2", Seats: 3}}).Set(zeros...).Exec(ctx)
			}},
			{"allupsert", func(name string) error {
				return tg.db.InsertAll([]zeroy{{Name: name}, {Name: name + "2"}}).Set(zeros...).
					OnConflict(Z.Name).Update(Z.Seats).Exec(ctx)
			}},
		}
		for _, c := range cases {
			if err := c.run(c.name); err != nil {
				t.Fatalf("%s: %v", c.name, err)
			}
			if z := storedZeroy(t, tg, c.name); z.Seats != 0 || z.Rate != 0 || z.Active || z.Plan != "" {
				t.Errorf("%s: stored %+v; want zeros", c.name, z)
			}
		}
		x := zeroy{Name: "unset"}
		if err := tg.db.Insert(&x).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if z := storedZeroy(t, tg, "unset"); z.Seats != 100 || z.Rate != 1.5 || !z.Active || z.Plan != "free" {
			t.Errorf("unset: stored %+v; want the defaults", z)
		}
		if x.Seats != 100 || x.Rate != 1.5 || !x.Active || x.Plan != "free" {
			t.Errorf("unset: read back %+v; want the defaults", x)
		}
	})
}

// Package colgen writes orm/columns.go: the column types of package orm,
// which are one type per set of methods a column has, twenty-four of them
// with the same few methods. Written out by hand they would be seven hundred
// lines that must agree with each other; here each method is said once.
//
//	go generate ./orm
package colgen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// level is what a column's values can be asked: each level has what the
// one before it has.
type level struct {
	name string
	doc  string // "a column " + doc
	ops  []string
	sort bool
	add  bool
}

var levels = []level{
	{name: "Value", doc: "whose values are only stored and read back: JSON, bytes"},
	{name: "Bool", doc: "whose values are compared for equality: a bool", ops: []string{"EQ", "NEQ"}, sort: true},
	{name: "Enum", doc: "whose values are one of a set: an enum, a key of an edge", ops: []string{"EQ", "NEQ", "In", "NotIn"}, sort: true},
	{name: "Ordered", doc: "whose values have an order: a time, a UUID, an id", ops: []string{"EQ", "NEQ", "In", "NotIn", "GT", "GTE", "LT", "LTE"}, sort: true},
	{name: "Number", doc: "of numbers", ops: []string{"EQ", "NEQ", "In", "NotIn", "GT", "GTE", "LT", "LTE"}, sort: true, add: true},
	{name: "String", doc: "of strings", ops: []string{"EQ", "NEQ", "In", "NotIn", "GT", "GTE", "LT", "LTE", "Contains", "HasPrefix", "HasSuffix", "EqualFold", "ContainsFold"}, sort: true},
}

// below lists, for each level, the levels a column of it can be seen as:
// itself and every level whose methods it has.
var below = map[string][]string{
	"Value":   {"Value"},
	"Bool":    {"Value", "Bool"},
	"Enum":    {"Value", "Bool", "Enum"},
	"Ordered": {"Value", "Bool", "Enum", "Ordered"},
	"Number":  {"Value", "Bool", "Enum", "Ordered", "Number"},
	"String":  {"Value", "Bool", "Enum", "Ordered", "String"},
}

var opDoc = map[string]string{
	"EQ": "matches the rows whose column equals v.", "NEQ": "matches the rows whose column differs from v.",
	"In": "matches the rows whose column is one of vs; without any, none.", "NotIn": "matches the rows whose column is none of vs.",
	"GT": "matches the rows whose column is greater than v.", "GTE": "matches the rows whose column is v or greater.",
	"LT": "matches the rows whose column is less than v.", "LTE": "matches the rows whose column is v or less.",
	"Contains": "matches the rows whose column contains v.", "ContainsFold": "matches the rows whose column contains v, whatever the case.",
	"HasPrefix": "matches the rows whose column starts with v.", "HasSuffix": "matches the rows whose column ends with v.",
	"EqualFold": "matches the rows whose column equals v, whatever the case.",
}

// Name returns the name of the column type of a level: NullableAutoOrderedColumn.
func Name(lv string, nullable, auto bool) string {
	n := ""
	if nullable {
		n += "Nullable"
	}
	if auto {
		n += "Auto"
	}
	return n + lv + "Column"
}

// Levels returns the names of the levels, lowest first.
func Levels() []string {
	out := make([]string, len(levels))
	for i, l := range levels {
		out[i] = l.name
	}
	return out
}

const head = `// Code generated by colgen (go generate ./orm). DO NOT EDIT.

//go:build go1.27

package orm

// The column types. A generated entity package declares each column of its
// entity as a variable of one of them,
//
//	Title = orm.StringColumn[string, predicate.Post](ColumnTitle)
//
// and the methods of the variable build what a query or a mutation of the
// entity takes: post.Title.EQ("a") is a condition, post.Title.Set("a") an
// assignment, post.Title.Asc() an order term. T is the Go type of the
// column's values and E the predicate type of its entity, so a value of
// another type, and a condition, an assignment or an order term of another
// entity, do not compile.
//
// There is a type per set of methods a column has. Which methods compare
// follows from the level (ValueColumn, BoolColumn, EnumColumn, OrderedColumn,
// NumberColumn, StringColumn: each has what the one before it has, and
// NumberColumn and StringColumn both extend OrderedColumn); a Nullable type
// has Clear, an Auto type, the type of a column with an update default, has
// Keep. A method a column does not have is a compile error at its call.
//
// Every method has a type parameter of its own, Lazy[T], which a call never
// writes. It is what makes these types cost a program nothing it does not
// use: an ordinary method of a generic type is compiled, with the rest of
// the type's methods, in every package that so much as names a variable of
// the type, where a method with a type parameter is compiled where it is
// called. Measured on a schema of 450 entities and 312 packages that use
// them (benchmarks/fixtures/realistic/README.md): generated column types,
// 50.7 CPU-s for the entities' packages and 92.3 for the users; these types
// with ordinary methods, 35-45%% and 20%% more; with Lazy, 24.6 and 95.5.
//
// The As methods give a column as the plain type of a level it has, for a
// function written once for several entities:
//
//	func recent[E orm.Predicate](created *orm.OrderedColumn[time.Time, E], since time.Time) E {
//		return created.GTE(since)
//	}
//
//	velox.Post.Query(conn).Where(recent(post.UpdatedAt.AsOrdered(), since))

// Lazy is the type parameter of a method that needs none: it is inferred
// from the type parameter of the receiver, so a call does not write it, and
// it makes the method one that is compiled where it is called and not where
// its receiver's type is named. See the column types.
type Lazy[T any] interface{ *T }

// SetterOf is an assignment of a mutation of the entity whose predicate type
// is E: what the Set of a builder takes. A generated predicate package names
// it per entity, predicate.PostSetter.
type SetterOf[E Predicate] S

// OrderOf is an order term of a query of the entity whose predicate type is
// E: what OrderBy takes. A generated predicate package names it per entity,
// predicate.PostOrderTerm.
type OrderOf[E Predicate] O

// operands returns vs as the operand of an In.
func operands[T any](vs []T) []any {
	a := make([]any, len(vs))
	for i, v := range vs {
		a[i] = v
	}
	return a
}

`

// Source returns the source of orm/columns.go.
func Source() ([]byte, error) {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	b.WriteString(strings.ReplaceAll(head, "%%", "%"))
	const g = "[_ Lazy[T]]"
	text := map[string]bool{"Contains": true, "HasPrefix": true, "HasSuffix": true, "EqualFold": true, "ContainsFold": true}
	for _, lv := range levels {
		for _, nullable := range []bool{false, true} {
			for _, auto := range []bool{false, true} {
				name := Name(lv.name, nullable, auto)
				doc := name + " is a column " + lv.doc
				switch {
				case nullable && auto:
					doc += ", that can hold NULL and be cleared, and has an update default"
				case nullable:
					doc += ", that can hold NULL and be cleared"
				case auto:
					doc += ", that has an update default"
				}
				w("// %s.\ntype %s[T any, E Predicate] string\n\n", doc, name)
				r := fmt.Sprintf("func (c *%s[T, E])", name)
				for _, op := range lv.ops {
					w("// %s %s\n", op, opDoc[op])
					switch {
					case op == "In" || op == "NotIn":
						w("%s %s%s(vs ...T) E { return E(P{Op: Op%s, Col: string(*c), Val: operands(vs)}) }\n\n", r, op, g, op)
					case text[op]:
						w("%s %s%s(v string) E { return E(P{Op: Op%s, Col: string(*c), Val: v}) }\n\n", r, op, g, op)
					default:
						w("%s %s%s(v T) E { return E(P{Op: Op%s, Col: string(*c), Val: v}) }\n\n", r, op, g, op)
					}
				}
				w("// IsNil matches the rows whose column is NULL.\n%s IsNil%s() E { return E(P{Op: OpIsNil, Col: string(*c)}) }\n\n", r, g)
				w("// NotNil matches the rows whose column is not NULL.\n%s NotNil%s() E { return E(P{Op: OpNotNil, Col: string(*c)}) }\n\n", r, g)
				w("// Set assigns v to the column.\n%s Set%s(v T) SetterOf[E] { return SetterOf[E]{Kind: SetValue, Col: string(*c), Val: v} }\n\n", r, g)
				w("// SetNillable assigns *v to the column, or nothing when v is nil: the setter\n// for an input field the caller may have left out.\n%s SetNillable%s(v *T) SetterOf[E] {\n\tif v == nil {\n\t\treturn SetterOf[E]{}\n\t}\n\treturn SetterOf[E]{Kind: SetValue, Col: string(*c), Val: *v}\n}\n\n", r, g)
				if nullable {
					w("// Clear sets the column to NULL.\n%s Clear%s() SetterOf[E] { return SetterOf[E]{Kind: SetNull, Col: string(*c)} }\n\n", r, g)
				}
				if auto {
					w("// Keep leaves the column as it is in an update: its update default (for an\n// updated_at, the time of the update) is not applied. For a change that is\n// not the user's, such as a recomputed total.\n%s Keep%s() SetterOf[E] { return SetterOf[E]{Kind: SetKeep, Col: string(*c)} }\n\n", r, g)
				}
				if lv.add {
					w("// Add increments the column by v.\n%s Add%s(v T) SetterOf[E] { return SetterOf[E]{Kind: SetAdd, Col: string(*c), Val: v} }\n\n", r, g)
				}
				if lv.sort {
					w("// Asc orders by the column, smallest first.\n%s Asc%s() OrderOf[E] { return OrderOf[E]{Col: string(*c)} }\n\n", r, g)
					w("// Desc orders by the column, greatest first.\n%s Desc%s() OrderOf[E] { return OrderOf[E]{Col: string(*c), Desc: true} }\n\n", r, g)
				}
				for _, as := range below[lv.name] {
					plain := Name(as, false, false)
					w("// As%[1]s returns the column as %[4]s %[2]s: what a function written once for\n// several entities takes.\n%[3]s As%[1]s%[5]s() *%[2]s[T, E] { return (*%[2]s[T, E])(c) }\n\n", as, plain, r, article(plain), g)
				}
			}
		}
	}
	return format.Source(b.Bytes())
}

func article(s string) string {
	if strings.ContainsRune("AEIOU", rune(s[0])) {
		return "an"
	}
	return "a"
}

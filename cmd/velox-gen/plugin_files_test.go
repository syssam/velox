// sdlFiles is what velox-graphql:sdlfiles=entity answers, in small: a root
// SDL file, one per entity, and a Go file of the package.
func sdlFiles(t *testing.T, v string) string {
	t.Helper()
	return filesEnv(t,
		plugin.File{Path: "velox.graphql", Content: "# " + v + "\nscalar Time\n"},
		plugin.File{Path: "velox_user.graphql", Content: "# " + v + "\ntype User { id: ID! }\n"},
		plugin.File{Path: "velox_tag.graphql", Content: "# " + v + "\ntype Tag { id: ID! }\n"},
		plugin.File{Path: "gql.go", Content: "package veloxgen\n\n// V is the variant.\nconst V = \"" + v + "\"\n"},
	)
}

// With -files schema, a plugin's .graphql files go to schema/ at their
// paths, and its .go file stays in -out. A second run writes nothing,
// -check and verify pass, and the rerun command carries -files.
func TestPluginFilesDir(t *testing.T) {
	dir := pluginModule(t)
	env := fakeEnv(sdlFiles(t, "1"))
	args := []string{"-files", "schema", "-plugin", "fakeplugin", "./veloxschema"}
	code, out, errs := veloxEnv(t, dir, env, args...)
	if code != 0 {
		t.Fatalf("generate: %d %q %q", code, out, errs)
	}
	for _, p := range []string{"schema/velox.graphql", "schema/velox_user.graphql", "schema/velox_tag.graphql", "veloxgen/gql.go"} {
		if !strings.Contains(out, p+"\n") {
			t.Errorf("stdout lacks %s: %q", p, out)
		}
	}
	if got := strings.Join(names(t, filepath.Join(dir, "schema")), " "); got != "velox.graphql velox_tag.graphql velox_user.graphql" {
		t.Errorf("schema holds %s", got)
	}
	if got := names(t, filepath.Join(dir, "veloxgen")); slices.ContainsFunc(got, func(n string) bool { return strings.HasSuffix(n, ".graphql") }) {
		t.Errorf("veloxgen holds SDL: %v", got)
	}
	if got, want := read(t, filepath.Join(dir, "schema", "velox_user.graphql")), "# Code generated by velox-gen. DO NOT EDIT.\n\n# 1\ntype User { id: ID! }\n"; got != want {
		t.Errorf("velox_user.graphql = %q, want %q", got, want)
	}
	if code, out, errs := veloxEnv(t, dir, env, args...); code != 0 || out != "" || errs != "" {
		t.Errorf("second run: %d %q %q", code, out, errs)
	}
	if code, out, errs := veloxEnv(t, dir, env, append([]string{"-check"}, args...)...); code != 0 || out != "" || errs != "" {
		t.Errorf("-check: %d %q %q", code, out, errs)
	}
	if code, out, errs := veloxEnv(t, dir, env, append([]string{"verify"}, args...)...); code != 0 {
		t.Errorf("verify: %d %q %q", code, out, errs)
	}

	// A changed SDL: -check names the files in schema/ and the command.
	code, _, errs = veloxEnv(t, dir, fakeEnv(sdlFiles(t, "2")), append([]string{"-check"}, args...)...)
	if code != 3 || !strings.Contains(errs, "velox-gen: schema/velox_user.graphql is out of date\n") ||
		!strings.HasSuffix(errs, "velox-gen: run go tool velox-gen -files schema -plugin fakeplugin ./veloxschema\n") {
		t.Errorf("-check of a change: %d %q", code, errs)
	}
}

// Under -files, -check reports a missing file and a stale one, and a run
// removes the stale one with the directory that leaves empty, but never
// -files itself, a file without the header, whatever its name, or a .go
// file.
func TestPluginFilesDirStale(t *testing.T) {
	dir := pluginModule(t)
	schema := filepath.Join(dir, "schema")
	nested := filesEnv(t,
		plugin.File{Path: "velox.graphql", Content: "scalar Time\n"},
		plugin.File{Path: "more/velox_user.graphql", Content: "type User { id: ID! }\n"},
	)
	args := []string{"-files", "schema", "-plugin", "fakeplugin", "./veloxschema"}
	if code, out, errs := veloxEnv(t, dir, fakeEnv(nested), args...); code != 0 {
		t.Fatalf("generate: %d %q %q", code, out, errs)
	}
	const mine = "# mine, no header\ntype Mine { id: ID! }\n"
	writeFile(t, filepath.Join(schema, "foo.graphql"), mine)
	writeFile(t, filepath.Join(schema, "velox_foo.graphql"), mine)
	writeFile(t, filepath.Join(schema, "x.go"), "// Code generated by velox-gen. DO NOT EDIT.\n\npackage schema\n")
	if err := os.Remove(filepath.Join(schema, "velox.graphql")); err != nil {
		t.Fatal(err)
	}

	only := filesEnv(t, plugin.File{Path: "velox.graphql", Content: "scalar Time\n"})
	code, _, errs := veloxEnv(t, dir, fakeEnv(only), append([]string{"-check"}, args...)...)
	if code != 3 || !strings.Contains(errs, "velox-gen: schema/velox.graphql is missing\n") ||
		!strings.Contains(errs, "velox-gen: schema/more/velox_user.graphql is no longer generated; a run removes it\n") ||
		strings.Contains(errs, "foo.graphql") || strings.Contains(errs, "x.go") {
		t.Errorf("-check: %d %q", code, errs)
	}
	code, out, errs := veloxEnv(t, dir, fakeEnv(only), args...)
	if code != 0 || out != "schema/more/velox_user.graphql\nschema/velox.graphql\n" {
		t.Fatalf("generate: %d %q %q", code, out, errs)
	}
	if got := strings.Join(names(t, schema), " "); got != "foo.graphql velox.graphql velox_foo.graphql x.go" {
		t.Errorf("schema holds %s", got)
	}
	for _, f := range []string{"foo.graphql", "velox_foo.graphql"} {
		if got := read(t, filepath.Join(schema, f)); got != mine {
			t.Errorf("%s changed: %q", f, got)
		}
	}

	// With no plugin file left, -files is kept, empty of generated files.
	if code, out, errs := veloxEnv(t, dir, fakeEnv(filesEnv(t)), args...); code != 0 || out != "schema/velox.graphql\n" {
		t.Fatalf("generate with no files: %d %q %q", code, out, errs)
	}
	if got := strings.Join(names(t, schema), " "); got != "foo.graphql velox_foo.graphql x.go" {
		t.Errorf("schema holds %s", got)
	}
}

// A file without the header where a plugin's file goes under -files is
// refused, and nothing is written.
func TestPluginFilesDirRefusesAFileOfYours(t *testing.T) {
	dir := pluginModule(t)
	const mine = "# mine\nscalar Time\n"
	writeFile(t, filepath.Join(dir, "schema", "velox.graphql"), mine)
	code, out, errs := veloxEnv(t, dir, fakeEnv(sdlFiles(t, "1")), "-files", "schema", "-plugin", "fakeplugin", "./veloxschema")
	if code != 1 || out != "" || errs != "velox-gen: schema/velox.graphql was not written by velox-gen; move it\n" {
		t.Errorf("%d %q %q", code, out, errs)
	}
	if got := read(t, filepath.Join(dir, "schema", "velox.graphql")); got != mine {
		t.Errorf("velox.graphql changed: %q", got)
	}
	if got := names(t, filepath.Join(dir, "veloxgen")); got != nil {
		t.Errorf("veloxgen was written: %v", got)
	}
}

// Moving the SDL with -files: the first run with it writes schema/ and
// removes the SDL that a run without it left in -out, and keeps the .go
// file; dropping -files moves it back, and leaves schema/'s files, which no
// sweep reaches, to be deleted by hand.
func TestPluginFilesDirSwitch(t *testing.T) {
	dir := pluginModule(t)
	env := fakeEnv(sdlFiles(t, "1"))
	if code, out, errs := veloxEnv(t, dir, env, "-plugin", "fakeplugin", "./veloxschema"); code != 0 {
		t.Fatalf("without -files: %d %q %q", code, out, errs)
	}
	gen := filepath.Join(dir, "veloxgen")
	if !slices.Contains(names(t, gen), "velox_user.graphql") {
		t.Fatalf("veloxgen holds %v", names(t, gen))
	}
	code, _, errs := veloxEnv(t, dir, env, "-check", "-files", "schema", "-plugin", "fakeplugin", "./veloxschema")
	if code != 3 || !strings.Contains(errs, "velox-gen: veloxgen/velox_user.graphql is no longer generated; a run removes it\n") ||
		!strings.Contains(errs, "velox-gen: schema/velox_user.graphql is missing\n") {
		t.Errorf("-check: %d %q", code, errs)
	}
	code, out, errs := veloxEnv(t, dir, env, "-files", "schema", "-plugin", "fakeplugin", "./veloxschema")
	want := "schema/velox.graphql\nschema/velox_tag.graphql\nschema/velox_user.graphql\nveloxgen/velox.graphql\nveloxgen/velox_tag.graphql\nveloxgen/velox_user.graphql\n"
	if code != 0 || out != want {
		t.Fatalf("with -files: %d %q %q, want %q", code, out, errs, want)
	}
	if got := strings.Join(names(t, gen), " "); got != "gql.go tag.go user.go velox.go" {
		t.Errorf("veloxgen holds %s", got)
	}

	// Without -files the SDL is in -out again; schema/'s copies stay.
	code, out, errs = veloxEnv(t, dir, env, "-plugin", "fakeplugin", "./veloxschema")
	if code != 0 || out != "veloxgen/velox.graphql\nveloxgen/velox_tag.graphql\nveloxgen/velox_user.graphql\n" {
		t.Fatalf("without -files again: %d %q %q", code, out, errs)
	}
	if got := len(names(t, filepath.Join(dir, "schema"))); got != 3 {
		t.Errorf("schema holds %d files, want the 3 left", got)
	}
}

// -files names a directory strictly inside the output module, outside -out's
// tree and not above it, below no other module or velox-gen output; -files
// equal to -out is as without it. A refusal writes nothing.
func TestPluginFilesDirRefusals(t *testing.T) {
	dir := pluginModule(t)
	outside := t.TempDir()
	if err := os.Symlink(outside, filepath.Join(dir, "away")); err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(dir, "sub", "go.mod"), "module example.com/sub\n\ngo 1.27\n")
	writeFile(t, filepath.Join(dir, "afile"), "x\n")
	env := fakeEnv(sdlFiles(t, "1"))
	for _, c := range []struct{ files, why string }{
		{"../x", "is outside the module"},
		{outside, "is outside the module"},
		{"away/schema", "is outside the module"},
		{".", "is the module's root"},
		{"veloxgen/schema", "is inside -out"},
		{"sub/schema", "is in another module or velox-gen output: sub"},
		{"afile/schema", "afile is not a directory"},
	} {
		for _, cmd := range []string{"generate", "verify"} {
			code, out, errs := veloxEnv(t, dir, env, cmd, "-files", c.files, "-plugin", "fakeplugin", "./veloxschema")
			if code != 1 || out != "" || !strings.Contains(errs, "-files "+c.files+": ") || !strings.Contains(errs, c.why) {
				t.Errorf("%s -files %s: %d %q %q; want %q", cmd, c.files, code, out, errs, c.why)
			}
		}
	}
	if got := names(t, filepath.Join(dir, "veloxgen")); got != nil {
		t.Errorf("a refusal wrote %v", got)
	}
	if got := names(t, outside); got != nil {
		t.Errorf("a refusal wrote %v outside", got)
	}

	// -out below -files is refused too; -files equal to -out is as without it.
	if code, _, errs := veloxEnv(t, dir, env, "-out", "app/veloxgen", "-files", "app", "-plugin", "fakeplugin", "./veloxschema"); code != 1 || !strings.Contains(errs, "-files app: it holds -out") {
		t.Errorf("-files above -out: %d %q", code, errs)
	}
	if code, out, errs := veloxEnv(t, dir, env, "-files", "veloxgen", "-plugin", "fakeplugin", "./veloxschema"); code != 0 || !strings.Contains(out, "veloxgen/velox_user.graphql\n") {
		t.Errorf("-files equal to -out: %d %q %q", code, out, errs)
	}
}

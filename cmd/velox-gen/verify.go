// verifyPrefix starts the name of each directory runProgram makes.
const verifyPrefix = ".velox-verify-"

// runProgram builds src as a main package in a new .velox-verify-* directory
// of the module at modDir and runs it, with stdout and stderr connected, and
// removes the directory afterwards. It first removes the directories older
// runs left behind (sweepVerifyDirs). When ctx is done, as on an interrupt,
// it interrupts the command (gently, see gentle), says so and returns
// interruptedCode, as it does when the command dies of a signal and ctx is
// done soon after; when the program does not build, it says why go's errors
// may be in the generated package. It returns the exit code of velox-gen.
func runProgram(ctx context.Context, modDir string, src []byte, env []string, stdout, stderr io.Writer) int {
	sweepVerifyDirs(modDir, time.Now())
	tmp, err := os.MkdirTemp(modDir, verifyPrefix)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "velox-gen verify: %v\n", err)
		return 1
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	if err := os.WriteFile(filepath.Join(tmp, "main.go"), src, 0o644); err != nil {
		_, _ = fmt.Fprintf(stderr, "velox-gen verify: %v\n", err)
		return 1
	}
	bin := filepath.Join(tmp, "check")
	if runtime.GOOS == "windows" {
		bin += ".exe"
	}
	build := gentle(exec.CommandContext(ctx, "go", "build", "-o", bin, "./"+filepath.Base(tmp)))
	build.Dir, build.Env, build.Stdout, build.Stderr = modDir, env, stdout, stderr
	err = build.Run()
	if interrupted(ctx, err) {
		_, _ = fmt.Fprintln(stderr, "velox-gen verify: interrupted")
		return interruptedCode
	}
	if err != nil {
		if exit, ok := errors.AsType[*exec.ExitError](err); !ok || exit.ExitCode() == -1 { // an exit of go's own, not a signal, means go printed why
			_, _ = fmt.Fprintf(stderr, "velox-gen verify: %v\n", err)
			return 1
		}
		_, _ = fmt.Fprintln(stderr, "velox-gen verify: the check program did not build; the generated package may be stale or edited by hand: run velox-gen, then verify again")
		return 1
	}
	run := gentle(exec.CommandContext(ctx, bin))
	run.Dir, run.Env, run.Stdout, run.Stderr = modDir, env, stdout, stderr
	err = run.Run()
	if interrupted(ctx, err) {
		_, _ = fmt.Fprintln(stderr, "velox-gen verify: interrupted")
		return interruptedCode
	}
	if err != nil {
		if exit, ok := errors.AsType[*exec.ExitError](err); !ok || exit.ExitCode() == -1 { // an exit of the program's own, not a signal, means it printed why
			_, _ = fmt.Fprintf(stderr, "velox-gen verify: %v\n", err)
		}
		return 1
	}
	return 0
}

// gentle makes c, when its context is done, send os.Interrupt rather than
// kill, and wait up to 5s for it to exit before it is killed, so that go
// build cleans up after itself; Windows cannot send os.Interrupt to a
// process, so there c is killed at once.
func gentle(c *exec.Cmd) *exec.Cmd {
	if runtime.GOOS != "windows" {
		c.Cancel = func() error { return c.Process.Signal(os.Interrupt) }
		c.WaitDelay = 5 * time.Second
	}
	return c
}

// interruptGrace is how long interrupted waits, after a command died of a
// signal, for ctx to be done.
var interruptGrace = time.Second

// interrupted reports whether a command's run, which returned err, was
// interrupted: ctx is done, or the command died of a signal and ctx is done
// within interruptGrace. A terminal's Ctrl-C reaches the command too, which
// can die of it before velox-gen's own handler cancels ctx.
func interrupted(ctx context.Context, err error) bool {
	if ctx.Err() != nil {
		return true
	}
	if exit, ok := errors.AsType[*exec.ExitError](err); !ok || exit.ExitCode() != -1 {
		return false
	}
	select {
	case <-ctx.Done():
		return true
	case <-time.After(interruptGrace):
		return false
	}
}

// sweepVerifyDirs removes the .velox-verify-* directories of modDir last
// modified over an hour before now: a verify that was killed left them
// behind, and one younger may be another verify's, still running. It removes
// what it can and reports nothing.
func sweepVerifyDirs(modDir string, now time.Time) {
	entries, err := os.ReadDir(modDir)
	if err != nil {
		return
	}
	for _, e := range entries {
		if !e.IsDir() || !strings.HasPrefix(e.Name(), verifyPrefix) {
			continue
		}
		if fi, err := e.Info(); err == nil && now.Sub(fi.ModTime()) > time.Hour {
			_ = os.RemoveAll(filepath.Join(modDir, e.Name()))
		}
	}
}

// checkProgram is a main package that imports the packages ([alias, path]),
// calls velox.CheckEntity for each type (alias.Name) and velox.CheckRelation
// for each relation handle (alias.Handles.Relation), and exits 1 when any
// reports an error. Each failing check counts once in the "with errors"
// total.
func checkProgram(imports [][2]string, types, rels []string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by velox-gen verify, which deletes it after running.\n\npackage main\n\nimport (\n\t\"fmt\"\n\t\"os\"\n\n\tvelox %q\n", veloxPath)
	for _, im := range imports {
		fmt.Fprintf(&b, "\t%s %q\n", im[0], im[1])
	}
	b.WriteString(")\n\nfunc main() {\n\tfailed := 0\n\tfor _, err := range []error{\n")
	for _, t := range types {
		fmt.Fprintf(&b, "\t\tvelox.CheckEntity[%s](),\n", t)
	}
	for _, r := range rels {
		fmt.Fprintf(&b, "\t\tvelox.CheckRelation(%s),\n", r)
	}
	fmt.Fprintf(&b, "\t} {\n\t\tif err != nil {\n\t\t\tfmt.Fprintln(os.Stderr, err)\n\t\t\tfailed++\n\t\t}\n\t}\n"+
		"\tfmt.Printf(\"velox-gen verify: %%d entities, %%d with errors\\n\", %d, failed)\n"+
		"\tif failed > 0 {\n\t\tos.Exit(1)\n\t}\n}\n", len(types))
	return b.Bytes()
}

package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/token"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"

	"golang.org/x/tools/go/packages"
)

// runVerify builds every entity's metadata in a temporary program, inside the
// module of the loaded packages, and prints what it reports: a mistake in a
// Schema or Mixin method, or generated code that is out of date. The program
// lives in a directory named .velox-verify-*, which ./... ignores, and is
// removed afterwards.
func runVerify(cfg config, ps []*packages.Package, stdout, stderr io.Writer) int {
	var ents []*entity
	var probs []problem
	for _, p := range ps {
		e, pr := discover(p, cfg)
		ents, probs = append(ents, e...), append(probs, pr...)
	}
	if report(stderr, probs) {
		return 1
	}
	var named []*entity
	for _, e := range ents {
		if !token.IsExported(e.name) || e.pkg.Name == "main" {
			_, _ = fmt.Fprintf(stderr, "velox-gen verify: skipping %s.%s, which a program outside its package cannot name\n", e.pkg.Name, e.name)
			continue
		}
		named = append(named, e)
	}
	if len(named) == 0 {
		_, _ = fmt.Fprintln(stdout, "velox-gen verify: no entities")
		return 0
	}
	mod := named[0].pkg.Module
	for _, e := range named {
		if mod == nil || e.pkg.Module == nil || e.pkg.Module.Dir != mod.Dir {
			_, _ = fmt.Fprintln(stderr, "velox-gen verify: the entities must be in one module; run verify once per module")
			return 1
		}
	}
	tmp, err := os.MkdirTemp(mod.Dir, ".velox-verify-")
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "velox-gen verify: %v\n", err)
		return 1
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	if err := os.WriteFile(filepath.Join(tmp, "main.go"), verifyProgram(named), 0o644); err != nil {
		_, _ = fmt.Fprintf(stderr, "velox-gen verify: %v\n", err)
		return 1
	}
	cmd := exec.Command("go", "run", "./"+filepath.Base(tmp))
	cmd.Dir, cmd.Env, cmd.Stdout, cmd.Stderr = mod.Dir, cfg.env, stdout, stderr
	if err := cmd.Run(); err != nil {
		var exit *exec.ExitError
		if !errors.As(err, &exit) { // an ExitError means go already printed why
			_, _ = fmt.Fprintf(stderr, "velox-gen verify: %v\n", err)
		}
		return 1
	}
	return 0
}

// verifyProgram is a main package that calls velox.CheckEntity for every
// entity and exits 1 when any reports an error.
func verifyProgram(ents []*entity) []byte {
	sort.Slice(ents, func(i, j int) bool {
		if ents[i].pkg.PkgPath != ents[j].pkg.PkgPath {
			return ents[i].pkg.PkgPath < ents[j].pkg.PkgPath
		}
		return ents[i].name < ents[j].name
	})
	alias := map[string]string{}
	var paths []string
	for _, e := range ents {
		if _, ok := alias[e.pkg.PkgPath]; !ok {
			alias[e.pkg.PkgPath] = fmt.Sprintf("p%d", len(paths))
			paths = append(paths, e.pkg.PkgPath)
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by velox-gen verify, which deletes it after running.\n\npackage main\n\nimport (\n\t\"fmt\"\n\t\"os\"\n\n\tvelox %q\n", veloxPath)
	for _, p := range paths {
		fmt.Fprintf(&b, "\t%s %q\n", alias[p], p)
	}
	b.WriteString(")\n\nfunc main() {\n\tfailed := 0\n\tfor _, err := range []error{\n")
	for _, e := range ents {
		fmt.Fprintf(&b, "\t\tvelox.CheckEntity[%s.%s](),\n", alias[e.pkg.PkgPath], e.name)
	}
	fmt.Fprintf(&b, "\t} {\n\t\tif err != nil {\n\t\t\tfmt.Fprintln(os.Stderr, err)\n\t\t\tfailed++\n\t\t}\n\t}\n"+
		"\tfmt.Printf(\"velox-gen verify: %%d entities, %%d with errors\\n\", %d, failed)\n"+
		"\tif failed > 0 {\n\t\tos.Exit(1)\n\t}\n}\n", len(ents))
	return b.Bytes()
}

// Command velox-gen generates the Go code of velox entities.
//
// It reads a schema package, a package whose structs embed schema.Schema
// directly: a struct that embeds another struct that embeds it is skipped. It
// writes the gen package: one file, <entity>_velox.go, for every entity and
// for every join entity of a many-to-many relation, and velox.go, which holds
// the enums.
//
// Install it as a tool of your module and run it from the module root:
//
//	go get -tool github.com/syssam/velox/cmd/velox-gen
//	go tool velox-gen ./schema
//
// Usage:
//
//	velox-gen [generate] [-out dir] [-package name] [-plugin tool[:key=value,...]]... [-check] [package]
//	velox-gen verify [-out dir] [-package name] [-plugin tool[:key=value,...]]... [package]
//	velox-gen describe [-json] [package]
//	velox-gen version
//	velox-gen migrate diff [-dir ./migrations] [-dialect d] [-name n] [-allow code[=target],...]
//	                       [-rename-table old=new]... [-rename-column table.old=new]...
//	                       [-lock-timeout 5s] [-check] [-dry-run] [-db dsn] [package]
//	velox-gen migrate apply [-dir ./migrations] [-db dsn] [-to version] [-resume] [-lock-wait 5m] [-dry-run]
//	                        [-baseline version]
//	velox-gen migrate status [-dir ./migrations] [-db dsn] [-json]
//	velox-gen migrate drift [-dir ./migrations] [-db dsn] [-json]
//	velox-gen migrate baseline [-dir ./migrations] -dialect d [-db dsn] [package]
//	velox-gen migrate lint [-dir ./migrations] [-since version]
//	velox-gen migrate hash [-dir ./migrations] [-check]
//	velox-gen migrate resolve [-dir ./migrations] [-db dsn] -version n (-applied | -undone | -statements k | -adopt | -forget)
//	velox-gen migrate sql -dialect postgres|mysql|sqlite [package]
//
// Each subcommand has its own flags; a flag it does not take is a usage
// error. Flags may follow the package, as in "go test ./x -v"; "--" ends them.
// A word that is not a subcommand, or a second package, is a usage error; for
// a word that names a directory the message says to write ./word. The exit
// code is 0 for success, 1 for an error, 2 for misuse and 3 when generated
// files are stale (-check, and verify when a plugin's Go file is out of date)
// or a migration directory is (migrate diff -check and migrate hash -check),
// when migrate status finds pending files and when migrate drift finds a
// change. A command that writes files (generate, migrate diff, migrate hash
// and migrate baseline) holds SIGINT and SIGTERM until its write is done or
// undone, and then exits 130 if one arrived.
//
// The package is one schema package, ./schema when none is named; a pattern
// that names no package, or a package that declares no schemas, is an error
// ("no schemas in ..."), and several packages are a usage error. -out is the
// directory of the generated package (default ./gen) and -package its name
// (default: the base name of -out).
// velox-gen writes nothing when any entity has a problem. Each problem is
// printed as file:line: schema User: field "name": reason, with the file
// relative to the working directory. A misuse of a builder, such as a
// DefaultFunc that is not a func, is reported first, alone; the rules across
// fields, edges and schemas are checked once it is fixed. -check writes
// nothing and exits 3 when a generated file is out of date, missing or left
// over; CI runs it, and it is the check that the generated package matches
// the schema. A run rewrites the files that changed, deletes the generated
// files that no entity produces any more, and prints each path it wrote or
// deleted. It writes, rewrites and deletes only files that start with its
// header "Code generated by velox-gen. DO NOT EDIT." (a .graphqls file's
// header starts with # instead of //); a file of yours at a path it would
// write is an error. The deletion searches -out and its subdirectories, but
// not those whose name starts with "." or "_", nor those that hold a go.mod or
// velox-gen's own velox.go: another module, or another run's output, such as
// -out ./gen/b beside -out ./gen. The files you add to the output directory
// stay, but may not declare a type named like a generated one, nor a Policy
// or Hooks method on a generated entity: those are declared in the schema
// package, on the entity's schema, as func (E) Policy() velox.Policy[gen.E]
// and func (E) Hooks() []velox.Hook[gen.E]. When the schema package declares
// any, velox-gen also writes the package runtime in -out/runtime, which binds
// them into the generated package; a program imports it for its effect. The
// generated package cannot import the schema package then, as the schema
// imports it: what it read from the schema, such as a default function, comes
// through package runtime too, and every entity fails at its first use when
// package runtime is not linked. velox-gen reads the schema package without
// these methods and the declarations only they use, so it runs when the
// generated package is stale or missing. velox-gen refuses any .go file of
// yours, in -out or in the schema package, that some build would leave out,
// by its name or its build constraints, such as x_linux.go, //go:build linux
// or //go:build prod, since the generated code would bind its methods in one
// build and not another; it reads neither a file //go:build ignore leaves out
// nor one whose name starts with "_" or "." or ends in _test.go. A go1.N tag holds when the go line of
// the module's go.mod is go1.N or later. The generated velox.go has the
// package comment, unless a file of yours there has one.
//
// -plugin names a generator plugin, a tool of your module that "go tool" runs
// in the module directory (go get -tool example.com/some/velox-graphql, then
// -plugin velox-graphql; a tool the module lacks fails with that hint); repeat
// it for several. Options for the plugin follow
// a colon, -plugin velox-grpc:go_package=x/pb,mode=a; an option without "=",
// with an empty key, or a key given twice is a usage error (exit 2). velox-gen
// speaks plugin protocol 2, which package github.com/syssam/velox/plugin
// documents: a plugin reads a JSON request on standard input,
// {"plugin_protocol": 2, "generator": "velox-gen <version>", "out_package":
// name, "out_path": the package's import path, "options": {key: value},
// "model": the resolved model}, and writes {"plugin_protocol": 2, "files":
// [{"path": path, "content": text}], "warnings": [text], "error": text} to
// standard output. A path is a slash path below -out, such as pb/user.proto,
// with no "..", "." or empty segment, no directory that starts with "." or
// "_" or is testdata or vendor, ASCII, ending in .go, .graphqls or .proto, a
// .go file go build always builds, by its name and its build constraints (as
// for your own files, but //go:build ignore is refused too), and not a
// velox.go below -out. velox-gen puts its header in
// front of the content, so the plugin's files are checked, rewritten and, when
// the plugin is dropped from the command, deleted like its own, with the
// directories that leaves empty. Each warning is printed as "velox-gen: plugin
// name: warning: text" and never fails the run. A response without
// "plugin_protocol": 2 (a plugin of protocol 1 is told to update), a
// non-empty error, a non-zero exit, a path that is refused, one that velox-gen
// or another plugin writes (paths that differ only in case are one, over the
// whole path), a file of yours or a symbolic link at it or at a directory of
// it, or a directory of yours whose name differs from one of the path's only
// in case (rename it), fails the run before anything is written. A write that
// fails part-way, such as on a full disk, is undone: -out is left as it was.
// An interrupt (SIGINT or SIGTERM) waits until the write is done or undone,
// and velox-gen then exits 130. A run killed while it writes, as by SIGKILL,
// can leave entries named .<name>.tmp-velox-<n>, .<name>.old-velox-<n> or
// .<name>.gone-velox-<n> in -out; the next run puts back a file or directory
// set aside whose name is missing, removes the others, a directory entry by
// entry, keeping a file in it that is not velox-gen's, and prints a line for
// each; -check prints a line for each and exits 3.
// A plugin built on package plugin that panics fails with "the plugin
// panicked: " and the panic's value; run velox-gen with VELOX_PLUGIN_TRACE=1,
// which reaches the plugin, for the stack on the lines below it.
//
// verify builds a program in a temporary .velox-verify-* directory of your
// module, imports the generated package and reports, for every entity, the
// mistakes that velox.CheckEntity finds and, for every relation,
// velox.CheckRelation, whose target the generated metadata does not name. It
// removes the directory, also when interrupted (SIGINT or SIGTERM, which it
// passes on to go build and the program as an interrupt), after which it
// exits 130, as generate and migrate do, and it says so when the program
// does not build, as when the generated package is stale or edited by hand;
// a killed process leaves it behind, and the next verify removes one older
// than an hour; ignore .velox-verify-*/ in git. With -plugin it runs the
// plugins and fails when a Go file of theirs on disk is not what they write
// now; one in -out itself compiles with the rest of the package.
//
// describe prints the entities, columns and relations that the schema package
// (default ./schema) declares; with -json, the model that a plugin receives as
// "model", indented. version prints one line, such as
// "velox-gen v1.2.3 (generated code 7, plugin protocol 2, model 2)".
//
// migrate works on a migration directory, ./migrations unless -dir names
// another, which holds velox.json, schema.json, the migration files and
// velox.sum, as package github.com/syssam/velox/migrate reads them. Each
// path it prints is joined to -dir, and each error is printed as
// "velox-gen: migrate <subcommand>: <text>".
//
// migrate diff loads the schema package (default ./schema), builds its
// tables for the directory's dialect and plans them against schema.json. It
// writes the new files, schema.json and velox.sum, all or nothing, and prints
// their paths. A new directory, one that is missing or holds none of
// velox.json, velox.sum, schema.json and *.sql (a .gitkeep or a Go file
// stays), also gets velox.json, and needs -dialect (postgres, mysql or
// sqlite), which must otherwise agree with velox.json. No change prints "no
// changes". -name names the files (default: from the first change, as
// create_users or add_users_email). A destructive change is refused, with
// the flag that allows it, unless -allow covers it, as -allow
// drop-column=users.name,drop-table; each allowed change is written into the
// file as a -- velox:allow line. -rename-table old=new and -rename-column
// table.old=new, repeatable, name the renames the plan cannot see, a table
// optionally as schema.name; one that names nothing in schema.json is an
// error. -lock-timeout is the lock timeout the files carry (default:
// velox.json's); 0 writes none, so velox.json's applies when they run.
// -dry-run prints each file after "== <path>" and writes nothing. -check
// writes nothing and exits 3 when the schema differs from schema.json or
// velox.sum is out of date; CI runs it. A stale velox.sum is otherwise an
// error: run migrate hash when the edits are intended.
//
// migrate lint checks every file, or those from -since version on: their
// directives and statements, what cannot run in a file's transaction
// (CONCURRENTLY and ALTER TYPE … ADD VALUE on PostgreSQL, BEGIN or COMMIT
// on PostgreSQL and SQLite), and, in a file migrate diff did not write, the
// destructive statements it can read (DROP TABLE, DROP COLUMN, a type
// change, SET NOT NULL, TRUNCATE, and DELETE or UPDATE without WHERE) that no
// -- velox:allow line of the file allows. Each problem is printed as
// "<path>:<line>: <code>: <message>", and any is exit 1.
//
// migrate hash rewrites velox.sum when it does not match the files and
// prints its path; with -check it writes nothing and exits 3 when it does
// not match. A directory without velox.json is an error: migrate diff
// starts one.
//
// migrate apply, status, drift, baseline and resolve open the database -db
// names, a DSN as the driver of the directory's dialect (baseline's
// -dialect) reads it: a pgx connection string, a go-sql-driver/mysql DSN, or
// a SQLite path or URI. Without -db they read $VELOX_DB, which keeps a
// password out of the shell's history; with neither, the subcommand is a
// usage error, as is a DSN not of the dialect's form, which is refused
// before it is used. No message shows the DSN or its password; a SQLite path
// is named. status, drift, baseline and resolve open a SQLite file without
// creating it: one that is not there is an error; apply creates it. SIGINT
// or SIGTERM cancels the run: a file being applied statement by statement is
// left dirty with the reason, one in a transaction is rolled back, and the
// exit code is 1.
//
// migrate apply applies the pending files, as package migrate's Up does,
// and prints "applied <path> in <duration>" for each. -to stops at a
// version, -resume continues a dirty version first, and -lock-wait bounds
// the wait for another runner's lock (default 5m). -dry-run prints each
// file it would apply after "== <path>" and applies nothing. -baseline
// adopts a database made before the directory, as Up's WithBaseline does:
// it records the files up to its version as applied without running them,
// printing "baselined <path>" for each, then applies the rest; it is run
// once on each existing database, and refuses a history that has a row or
// a database with no table. -baseline with -resume or -dry-run, or with -to
// below it, is a usage error. A database
// with versions above the directory's last file is a newer directory's: apply
// says so and applies nothing (exit 0). A dirty version, an applied file that
// was edited or is gone, a stale velox.sum, a lock wait that ran out, or a
// failed file is exit 1; a file that fails part-way is printed with what to
// do next.
//
// migrate status prints a line per version, in version order: "applied
// <version> <path> <time>", the time in RFC 3339 and UTC, "pending <version>
// <path>", "dirty <version> <path>: <n> statement(s) done: <error>" and "ahead
// <version> <name>" for a version above the directory's last file. It exits
// 0 when the database is up to date or ahead, 3 with pending files and 1
// with a dirty version. -json prints {"applied", "pending", "ahead",
// "dirty"} instead, indented, with each file's path relative to the
// directory.
//
// migrate drift compares the database's tables with schema.json, on a
// database at the directory's last version (else exit 1, naming the pending,
// dirty or ahead versions), and prints each difference as "change: <the
// change that would remove it>" and each warning as "warning: <object>:
// <message>". A change is exit 3; warnings alone are not. -json prints
// {"changes": [{"kind", "target", "text"}], "warnings": [{"object",
// "message"}]} instead.
//
// migrate baseline adopts a database made before the directory, such as one
// ent made. It builds the schema package's tables for -dialect, reads them
// from the database as package migrate's Baseline does, and writes a new
// directory, all or nothing: 0001_baseline.sql, which builds them, then
// schema.json, velox.json and velox.sum. It prints their paths, then each
// warning on stderr as "warning: <object>: <message>", and what to run next:
// migrate apply -baseline 1 on each existing database, then migrate drift
// there. A -dir that is a migration directory already is exit 1, as is a
// database that holds none of the schema's tables, a foreign key to a table
// outside them or, on PostgreSQL, a nextval default whose sequence the
// column does not own. No -dialect is exit 2.
//
// migrate resolve ends a dirty version a human finished (-applied, which
// needs its file unchanged) or reverted (-undone, which deletes its row, so
// the file may be edited and applied again), says how many statements of one
// ran (-statements, for apply -resume), records a pending file as applied
// (-applied again), accepts a changed file for an applied version (-adopt)
// and removes the row of a version whose file is gone, differs or never ran
// (-forget). A version not in the state its way needs is exit 1; no -version,
// or not exactly one way, is exit 2. docs/migrations-operations.md has when.
package main


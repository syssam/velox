func main() {
	os.Exit(run(os.Args[1:], ".", nil, os.Stdout, os.Stderr))
}

// run is the command, with its directory, environment and output passed in
// so that tests can run it.
func run(args []string, dir string, env []string, stdout, stderr io.Writer) int {
	if len(args) > 0 && isWord(args[0]) {
		switch args[0] {
		case "generate":
			return runGenCommand("generate", args[1:], dir, env, stdout, stderr)
		case "verify":
			return runGenCommand("verify", args[1:], dir, env, stdout, stderr)
		case "describe":
			return runDescribe(args[1:], dir, env, stdout, stderr)
		case "migrate":
			return runMigrate(args[1:], dir, env, stdout, stderr)
		case "version":
			return runVersion(args[1:], stdout, stderr)
		default:
			hint := ""
			if fi, err := os.Stat(filepath.Join(dir, args[0])); err == nil && fi.IsDir() {
				hint = fmt.Sprintf("; for the package write ./%s", args[0])
			}
			_, _ = fmt.Fprintf(stderr, "velox-gen: unknown subcommand %q%s\n", args[0], hint)
			printUsage(stderr)
			return 2
		}
	}
	return runGenCommand("generate", args, dir, env, stdout, stderr)
}

// isWord reports whether the first argument is meant as a subcommand: a word,
// not a flag and not a package pattern (which has a "/" or a ".").
func isWord(a string) bool {
	return a != "" && !strings.ContainsAny(a, "-/.\\")
}

// runGenCommand is generate or verify, which take the same flags but -check.
func runGenCommand(name string, args []string, dir string, env []string, stdout, stderr io.Writer) int {
	verify := name == "verify"
	fs := newFlagSet(name, stderr)
	var checkOnly *bool
	if !verify {
		checkOnly = fs.Bool("check", false, "write nothing; exit 3 when a generated file is out of date, missing or left over")
	}
	outDir := fs.String("out", "./gen", "the directory of the generated package")
	pkgName := fs.String("package", "", "the generated package's name (default: the base name of -out)")
	var plugins pluginFlag
	fs.Var(&plugins, "plugin", "run the generator plugin `tool`, a tool of your module as go tool names it, on the model; options follow a colon (tool:key=value,...); repeat for several")
	patterns, code, done := parseFlags(fs, args)
	if done {
		return code
	}
	if len(patterns) > 1 {
		return tooMany(name, fs, stderr)
	}
	var rerun []string
	fs.Visit(func(f *flag.Flag) {
		switch f.Name {
		case "out", "package":
			rerun = append(rerun, "-"+f.Name, f.Value.String())
		case "plugin":
			for _, spec := range plugins {
				rerun = append(rerun, "-plugin", spec.raw)
			}
		}
	})
	pattern, err := schemaPackage(dir, patterns, env)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "velox-gen: %v\n", err)
		return 1
	}
	f := genFlags{out: *outDir, pkg: *pkgName, plugins: plugins, rerun: append(rerun, patterns...)}
	if verify {
		return runGenerateVerify(f, pattern, dir, env, stdout, stderr)
	}
	f.check = *checkOnly
	return runGenerate(f, pattern, dir, env, stdout, stderr)
}

// newFlagSet is the flag set of one subcommand, whose usage lists its flags.
func newFlagSet(name string, stderr io.Writer) *flag.FlagSet {
	fs := flag.NewFlagSet("velox-gen "+name, flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.Usage = func() {
		printUsage(stderr)
		_, _ = fmt.Fprintf(stderr, "\nFlags of %s:\n", name)
		fs.PrintDefaults()
	}
	return fs
}

// parseFlags parses args and returns the arguments that are not flags. As
// "go test ./x -v" does, flags may follow the positional arguments; "--" ends
// the flags. It reports done, with the exit code, when the command must stop:
// -h exits 0, a bad flag 2.
func parseFlags(fs *flag.FlagSet, args []string) (rest []string, code int, done bool) {
	for {
		if err := fs.Parse(args); err != nil {
			if errors.Is(err, flag.ErrHelp) {
				return nil, 0, true
			}
			return nil, 2, true
		}
		left := fs.Args()
		if n := len(args) - len(left); n > 0 && args[n-1] == "--" {
			return append(rest, left...), 0, false
		}
		if len(left) == 0 {
			return rest, 0, false
		}
		rest = append(rest, left[0])
		args = left[1:]
	}
}

// tooMany is the usage error of a command that was given more arguments than
// it takes.
func tooMany(name string, fs *flag.FlagSet, stderr io.Writer) int {
	_, _ = fmt.Fprintf(stderr, "velox-gen: %s takes one package\n", name)
	fs.Usage()
	return 2
}

// runVersion is velox-gen version.
func runVersion(args []string, stdout, stderr io.Writer) int {
	fs := newFlagSet("version", stderr)
	rest, code, done := parseFlags(fs, args)
	if done {
		return code
	}
	if len(rest) > 0 {
		_, _ = fmt.Fprintln(stderr, "velox-gen: version takes no arguments")
		printUsage(stderr)
		return 2
	}
	_, _ = fmt.Fprintf(stdout, "%s (generated code %d, plugin protocol %d, model %d)\n",
		generator(), codegen.GeneratedCodeVersion, plugin.ProtocolVersion, plugin.ModelVersion)
	return 0
}


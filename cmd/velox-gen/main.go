// Command velox-gen generates the Go code of velox entities.
//
// It reads a schema package, a package whose structs embed schema.Schema, and
// writes the gen package: one file, <entity>_velox.go, for every entity and
// for every join entity of a many-to-many relation, and velox.go, which holds
// the enums and the hash of the model.
//
// Install it as a tool of your module and run it from the module root:
//
//	go get -tool github.com/syssam/velox2/cmd/velox-gen
//	go tool velox-gen ./schema
//
// Usage:
//
//	velox-gen [generate] [-out dir] [-package name] [-plugin tool[:key=value,...]]... [-check] [package]
//	velox-gen verify [-out dir] [-package name] [-plugin tool[:key=value,...]]... [package]
//	velox-gen describe [-json] [package]
//	velox-gen version
//
// Each subcommand has its own flags; a flag it does not take is a usage
// error. The exit code is 0 for success, 1 for an error, 2 for misuse and 3
// when generated files are stale (-check, and verify when a plugin's Go file
// is out of date).
//
// The package is one schema package, ./schema when none is named; a pattern
// that names no package, several, or a package that declares no schemas is an
// error ("no schemas in ..."). -out is the directory of the generated package
// (default ./gen) and -package its name (default: the base name of -out).
// velox-gen writes nothing when any entity has a problem. Each problem is
// printed as file:line: schema User: field "name": reason, with the file
// relative to the working directory. A misuse of a builder, such as a
// DefaultFunc that is not a func, is reported first, alone; the rules across
// fields, edges and schemas are checked once it is fixed. -check writes
// nothing and exits 1 when a generated file is out of date, missing or left
// over; CI runs it, and it is the check that the generated package matches
// the schema. A run rewrites the files that changed, deletes the generated
// files that no entity produces any more, and prints each path it wrote or
// deleted. It writes, rewrites and deletes only files that start with its
// header "Code generated by velox-gen. DO NOT EDIT." (a .graphqls file's
// header starts with # instead of //); a file of yours at a path it would
// write is an error. The files you add to the output directory
// stay: a method Policy or Hooks on a generated entity E, with receiver *E,
// in a file of yours there, is bound into E's metadata. A value receiver is an
// error, because velox calls the method on a nil *E. Your own file must not
// declare a type named like a generated one.
//
// -plugin names a generator plugin, a tool of your module that "go tool" runs
// in the module directory (go get -tool example.com/some/velox-graphql, then
// -plugin velox-graphql); repeat it for several. Options for the plugin follow
// a colon, -plugin velox-grpc:go_package=x/pb,mode=a; an option without "=",
// with an empty key, or a key given twice is a usage error (exit 2). velox-gen
// speaks plugin protocol 2, which package github.com/syssam/velox2/plugin
// documents: a plugin reads a JSON request on standard input,
// {"plugin_protocol": 2, "generator": "velox-gen <version>", "out_package":
// name, "out_path": the package's import path, "options": {key: value},
// "model": the resolved model}, and writes {"plugin_protocol": 2, "files":
// [{"path": path, "content": text}], "warnings": [text], "error": text} to
// standard output. A path is a slash path below -out, such as pb/user.proto,
// with no "..", "." or empty segment, no directory that starts with "." or
// "_", and ending in .go, .graphqls or .proto. velox-gen puts its header in
// front of the content, so the plugin's files are checked, rewritten and, when
// the plugin is dropped from the command, deleted like its own, with the
// directories that leaves empty. Each warning is printed as "velox-gen: plugin
// name: warning: text" and never fails the run. A response without
// "plugin_protocol": 2 (a plugin of protocol 1 is told to update), a
// non-empty error, a non-zero exit, a path that is refused, one that velox-gen
// or another plugin writes (paths that differ only in case are one, over the
// whole path), a file of yours or a symbolic link at it or at a directory of
// it, or a directory of yours whose name differs from one of the path's only
// in case (rename it), fails the run before anything is written. A write that
// fails part-way, such as on a full disk, leaves -out partly updated; running
// velox-gen again restores it.
//
// verify builds a program in a temporary .velox-verify-* directory of your
// module, imports the generated package and reports, for every entity, the
// mistakes that velox.CheckEntity finds and, for every relation,
// velox.CheckRelation, whose target the generated metadata does not name. It
// removes the directory, but a killed process leaves it behind; ignore
// .velox-verify-*/ in git. With -plugin it runs the plugins and fails when a
// Go file of theirs on disk is not what they write now; one in -out itself
// compiles with the rest of the package.
//
// describe prints the entities, columns and relations that the schema package
// (default ./schema) declares; with -json, the model that a plugin receives as
// "model", indented. version prints one line, such as
// "velox-gen v1.2.3 (generated code 4, plugin protocol 2, model 2)".
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/syssam/velox2/internal/gen"
	"github.com/syssam/velox2/plugin"
)

func main() {
	os.Exit(run(os.Args[1:], ".", nil, os.Stdout, os.Stderr))
}

// run is the command, with its directory, environment and output passed in
// so that tests can run it.
func run(args []string, dir string, env []string, stdout, stderr io.Writer) int {
	if len(args) > 0 && isWord(args[0]) {
		switch args[0] {
		case "generate":
			return runGenCommand("generate", args[1:], dir, env, stdout, stderr)
		case "verify":
			return runGenCommand("verify", args[1:], dir, env, stdout, stderr)
		case "describe":
			return runDescribe(args[1:], dir, env, stdout, stderr)
		case "version":
			return runVersion(args[1:], stdout, stderr)
		default:
			_, _ = fmt.Fprintf(stderr, "velox-gen: unknown subcommand %q\n", args[0])
			printUsage(stderr)
			return 2
		}
	}
	return runGenCommand("generate", args, dir, env, stdout, stderr)
}

// isWord reports whether the first argument is meant as a subcommand: a word,
// not a flag and not a package pattern (which has a "/" or a ".").
func isWord(a string) bool {
	return a != "" && !strings.ContainsAny(a, "-/.\\")
}

// runGenCommand is generate or verify, which take the same flags but -check.
func runGenCommand(name string, args []string, dir string, env []string, stdout, stderr io.Writer) int {
	verify := name == "verify"
	fs := newFlagSet(name, stderr)
	var checkOnly *bool
	if !verify {
		checkOnly = fs.Bool("check", false, "write nothing; exit 3 when a generated file is out of date, missing or left over")
	}
	outDir := fs.String("out", "./gen", "the directory of the generated package")
	pkgName := fs.String("package", "", "the generated package's name (default: the base name of -out)")
	var plugins pluginFlag
	fs.Var(&plugins, "plugin", "run the generator plugin `tool[:key=value,...]` (a tool of your module, as go tool names it, with its options) on the model; repeat for several")
	if code, done := parseFlags(fs, args); done {
		return code
	}
	patterns := fs.Args()
	var rerun []string
	fs.Visit(func(f *flag.Flag) {
		switch f.Name {
		case "out", "package":
			rerun = append(rerun, "-"+f.Name, f.Value.String())
		case "plugin":
			for _, spec := range plugins {
				rerun = append(rerun, "-plugin", spec.raw)
			}
		}
	})
	pattern, err := schemaPackage(dir, patterns, env)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "velox-gen: %v\n", err)
		return 1
	}
	f := genFlags{out: *outDir, pkg: *pkgName, plugins: plugins, rerun: append(rerun, patterns...)}
	if verify {
		return runGenerateVerify(f, pattern, dir, env, stdout, stderr)
	}
	f.check = *checkOnly
	return runGenerate(f, pattern, dir, env, stdout, stderr)
}

// newFlagSet is the flag set of one subcommand, whose usage lists its flags.
func newFlagSet(name string, stderr io.Writer) *flag.FlagSet {
	fs := flag.NewFlagSet("velox-gen "+name, flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.Usage = func() {
		printUsage(stderr)
		_, _ = fmt.Fprintf(stderr, "\nFlags of %s:\n", name)
		fs.PrintDefaults()
	}
	return fs
}

// parseFlags parses args. It reports done, with the exit code, when the
// command must stop: -h exits 0, a bad flag 2.
func parseFlags(fs *flag.FlagSet, args []string) (code int, done bool) {
	switch err := fs.Parse(args); {
	case err == nil:
		return 0, false
	case errors.Is(err, flag.ErrHelp):
		return 0, true
	default:
		return 2, true
	}
}

// runVersion is velox-gen version.
func runVersion(args []string, stdout, stderr io.Writer) int {
	fs := newFlagSet("version", stderr)
	if code, done := parseFlags(fs, args); done {
		return code
	}
	if fs.NArg() > 0 {
		_, _ = fmt.Fprintln(stderr, "velox-gen: version takes no arguments")
		printUsage(stderr)
		return 2
	}
	_, _ = fmt.Fprintf(stdout, "%s (generated code %d, plugin protocol %d, model %d)\n",
		generator(), gen.GeneratedCodeVersion, plugin.ProtocolVersion, plugin.ModelVersion)
	return 0
}

// printUsage prints the forms of the command and its exit codes.
func printUsage(w io.Writer) {
	_, _ = fmt.Fprint(w, `Usage:
  velox-gen [generate] [-out dir] [-package name] [-plugin tool[:key=value,...]]... [-check] [package]
        generate the gen package of a schema package (default ./schema)
  velox-gen verify [-out dir] [-package name] [-plugin tool[:key=value,...]]... [package]
        check every generated entity's metadata
  velox-gen describe [-json] [package]
        print the entities, columns and relations of a schema package;
        with -json, the model that a plugin receives
  velox-gen version
        print the version of velox-gen, of the generated code, of the plugin
        protocol and of the model

Exit codes:
  0  success
  1  an error
  2  misuse: an unknown subcommand or flag, a malformed option
  3  generated files are stale (generate -check; verify, for a plugin's Go file)
`)
}

// relPath shows a path relative to dir when it is inside dir.
func relPath(dir, path string) string {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return path
	}
	if r, err := filepath.EvalSymlinks(abs); err == nil {
		abs = r
	}
	if r, err := filepath.Rel(abs, path); err == nil && !strings.HasPrefix(r, "..") {
		return r
	}
	return path
}

// relErrors shows the positions of err's *gen.Error values, as errors.Join
// joined them, relative to dir when their files are inside it.
func relErrors(dir string, err error) error {
	errs := []error{err}
	if j, ok := err.(interface{ Unwrap() []error }); ok {
		errs = j.Unwrap()
	}
	out := make([]error, len(errs))
	changed := false
	for i, e := range errs {
		out[i] = e
		if ge, ok := e.(*gen.Error); ok && ge.Pos != "" {
			c := *ge
			c.Pos = relPos(dir, ge.Pos)
			out[i], changed = &c, true
		}
	}
	if !changed {
		return err
	}
	return errors.Join(out...)
}

// relPos shows a file:line position relative to dir when the file is inside
// it.
func relPos(dir, pos string) string {
	i := strings.LastIndexByte(pos, ':')
	if i < 0 {
		return pos
	}
	file := filepath.FromSlash(pos[:i])
	if !filepath.IsAbs(file) {
		return pos
	}
	if r, err := filepath.EvalSymlinks(file); err == nil {
		file = r
	}
	return relPath(dir, file) + pos[i:]
}

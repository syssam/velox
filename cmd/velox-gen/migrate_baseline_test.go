var update = flag.Bool("update", false, "write the golden files")

// baselineHint is the last line baseline prints.
const baselineHint = "velox-gen: migrate baseline: run velox-gen migrate apply -baseline 1 once on each existing database, then migrate drift there\n"

// TestMigrateBaselineSQLite: baseline adopts a SQLite database velox made
// into a new directory, whose next diff has no changes; its refusals and
// misuses.
func TestMigrateBaselineSQLite(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a module")
	}
	dir := tempModule(t, map[string]string{"veloxschema/user.go": userSchema(`field.String("name")`)})
	dsn := filepath.Join(dir, "app.db")
	if code, _, errs := runCLI(t, dir, "migrate", "diff", "-dialect", "sqlite", "-dir", "made"); code != 0 {
		t.Fatalf("diff: %d %s", code, errs)
	}
	if code, _, errs := runCLI(t, dir, "migrate", "apply", "-dir", "made", "-db", dsn); code != 0 {
		t.Fatalf("apply: %d %s", code, errs)
	}

	code, out, errs := runCLI(t, dir, "migrate", "baseline", "-dialect", "sqlite", "-db", dsn)
	want(t, "baseline", code, out, errs, 0,
		"migrations/0001_baseline.sql\nmigrations/schema.json\nmigrations/velox.json\nmigrations/velox.sum\n", baselineHint)
	data, err := os.ReadFile(filepath.Join(dir, "migrations", "0001_baseline.sql"))
	if first, _, _ := strings.Cut(string(data), "\n"); err != nil || !strings.HasPrefix(first, "-- Generated by velox-gen ") || !strings.Contains(first, " migrate baseline. ") {
		t.Errorf("the header of 0001_baseline.sql: %v %q", err, first)
	}
	code, out, errs = runCLI(t, dir, "migrate", "diff")
	want(t, "diff", code, out, errs, 0, "no changes\n", "")

	code, out, errs = runCLI(t, dir, "migrate", "baseline", "-dialect", "sqlite", "-db", dsn)
	want(t, "again", code, out, errs, 1, "", "velox-gen: migrate baseline: migrations is a migration directory already; baseline starts a new one\n")

	empty := filepath.Join(dir, "empty.db")
	db, err := sql.Open("sqlite", empty)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec("CREATE TABLE other (id integer)"); err != nil {
		t.Fatal(err)
	}
	_ = db.Close()
	code, out, errs = runCLI(t, dir, "migrate", "baseline", "-dir", "other", "-dialect", "sqlite", "-db", empty)
	want(t, "empty", code, out, errs, 1, "", "velox-gen: migrate baseline: the database holds none of the schema's tables; use migrate diff to start a directory\n")
	if exists(filepath.Join(dir, "other")) {
		t.Error("a refused baseline made the directory")
	}

	code, out, errs = runCLI(t, dir, "migrate", "baseline", "-dir", "other", "-db", dsn)
	if code != 2 || out != "" || !strings.HasPrefix(errs, "velox-gen: migrate baseline needs -dialect postgres, mysql or sqlite\n") || !strings.Contains(errs, "Usage:") {
		t.Errorf("no -dialect: %d %q %q", code, out, errs)
	}
	code, out, errs = runCLI(t, dir, "migrate", "baseline", "-dir", "other", "-dialect", "sqlite", "-db", "postgres://x/y")
	if code != 2 || out != "" || errs != "velox-gen: migrate baseline: -db is not a SQLite path or URI (-dialect is sqlite)\n" {
		t.Errorf("malformed -db: %d %q %q", code, out, errs)
	}
	missing := filepath.Join(dir, "missing.db")
	code, out, errs = runCLI(t, dir, "migrate", "baseline", "-dir", "other", "-dialect", "sqlite", "-db", missing)
	want(t, "missing", code, out, errs, 1, "", "velox-gen: migrate baseline: "+missing+": no such database\n")
	if exists(missing) {
		t.Error("baseline made the database")
	}
}

// TestMigrateBaselineEnt: baseline adopts the tables ent makes, on
// PostgreSQL, MySQL and SQLite, under ent's names, long ones capped as ent
// caps them. The directory builds a fresh database, apply -baseline records
// it, and the next diff holds only what velox spells differently from ent
// (entChange). It adds no index of a foreign key on any dialect: velox
// declares none, as ent does (decision 0090). PostgreSQL and MySQL need
// their variables; SQLite needs nothing.
func TestMigrateBaselineEnt(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a module")
	}
	t.Parallel() // each dialect's subtest takes a slot of its own (tempModule)
	for _, d := range []velox.Dialect{velox.Postgres, velox.MySQL, velox.SQLite} {
		t.Run(d.String(), func(t *testing.T) { baselineEnt(t, d) })
	}
}

func baselineEnt(t *testing.T, d velox.Dialect) {
	// dsn is the DSN of a new, empty database: a file in t.TempDir on SQLite.
	dsn := func(name string) string {
		if d == velox.SQLite {
			return filepath.Join(t.TempDir(), name)
		}
		return testDSN(t, d)
	}
	original := dsn("original.db")
	files := map[string]string{}
	for _, f := range []string{"user.go", "post.go", "audit_entry.go"} {
		files["veloxschema/"+f] = readFile(t, filepath.Join("testdata", "ent", "schema", f))
	}
	dir := tempModule(t, files)
	execFile(t, d, original, filepath.Join("testdata", "ent", d.String()+".sql"))
	mig := filepath.Join(dir, "migrations")
	golden := filepath.Join("testdata", "ent", "want", d.String())

	// 1. The directory, and baseline's warnings.
	code, out, errs := runCLI(t, dir, "migrate", "baseline", "-dialect", d.String(), "-db", original)
	if code != 0 || out != "migrations/0001_baseline.sql\nmigrations/schema.json\nmigrations/velox.json\nmigrations/velox.sum\n" {
		t.Fatalf("baseline: exit %d\nstdout:\n%s\nstderr:\n%s", code, out, errs)
	}
	if !strings.HasSuffix(errs, baselineHint) {
		t.Errorf("baseline's stderr does not end with the hint:\n%s", errs)
	}
	if strings.Contains(errs, "read as its index") {
		t.Errorf("baseline warns of a unique constraint:\n%s", errs)
	}
	compareGolden(t, filepath.Join(golden, "0001_baseline.sql"), generated(readFile(t, filepath.Join(mig, "0001_baseline.sql"))))
	compareGolden(t, filepath.Join(golden, "schema.json"), readFile(t, filepath.Join(mig, "schema.json")))
	compareGolden(t, filepath.Join(golden, "warnings.txt"), errs)

	// 2. The directory builds what its snapshot says.
	fresh, err := openDB(d, dsn("fresh.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = fresh.Close() }()
	if err := migrate.Verify(context.Background(), fresh, os.DirFS(mig)); err != nil {
		t.Errorf("Verify: %v", err)
	}

	// 3. apply -baseline records 0001 on the original database.
	code, out, errs = runCLI(t, dir, "migrate", "apply", "-baseline", "1", "-db", original)
	want(t, "apply -baseline 1", code, out, errs, 0, "baselined migrations/0001_baseline.sql\n", "")
	code, out, errs = runCLI(t, dir, "migrate", "status", "-db", original)
	matches(t, "status", code, out, errs, 0, "applied 1 migrations/0001_baseline.sql "+stamp+"\n", "")

	// 4. The next diff.
	code, out, errs = runCLI(t, dir, "migrate", "diff", "-dry-run", "-allow", "alter-type=users.role")
	if code != 0 || errs != "" {
		t.Fatalf("diff: exit %d\nstdout:\n%s\nstderr:\n%s", code, out, errs)
	}
	compareGolden(t, filepath.Join(golden, "diff.sql"), generated(withoutSum(out)))

	// 5. It holds only what velox spells differently from ent.
	snap, err := migrate.ReadDir(os.DirFS(mig))
	if err != nil {
		t.Fatal(err)
	}
	m, err := codegen.Load(dir, "./veloxschema", offlineEnv())
	if err != nil {
		t.Fatal(err)
	}
	g, err := codegen.Build(m)
	if err != nil {
		t.Fatal(err)
	}
	to, err := codegen.Tables(g, d)
	if err != nil {
		t.Fatal(err)
	}
	changes, err := migrate.Diff(snap.Snapshot, to, migrate.DiffOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if n := map[velox.Dialect]int{velox.Postgres: 9, velox.MySQL: 9, velox.SQLite: 7}[d]; len(changes) != n {
		t.Errorf("the next diff has %d changes, want %d: %v", len(changes), n, changes)
	}
	for _, ch := range changes {
		if !entChange(d, ch) {
			t.Errorf("the next diff holds %s (%T), which is not what velox spells differently from ent", ch, ch)
		}
	}
}

// entChange reports whether ch is one the next diff of an ent database may
// hold: the rename of an index to the name with its table's prefix, which ent
// does not give; the rename of a foreign-key constraint whose name is longer
// than the dialect allows, which velox caps with FNV-1, not as ent does
// (decision 0090); the default of a string column, which velox sets to its
// zero (decision 0090); and users.id's serial-to-identity on PostgreSQL. No
// index of a foreign key is added: velox declares none, as ent does
// (decision 0090).
func entChange(d velox.Dialect, ch migrate.Change) bool {
	s := ch.String()
	switch {
	case strings.HasPrefix(s, "rename-index "), strings.HasPrefix(s, "rename-constraint posts.posts_users_drafts_written_but_"):
		return true
	case strings.HasPrefix(s, "alter-column ") && strings.HasSuffix(s, " (default)"):
		return true
	case s == "alter-column users.id (identity)", s == "alter-column users.id (default|identity)":
		return d == velox.Postgres
	}
	return false
}

// readFile is the content of the file at path.
func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// execFile runs each statement of the SQL file at path, split at ";" ending
// a line, on the database dsn of dialect d.
func execFile(t *testing.T, d velox.Dialect, dsn, path string) {
	t.Helper()
	db, err := openDB(d, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = db.Close() }()
	for stmt := range strings.SplitSeq(readFile(t, path), ";\n") {
		if strings.TrimSpace(stmt) == "" {
			continue
		}
		if _, err := db.Exec(stmt); err != nil {
			t.Fatalf("%s: %v\n%s", path, err, stmt)
		}
	}
}

// generatorVersion is the version in the header Dir.Add writes, which the
// goldens leave out.
var generatorVersion = regexp.MustCompile(`(?m)^(-- Generated by velox-gen) \S+ `)

// generated is s with the version of each header left out.
func generated(s string) string { return generatorVersion.ReplaceAllString(s, "$1 ") }

// withoutSum is diff -dry-run's output without velox.sum, whose sums cover
// the headers' version.
func withoutSum(out string) string {
	before, _, _ := strings.Cut(out, "== migrations/velox.sum\n")
	return before
}

// compareGolden checks got against the file at path; with -update it writes
// the file.
func compareGolden(t *testing.T, path, got string) {
	t.Helper()
	if *update {
		writeFile(t, path, got)
		return
	}
	if w := readFile(t, path); got != w {
		t.Errorf("%s differs:\n%s\nwant:\n%s", path, got, w)
	}
}

// pluginModule is genModule with the fake plugin (testdata/fakeplugin) added
// as a tool of the module.
func pluginModule(t *testing.T) string {
	t.Helper()
	src, err := os.ReadFile(filepath.Join("testdata", "fakeplugin", "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	dir := genModule(t, map[string]string{"fakeplugin/main.go": string(src)})
	gomod := filepath.Join(dir, "go.mod")
	b, err := os.ReadFile(gomod)
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, gomod, string(b)+"\ntool example.com/app/fakeplugin\n")
	return dir
}

// fakeEnv is the environment of a run: offline, and the fake plugin's
// settings (KEY=value).
func fakeEnv(settings ...string) []string {
	return append(offlineEnv(), settings...)
}

// filesEnv is the setting that makes the fake plugin answer with these files.
func filesEnv(t *testing.T, files ...plugin.File) string {
	t.Helper()
	b, err := json.Marshal(files)
	if err != nil {
		t.Fatal(err)
	}
	return "FAKEPLUGIN_FILES=" + string(b)
}

// names lists the entries of dir; nil when it does not exist.
func names(t *testing.T, dir string) []string {
	t.Helper()
	des, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, de := range des {
		out = append(out, de.Name())
	}
	return out
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestPluginFilesAreWritten(t *testing.T) {
	dir := pluginModule(t)
	env := fakeEnv("FAKEPLUGIN_V=1")
	code, out, errs := veloxEnv(t, dir, env, "-plugin", "fakeplugin", "./schema")
	if code != 0 || !strings.Contains(out, "gen/fake.graphqls\n") || !strings.Contains(out, "gen/fake_gql.go\n") {
		t.Fatalf("first run: %d %q %q", code, out, errs)
	}
	sdl := read(t, filepath.Join(dir, "gen", "fake.graphqls"))
	if want := "# Code generated by velox-gen. DO NOT EDIT.\n\n# variant 1\ntype Fake { id: ID! }\n"; sdl != want {
		t.Errorf("fake.graphqls:\n%q\nwant\n%q", sdl, want)
	}
	goSrc := read(t, filepath.Join(dir, "gen", "fake_gql.go"))
	if want := "// Code generated by velox-gen. DO NOT EDIT.\n\npackage gen\n\nconst FakeVariant = \"1\"\n"; goSrc != want {
		t.Errorf("fake_gql.go:\n%q\nwant\n%q", goSrc, want)
	}
	for _, f := range []string{"fake.graphqls", "fake_gql.go"} {
		if !isGenerated(filepath.Join(dir, "gen", f)) {
			t.Errorf("isGenerated(%s) is false", f)
		}
	}
	before := mtimes(t, filepath.Join(dir, "gen"))
	if code, out, errs := veloxEnv(t, dir, env, "-plugin", "fakeplugin", "./schema"); code != 0 || out != "" || errs != "" {
		t.Errorf("second run: %d %q %q", code, out, errs)
	}
	after := mtimes(t, filepath.Join(dir, "gen"))
	for name, mt := range before {
		if !after[name].Equal(mt) {
			t.Errorf("%s was rewritten", name)
		}
	}
	if code, out, errs := veloxEnv(t, dir, env, "-check", "-plugin", "fakeplugin", "./schema"); code != 0 || out != "" || errs != "" {
		t.Errorf("-check: %d %q %q", code, out, errs)
	}
}

func TestPluginFilesAreOwned(t *testing.T) {
	dir := pluginModule(t)
	gen := filepath.Join(dir, "gen")
	if code, _, errs := veloxEnv(t, dir, fakeEnv("FAKEPLUGIN_V=1"), "-plugin", "fakeplugin", "./schema"); code != 0 {
		t.Fatalf("generate: %d %q", code, errs)
	}
	const mine = "# my notes, no header\ntype Mine { id: ID! }\n"
	writeFile(t, filepath.Join(gen, "mine.graphqls"), mine)

	// A changed output: -check fails and names both files, and writes nothing.
	before := read(t, filepath.Join(gen, "fake.graphqls"))
	code, out, errs := veloxEnv(t, dir, fakeEnv("FAKEPLUGIN_V=2"), "-check", "-plugin", "fakeplugin", "./schema")
	if code != 1 || out != "" || !strings.Contains(errs, "velox-gen: gen/fake.graphqls is out of date\n") ||
		!strings.Contains(errs, "velox-gen: gen/fake_gql.go is out of date\n") ||
		!strings.Contains(errs, "run go tool velox-gen -plugin fakeplugin ./schema\n") || strings.Contains(errs, "mine.graphqls") {
		t.Fatalf("-check: %d %q %q", code, out, errs)
	}
	if read(t, filepath.Join(gen, "fake.graphqls")) != before {
		t.Error("-check changed the file")
	}

	// -check without -plugin: the plugin's files are left over.
	code, _, errs = velox(t, dir, "-check", "./schema")
	if code != 1 || !strings.Contains(errs, "gen/fake.graphqls is out of date") || !strings.Contains(errs, "gen/fake_gql.go is out of date") {
		t.Fatalf("-check without the plugin: %d %q", code, errs)
	}

	// Without -plugin the next generate removes both files, and only those.
	code, out, errs = velox(t, dir, "./schema")
	if code != 0 || !strings.Contains(out, "gen/fake.graphqls\n") || !strings.Contains(out, "gen/fake_gql.go\n") {
		t.Fatalf("generate without the plugin: %d %q %q", code, out, errs)
	}
	if got := names(t, gen); slices.Contains(got, "fake.graphqls") || slices.Contains(got, "fake_gql.go") {
		t.Errorf("the plugin's files are still there: %v", got)
	}
	if got := read(t, filepath.Join(gen, "mine.graphqls")); got != mine {
		t.Errorf("the hand-written .graphqls changed: %q", got)
	}
}

func TestPluginPathsAreChecked(t *testing.T) {
	dir := pluginModule(t)
	gen := filepath.Join(dir, "gen")
	cases := []struct {
		name, path string
	}{
		{"parent", "../x.go"},
		{"directory", "sub/x.go"},
		{"backslash", `sub\x.go`},
		{"extension", "x.txt"},
		{"no name", ".go"},
		{"empty", ""},
		{"velox-gen's own file", "user_velox.go"},
		{"velox-gen's package file", "velox.go"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			env := fakeEnv(filesEnv(t, plugin.File{Path: c.path, Content: "package gen\n"}))
			code, out, errs := veloxEnv(t, dir, env, "-plugin", "fakeplugin", "./schema")
			want := "velox-gen: plugin fakeplugin: "
			if strings.HasSuffix(c.path, "velox.go") { // a collision, found after the plugins ran
				want = "velox-gen: plugin file gen/" + c.path + " collides"
			}
			if code != 1 || out != "" || !strings.HasPrefix(errs, want) {
				t.Errorf("%d %q %q", code, out, errs)
			}
			if got := names(t, gen); len(got) != 0 {
				t.Errorf("wrote %v", got)
			}
		})
	}

	t.Run("twice", func(t *testing.T) {
		env := fakeEnv(filesEnv(t, plugin.File{Path: "x.go", Content: "package gen\n"}, plugin.File{Path: "x.go", Content: "package gen\n"}))
		code, out, errs := veloxEnv(t, dir, env, "-plugin", "fakeplugin", "./schema")
		if code != 1 || out != "" || !strings.Contains(errs, "x.go") {
			t.Errorf("%d %q %q", code, out, errs)
		}
		if got := names(t, gen); len(got) != 0 {
			t.Errorf("wrote %v", got)
		}
	})

	t.Run("two plugins", func(t *testing.T) {
		code, out, errs := veloxEnv(t, dir, fakeEnv("FAKEPLUGIN_V=1"), "-plugin", "fakeplugin", "-plugin", "fakeplugin", "./schema")
		if code != 1 || out != "" || !strings.Contains(errs, "fake.graphqls") {
			t.Errorf("%d %q %q", code, out, errs)
		}
		if got := names(t, gen); len(got) != 0 {
			t.Errorf("wrote %v", got)
		}
	})

	t.Run("a file without the header", func(t *testing.T) {
		const mine = "# not generated\n"
		writeFile(t, filepath.Join(gen, "fake.graphqls"), mine)
		code, out, errs := veloxEnv(t, dir, fakeEnv("FAKEPLUGIN_V=1"), "-plugin", "fakeplugin", "./schema")
		if code != 1 || out != "" || !strings.Contains(errs, "gen/fake.graphqls was not written by velox-gen") {
			t.Errorf("%d %q %q", code, out, errs)
		}
		if got := names(t, gen); !slices.Equal(got, []string{"fake.graphqls"}) || read(t, filepath.Join(gen, "fake.graphqls")) != mine {
			t.Errorf("wrote %v", got)
		}
	})
}

func TestPluginErrors(t *testing.T) {
	dir := pluginModule(t)
	gen := filepath.Join(dir, "gen")
	cases := []struct {
		name, plugin string
		env          []string
		want         string
	}{
		{"error", "fakeplugin", []string{"FAKEPLUGIN_MODE=error"}, "the fake plugin refuses"},
		{"exit", "fakeplugin", []string{"FAKEPLUGIN_MODE=exit"}, "the fake plugin crashed"},
		{"malformed", "fakeplugin", []string{"FAKEPLUGIN_MODE=malformed"}, "response"},
		{"unknown", "nosuchplugin", nil, "nosuchplugin"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			code, out, errs := veloxEnv(t, dir, fakeEnv(c.env...), "-plugin", c.plugin, "./schema")
			if code != 1 || out != "" || !strings.HasPrefix(errs, "velox-gen: plugin "+c.plugin+": ") || !strings.Contains(errs, c.want) {
				t.Errorf("%d %q %q", code, out, errs)
			}
			if got := names(t, gen); len(got) != 0 {
				t.Errorf("wrote %v", got)
			}
		})
	}
}

func TestPluginRequest(t *testing.T) {
	dir := pluginModule(t)
	dump := filepath.Join(t.TempDir(), "request.json")
	code, _, errs := veloxEnv(t, dir, fakeEnv("FAKEPLUGIN_DUMP="+dump), "-plugin", "fakeplugin", "./schema")
	if code != 0 {
		t.Fatalf("%d %q", code, errs)
	}
	var raw map[string]json.RawMessage
	if err := json.Unmarshal([]byte(read(t, dump)), &raw); err != nil {
		t.Fatal(err)
	}
	for _, k := range []string{"plugin_protocol", "out_package", "model"} {
		if _, ok := raw[k]; !ok {
			t.Errorf("the request has no %q: %v", k, raw)
		}
	}
	var req plugin.Request
	if err := json.Unmarshal([]byte(read(t, dump)), &req); err != nil {
		t.Fatal(err)
	}
	if req.Protocol != 1 || req.OutPackage != "gen" || req.Model == nil {
		t.Fatalf("request: %+v", req)
	}
	var got []string
	for _, e := range req.Model.Entities {
		got = append(got, e.Name)
	}
	if !slices.Equal(got, []string{"Tag", "User"}) || req.Model.SchemaPath != "example.com/app/schema" {
		t.Errorf("model: entities %v, schema %q", got, req.Model.SchemaPath)
	}
}

func TestVerifyCompilesPluginGo(t *testing.T) {
	dir := pluginModule(t)
	good := fakeEnv("FAKEPLUGIN_V=1")
	if code, _, errs := veloxEnv(t, dir, good, "-plugin", "fakeplugin", "./schema"); code != 0 {
		t.Fatalf("generate: %d %q", code, errs)
	}
	if code, out, errs := veloxEnv(t, dir, good, "verify", "-plugin", "fakeplugin", "./schema"); code != 0 || !strings.Contains(out, "2 entities, 0 with errors") {
		t.Fatalf("verify: %d %q %q", code, out, errs)
	}

	// The plugin's files on disk are not what it writes now: verify says so.
	code, _, errs := veloxEnv(t, dir, fakeEnv("FAKEPLUGIN_V=2"), "verify", "-plugin", "fakeplugin", "./schema")
	if code != 1 || !strings.Contains(errs, "gen/fake_gql.go is out of date") {
		t.Errorf("stale: %d %q", code, errs)
	}

	// A Go file that does not compile: generate writes it, verify fails and names it.
	broken := fakeEnv(filesEnv(t, plugin.File{Path: "broken_gql.go", Content: "package gen\n\nvar X int = \"s\"\n"}))
	if code, _, errs := veloxEnv(t, dir, broken, "-plugin", "fakeplugin", "./schema"); code != 0 {
		t.Fatalf("generate broken: %d %q", code, errs)
	}
	code, out, errs := veloxEnv(t, dir, broken, "verify", "-plugin", "fakeplugin", "./schema")
	if code != 1 || !strings.Contains(errs, "broken_gql.go") || strings.Contains(out, "0 with errors") {
		t.Errorf("verify broken: %d %q %q", code, out, errs)
	}
}

func TestPluginFlagRepeats(t *testing.T) {
	var p pluginFlag
	for _, v := range []string{"a", "b"} {
		if err := p.Set(v); err != nil {
			t.Fatal(err)
		}
	}
	if err := p.Set(" "); err == nil {
		t.Error("an empty plugin name is accepted")
	}
	if got := p.String(); got != "a,b" {
		t.Errorf("String: %q", got)
	}
}

// pluginModule is genModule with the fake plugin (testdata/fakeplugin) added
// as two tools of the module, fakeplugin and fakeplugin2, which answer to
// their own settings.
func pluginModule(t *testing.T) string {
	t.Helper()
	src, err := os.ReadFile(filepath.Join("testdata", "fakeplugin", "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	dir := genModule(t, map[string]string{"fakeplugin/main.go": string(src), "fakeplugin2/main.go": string(src)})
	gomod := filepath.Join(dir, "go.mod")
	b, err := os.ReadFile(gomod)
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, gomod, string(b)+"\ntool example.com/app/fakeplugin\ntool example.com/app/fakeplugin2\n")
	return dir
}

// fakeEnv is the environment of a run: offline, and the fake plugin's
// settings (KEY=value).
func fakeEnv(settings ...string) []string {
	return append(offlineEnv(), settings...)
}

// filesEnv is the setting that makes the fake plugin answer with these files.
func filesEnv(t *testing.T, files ...plugin.File) string {
	t.Helper()
	b, err := json.Marshal(files)
	if err != nil {
		t.Fatal(err)
	}
	return "FAKEPLUGIN_FILES=" + string(b)
}

// names lists the entries of dir; nil when it does not exist.
func names(t *testing.T, dir string) []string {
	t.Helper()
	des, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, de := range des {
		out = append(out, de.Name())
	}
	return out
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// In split mode a plugin's Go files in gen/entity are re-exported in one
// file of gen, named for the plugin, in the order of their paths; gen holds
// no file per plugin file. verify builds the result.
func TestPluginSplitReexportsInOneFile(t *testing.T) {
	dir := pluginModule(t)
	writeFile(t, filepath.Join(dir, "schema", "user_policy.go"), schemaUserPolicy)
	env := fakeEnv(filesEnv(t,
		plugin.File{Path: "b_gql.go", Content: "package entity\n\n// B is b's.\nvar B = 2\n"},
		plugin.File{Path: "a_gql.go", Content: "package entity\n\n// A is a's.\nconst A = 1\n\n// AT is a's type.\ntype AT int\n"},
	))
	if code, _, errs := veloxEnv(t, dir, env, "-plugin", "fakeplugin", "./schema"); code != 0 {
		t.Fatalf("%d %q", code, errs)
	}
	if got := strings.Join(names(t, filepath.Join(dir, "gen")), " "); got != "entity fakeplugin_velox.go velox.go" {
		t.Errorf("gen holds %s", got)
	}
	got := read(t, filepath.Join(dir, "gen", "fakeplugin_velox.go"))
	want := "// Code generated by velox-gen. DO NOT EDIT.\n\npackage gen\n\nimport \"example.com/app/gen/entity\"\n\n" +
		"// AT is a's type.\ntype AT = entity.AT\n\n// A is a's.\nconst A = entity.A\n\n// B is b's.\nvar B = entity.B\n"
	if got != want {
		t.Errorf("fakeplugin_velox.go:\n%s\nwant\n%s", got, want)
	}
	if code, out, errs := veloxEnv(t, dir, env, "-check", "-plugin", "fakeplugin", "./schema"); code != 0 || out != "" || errs != "" {
		t.Errorf("-check: %d %q %q", code, out, errs)
	}
	if code, out, errs := veloxEnv(t, dir, env, "verify", "-plugin", "fakeplugin", "./schema"); code != 0 {
		t.Errorf("verify: %d %q %q", code, out, errs)
	}
}


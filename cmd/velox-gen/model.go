package main

import (
	"fmt"
	"go/token"
	"go/types"

	"golang.org/x/tools/go/packages"
)

// veloxPath is the import path of the velox library.
const veloxPath = "github.com/syssam/velox2"

// header is the first line of every file velox-gen writes. velox-gen deletes
// a file that starts with it when no entity produces that file any more, and
// never overwrites a file that does not.
const header = "// Code generated by velox-gen. DO NOT EDIT."

// entity is a struct velox-gen writes a file for.
type entity struct {
	pkg       *packages.Package
	name      string // the Go type name, e.g. "Invoice"
	file      string // the file that declares it
	pos       token.Position
	columns   []column
	relations []rel
	handles   string // the handles variable, e.g. "Invoices"
	meta      string // the MetaOnce variable, e.g. "invoiceMeta"
	shape     string // the function returning the Shape, e.g. "invoiceShape"
	out       string // the generated file's path
}

// column is one column of an entity, in the runtime's order.
type column struct {
	field  string     // the field's name; fields of embedded structs flatten in
	handle string     // the handle type in package velox, e.g. "NumberCol"
	value  types.Type // the handle's value type V
}

// rel is one relation field of an entity.
type rel struct {
	field  string
	target types.Type // T of velox.One[T] or velox.Many[T]
}

// problem is a reason velox-gen refuses to write anything.
type problem struct {
	pos token.Position
	msg string
}

func (p problem) String() string {
	if p.pos.IsValid() {
		return fmt.Sprintf("%s: %s", p.pos, p.msg)
	}
	return p.msg
}

// config is what the command line sets.
type config struct {
	dir     string          // the directory package patterns are relative to
	env     []string        // the environment of go commands; nil inherits
	ordered map[string]bool // types, as "import/path.Name", with ordered handles
	number  map[string]bool // types, as "import/path.Name", with number handles
}

// defaultSchema is the schema package when no package is named.
const defaultSchema = "./schema"

// veloxPath is the import path of the velox library.
const veloxPath = "github.com/syssam/velox"

// header is the first line of every file velox-gen writes. velox-gen deletes
// a file that starts with it when no entity produces that file any more, and
// never overwrites a file that does not.
const header = "// Code generated by velox-gen. DO NOT EDIT."

// graphqlHeader is the header of a .graphql file, whose comments start
// with #.
const graphqlHeader = "# Code generated by velox-gen. DO NOT EDIT."

// headerFor is the header line a file at path starts with, by its extension;
// "" for an extension velox-gen does not write.
func headerFor(path string) string {
	switch filepath.Ext(path) {
	case ".go", ".proto":
		return header
	case ".graphql":
		return graphqlHeader
	}
	return ""
}

// isGenerated reports whether the file at path starts with the header of its
// kind.
func isGenerated(path string) bool {
	h := headerFor(path)
	if h == "" {
		return false
	}
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	line, _ := bufio.NewReader(f).ReadString('\n')
	return line == h+"\n"
}

// schemaPackage is the schema package the command works on: the one pattern
// named, or defaultSchema when none is; the caller refuses more than one, as
// a usage error. The package must declare schemas; an error is a package that
// cannot be read, as go list says it, or one that declares none.
func schemaPackage(dir string, patterns, env []string) (string, error) {
	pattern := defaultSchema
	if len(patterns) == 1 {
		pattern = patterns[0]
	}
	importPath, schemas, err := codegen.Inspect(dir, pattern, env)
	if err != nil {
		return "", relErrors(dir, err)
	}
	if len(schemas) == 0 {
		return "", codegen.NoSchemas(importPath)
	}
	return pattern, nil
}

// genFlags are the flags of generate and verify.
type genFlags struct {
	out, pkg string
	check    bool
	plugins  []pluginSpec // the -plugin flags, in order
	rerun    []string     // the flags the user set, as a command line, for the -check hint
}

// outDir is the absolute path of the output directory. It is absolute so that
// go list reads it as a directory: a relative "gen" would be an import path.
// Symlinks in dir are resolved, as relPath does, so that paths print relative.
func (f genFlags) outDir(dir string) string {
	if filepath.IsAbs(f.out) {
		return filepath.Clean(f.out)
	}
	abs, err := filepath.Abs(dir)
	if err != nil {
		abs = dir
	} else if r, err := filepath.EvalSymlinks(abs); err == nil {
		abs = r
	}
	return filepath.Join(abs, f.out)
}

// packageName is -package, or the base name of -out.
func (f genFlags) packageName(dir string) (string, error) {
	name := f.pkg
	if name == "" {
		name = filepath.Base(f.outDir(dir))
	}
	if !token.IsIdentifier(name) {
		return "", fmt.Errorf("%q is not a package name; name it with -package", name)
	}
	return name, nil
}

// genModel is the generator's view of a schema package: what Lower made of its
// graph, and the names of every generated entity, join entities included.
type genModel struct {
	graph      *codegen.Graph
	out        *codegen.Out // what Lower made of graph, for the plugins' model
	importPath string
	names      []string
	rels       []string // every relation's handle, e.g. "Users.Posts", join entities included
}

// scopeNames are the package-level names velox-gen writes for scopes: each
// key's variable and each scoped entity's scope variable. A file of the user's
// may not declare them.
func (gm *genModel) scopeNames() []string {
	var names []string
	for _, k := range gm.out.ScopeKeys {
		names = append(names, k.Var)
	}
	for _, e := range gm.out.Entities {
		if e.Scope != nil {
			names = append(names, e.Scope.Var)
		}
	}
	return names
}

// loadModel loads and builds the schema package at pattern and lowers it to
// the names of its generated entities.
func loadModel(dir, pattern, out, pkg string, env []string) (*genModel, error) {
	// A schema package that reaches the generated package at out makes an
	// import cycle once that package imports the schema, which go list
	// reports with no chain: the error names the chain instead.
	cycle := func(err error) error {
		if genPath, perr := dirImportPath(out, env); perr == nil {
			if cerr := codegen.CheckGenImports(dir, pattern, genPath, env); cerr != nil {
				return relErrors(dir, cerr)
			}
		}
		return relErrors(dir, err)
	}
	importPath, _, err := codegen.Inspect(dir, pattern, env)
	if err != nil {
		return nil, cycle(err)
	}
	m, err := codegen.Load(dir, pattern, env)
	if err != nil {
		return nil, cycle(err)
	}
	g, err := codegen.Build(m)
	if err != nil {
		return nil, relErrors(dir, err)
	}
	o, err := codegen.Lower(g, codegen.Config{Package: pkg, SchemaPath: importPath})
	if err != nil {
		return nil, err
	}
	gm := &genModel{graph: g, out: o, importPath: importPath}
	for _, e := range o.Entities {
		gm.names = append(gm.names, e.Name)
		for _, r := range e.Rels {
			gm.rels = append(gm.rels, e.Handles+"."+r.GoName)
		}
	}
	return gm, nil
}

// genConfig is the codegen.Config of the package at out, named pkg, for the
// schema package at pattern: the import path of out, the Hooks and Policy
// methods the schema package declares, and whether the entities go in
// package entity below out (codegen.Behaviour). UserDoc is left for the
// caller.
func genConfig(gm *genModel, dir, pattern, out, pkg string, env []string) (codegen.Config, error) {
	cfg := codegen.Config{Package: pkg, SchemaPath: gm.importPath}
	genPath, err := dirImportPath(out, env)
	if err != nil {
		return cfg, err
	}
	bound, split, err := codegen.Behaviour(dir, pattern, genPath, env, gm.names)
	if err != nil {
		return cfg, err
	}
	cfg.GenPath = genPath
	if split {
		cfg.Bound, cfg.Split = bound, true
	}
	return cfg, nil
}

// output is what one run of velox-gen writes below out.
type output struct {
	cfg    codegen.Config
	want   map[string][]byte // every file, velox-gen's and the plugins', by absolute path
	plugin map[string][]byte // the plugins' files, by absolute path
	owners map[string]string // the plugin that wrote each of plugin
}

// buildOutput generates the files of the package at out, named pkg, for the
// schema package at pattern, and runs the plugins on the model. In split
// mode the plugins write below out/entity, the package that holds the
// entities, and each of their Go files there gets its re-export in out. The
// files of the user's in out, and in split mode in out/entity, are checked
// against what velox-gen writes. Nothing is written.
func buildOutput(f genFlags, gm *genModel, pattern, dir, out, pkg string, env []string, stderr io.Writer) (*output, error) {
	cfg, err := genConfig(gm, dir, pattern, out, pkg, env)
	if err != nil {
		return nil, err
	}
	entityDir := out
	if cfg.Split {
		entityDir = filepath.Join(out, codegen.EntityDir)
	}
	if err := codegen.CheckUserFiles(entityDir, gm.names, gm.scopeNames()); err != nil {
		return nil, err
	}
	if cfg.UserDoc, err = codegen.HasPackageDoc(out); err != nil {
		return nil, err
	}
	if cfg.Split {
		if cfg.EntityDoc, err = codegen.HasPackageDoc(entityDir); err != nil {
			return nil, err
		}
	}
	files, err := codegen.Generate(gm.graph, cfg)
	if err != nil {
		return nil, err
	}
	o := &output{cfg: cfg, want: make(map[string][]byte, len(files))}
	for _, file := range files {
		o.want[filepath.Join(out, filepath.FromSlash(file.Name))] = file.Data
	}
	// The plugins run after velox-gen's own files are built and before
	// anything is written.
	ppkg, ppath := pkg, cfg.GenPath
	if cfg.Split {
		ppkg, ppath = codegen.EntityDir, cfg.GenPath+"/"+codegen.EntityDir
	}
	o.plugin, o.owners, err = pluginFiles(f, gm, pattern, dir, entityDir, ppkg, ppath, env, stderr)
	if err != nil {
		return nil, err
	}
	if err := mergePluginFiles(dir, out, o.want, o.plugin, o.owners); err != nil {
		return nil, err
	}
	if !cfg.Split {
		return o, nil
	}
	for _, p := range slices.Sorted(maps.Keys(o.plugin)) {
		if filepath.Ext(p) != ".go" || filepath.Dir(p) != entityDir {
			continue
		}
		rf, ok, err := codegen.Reexport(filepath.Base(p), o.plugin[p], pkg, ppath)
		if err != nil {
			return nil, fmt.Errorf("plugin %s: %w", o.owners[p], err)
		}
		if !ok {
			continue
		}
		q := filepath.Join(out, rf.Name)
		if _, dup := o.want[q]; dup {
			return nil, fmt.Errorf("plugin %s: %s, whose re-export is %s, collides with a file velox-gen writes", o.owners[p], relPath(dir, p), relPath(dir, q))
		}
		o.want[q] = rf.Data
	}
	// A file of the user's in out may not declare what out re-exports.
	var names []string
	for p, data := range o.want {
		if filepath.Dir(p) != out || filepath.Ext(p) != ".go" {
			continue
		}
		ns, err := codegen.ReexportedNames(filepath.Base(p), data)
		if err != nil {
			return nil, err
		}
		names = append(names, ns...)
	}
	slices.Sort(names)
	if err := codegen.CheckUserFiles(out, gm.names, names); err != nil {
		return nil, err
	}
	if err := codegen.CheckFacadeFiles(out, names, relPath(dir, entityDir)); err != nil {
		return nil, err
	}
	return o, nil
}

// runGenerate generates the gen package of the schema
// package at pattern.
func runGenerate(f genFlags, pattern, dir string, env []string, stdout, stderr io.Writer) int {
	fail := func(err error) int {
		_, _ = fmt.Fprintf(stderr, "velox-gen: %v\n", err)
		return 1
	}
	pkg, err := f.packageName(dir)
	if err != nil {
		return fail(err)
	}
	gm, err := loadModel(dir, pattern, f.outDir(dir), pkg, env)
	if err != nil {
		return fail(err)
	}
	out := f.outDir(dir)
	// A *FileError names a user's file: relative to dir, as other paths are.
	failFile := func(err error) int {
		if fe := (*codegen.FileError)(nil); errors.As(err, &fe) {
			c := *fe
			c.Path = relPath(dir, fe.Path)
			return fail(&c)
		}
		return fail(err)
	}
	o, err := buildOutput(f, gm, pattern, dir, out, pkg, env, stderr)
	if err != nil {
		return failFile(err)
	}
	want, owners := o.want, o.owners
	// Nothing is written before every path is known to be velox-gen's: a
	// regular file with its header, below real directories.
	for _, p := range slices.Sorted(maps.Keys(want)) {
		for d := filepath.Dir(p); d != out && within(out, d); d = filepath.Dir(d) {
			if err := checkEntry(dir, d, true); err != nil {
				return fail(err)
			}
		}
		if err := checkEntry(dir, p, false); err != nil {
			return fail(err)
		}
		if _, err := os.Lstat(p); err == nil && !isGenerated(p) {
			return fail(fmt.Errorf("%s was not written by velox-gen; move it", relPath(dir, p)))
		}
	}
	sw, err := staleFiles(out, want, owners, !f.check)
	for _, s := range sw.swept {
		switch {
		case s.restored != "":
			_, _ = fmt.Fprintf(stderr, "velox-gen: restored %s from %s, which an interrupted run left\n", relPath(dir, s.restored), relPath(dir, s.path))
		case len(s.kept) > 0:
			for _, k := range s.kept {
				_, _ = fmt.Fprintf(stderr, "velox-gen: kept %s, which is not velox-gen's, in %s, which an interrupted run left; move it\n", relPath(dir, k), relPath(dir, s.path))
			}
		default:
			_, _ = fmt.Fprintf(stderr, "velox-gen: removed %s, which an interrupted run left\n", relPath(dir, s.path))
		}
	}
	if err != nil {
		return fail(err)
	}
	stale, remove := sw.write, sw.remove
	changed := append(slices.Clone(stale), remove...)
	slices.Sort(changed)
	if f.check {
		for _, p := range changed {
			_, _ = fmt.Fprintf(stderr, "velox-gen: %s is out of date\n", relPath(dir, p))
		}
		for _, p := range sw.leftovers {
			_, _ = fmt.Fprintf(stderr, "velox-gen: %s is left over from an interrupted run\n", relPath(dir, p))
		}
		if len(changed)+len(sw.leftovers) > 0 {
			_, _ = fmt.Fprintf(stderr, "velox-gen: run %s\n", rerunCommand(f.rerun))
			return 3
		}
		return 0
	}
	// writeAll sets the removals aside before it writes: on a
	// case-insensitive file system a file or directory whose name changed
	// only in case is the old one, which goes first. The emptied directories
	// go with the files they held.
	rel := func(p string) string {
		r, _ := filepath.Rel(out, p)
		return filepath.ToSlash(r)
	}
	write := make(map[string][]byte, len(stale))
	for _, p := range stale {
		write[rel(p)] = want[p]
	}
	var gone []string
	for _, p := range slices.Concat(remove, sw.emptied) {
		gone = append(gone, rel(p))
	}
	// A signal waits for the write to finish or be undone.
	interrupted, err := writeAllHeld(out, write, gone)
	code := 0
	if err != nil {
		code = fail(err)
	} else {
		for _, p := range changed {
			_, _ = fmt.Fprintln(stdout, relPath(dir, p))
		}
	}
	if interrupted {
		_, _ = fmt.Fprintln(stderr, "velox-gen: interrupted")
		return interruptedCode
	}
	return code
}

// checkEntry refuses what is at p, when anything is, unless it is a directory
// (dir) or a regular file (!dir). A symbolic link is refused either way: what
// velox-gen writes or removes stays below -out.
func checkEntry(dir, p string, isDir bool) error {
	fi, err := os.Lstat(p)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return nil
	case err != nil:
		return err
	case fi.Mode()&os.ModeSymlink != 0:
		return fmt.Errorf("%s is a symbolic link; velox-gen writes only regular files below real directories; move it", relPath(dir, p))
	case isDir && !fi.IsDir():
		return fmt.Errorf("%s is not a directory; move it", relPath(dir, p))
	case !isDir && !fi.Mode().IsRegular():
		return fmt.Errorf("%s is not a regular file; move it", relPath(dir, p))
	}
	return nil
}

// sweep is what staleFiles finds to do in the output directory.
type sweep struct {
	write     []string // the files of want that are missing or hold other content
	remove    []string // the generated files nothing produces now, under their spelling on disk
	emptied   []string // the directories the removals empty, deepest first
	swept     []swept  // what an interrupted run left, which tidy handled
	leftovers []string // what an interrupted run left, without tidy
}

// staleFiles compares want, the files that must be in out, with the disk.
//
// A generated file (.go, .graphql or .proto: a regular file that starts with
// the header of its kind) in out or below it that is not a path of want is
// removed. The walk skips the directories whose name starts with "." or "_"
// (.git, .velox-verify-*, testdata's kin), and those that hold a go.mod
// (another module) or a velox.go with the header (another run's output, such
// as -out ./gen/b beside -out ./gen). A directory is emptied only when
// it held something, everything it held is removed, and no file of want goes
// into it.
//
// Paths are matched to want by their spelling, and also folded, as a
// case-insensitive file system matches them. A generated file whose name
// differs from a path of want only in case is removed; when the file system
// takes the two for one file, that path of want is written again, after the
// removal, so that it ends up under its new spelling. A directory that differs
// from one of want only in case is removed when the removals empty it, and
// want's spelling is then created; any other such directory (one that holds a
// file of yours, or nothing) is an error, on every file system, because
// velox-gen never renames a directory it did not empty. owners names the
// plugin that wrote each path of want.
//
// With tidy, each directory the walk lists is first rid of what a killed run
// of writeAll left in it (sweepLeftovers), which sw.swept reports. Without
// it, as for -check, those entries stay, and sw.leftovers lists them. Either
// way they are never counted as a directory's entries.
func staleFiles(out string, want map[string][]byte, owners map[string]string, tidy bool) (sweep, error) {
	var sw sweep
	write := map[string]bool{}
	wantFold := make(map[string]string, len(want)) // folded path → the path of want
	for p := range want {
		wantFold[fold(p)] = p
	}
	keep := map[string]string{}   // folded directory a file of want goes into → its spelling
	keepBy := map[string]string{} // folded directory → the first path of want in it
	for _, p := range slices.Sorted(maps.Keys(want)) {
		for d := filepath.Dir(p); within(out, d) && d != out; d = filepath.Dir(d) {
			if _, ok := keep[fold(d)]; !ok {
				keep[fold(d)], keepBy[fold(d)] = d, p
			}
		}
	}
	// held counts each directory's entries, gone those that go.
	held, gone := map[string]int{}, map[string]int{}
	var dirs []string
	// walk lists the directory d, which it reads through a symlink only when
	// it is out itself, as os.ReadDir does.
	var walk func(d string) error
	walk = func(d string) error {
		des, err := os.ReadDir(d)
		if err != nil {
			if d == out && errors.Is(err, os.ErrNotExist) {
				return nil
			}
			return err
		}
		if tidy {
			done, err := sweepLeftovers(d, des)
			sw.swept = append(sw.swept, done...)
			if err != nil {
				return err
			}
			if len(done) > 0 {
				if des, err = os.ReadDir(d); err != nil {
					return err
				}
			}
		}
		for _, de := range des {
			p := filepath.Join(d, de.Name())
			if leftover.MatchString(de.Name()) {
				if !tidy {
					sw.leftovers = append(sw.leftovers, p)
				}
				continue // -check leaves them; they never hold a directory
			}
			held[d]++
			switch {
			case de.IsDir():
				if n := de.Name(); n[0] == '.' || n[0] == '_' || ownRoot(p) {
					continue
				}
				dirs = append(dirs, p)
				if err := walk(p); err != nil {
					return err
				}
			case de.Type().IsRegular():
				if _, ok := want[p]; ok || headerFor(p) == "" || !isGenerated(p) {
					continue
				}
				sw.remove = append(sw.remove, p)
				gone[d]++
				if q, ok := wantFold[fold(p)]; ok && sameEntry(p, q) {
					write[q] = true
				}
			}
		}
		return nil
	}
	if err := walk(out); err != nil {
		return sweep{swept: sw.swept}, err
	}
	// After the walk, which may put back a file set aside.
	for p, data := range want {
		if got, err := os.ReadFile(p); err != nil || !bytes.Equal(got, data) {
			write[p] = true
		}
	}
	// Deepest first, so that a directory's emptied children count as gone.
	slices.SortFunc(dirs, func(a, b string) int {
		return cmp.Or(cmp.Compare(strings.Count(b, string(filepath.Separator)), strings.Count(a, string(filepath.Separator))), cmp.Compare(a, b))
	})
	for _, d := range dirs {
		k, kept := keep[fold(d)]
		exact := kept && k == d
		switch {
		case !exact && held[d] > 0 && gone[d] == held[d]:
			sw.emptied = append(sw.emptied, d)
			gone[filepath.Dir(d)]++
		case kept && !exact:
			p := keepBy[fold(d)]
			rel := func(q string) string {
				r, _ := filepath.Rel(out, q)
				return filepath.ToSlash(r)
			}
			return sweep{}, fmt.Errorf("plugin %s: path %q: the directory %q differs only in case; rename it", owners[p], rel(p), rel(d))
		}
	}
	sw.write = slices.Sorted(maps.Keys(write))
	slices.Sort(sw.remove)
	return sw, nil
}

// ownRoot reports whether the directory d is the root of output the sweep
// leaves alone: another generate run's, which holds velox-gen's own velox.go
// with the header, or another module's, which holds a go.mod.
func ownRoot(d string) bool {
	if fi, err := os.Lstat(filepath.Join(d, "go.mod")); err == nil && !fi.IsDir() {
		return true
	}
	v := filepath.Join(d, "velox.go")
	fi, err := os.Lstat(v)
	return err == nil && fi.Mode().IsRegular() && isGenerated(v)
}

// sameEntry reports whether the paths a and b, which differ, name one entry of
// the file system: one that folds case.
func sameEntry(a, b string) bool {
	fa, err := os.Lstat(a)
	if err != nil {
		return false
	}
	fb, err := os.Lstat(b)
	return err == nil && os.SameFile(fa, fb)
}

// rerunCommand is the command that regenerates with the flags args, each
// quoted for a POSIX shell where it needs to be.
func rerunCommand(args []string) string {
	words := []string{"go", "tool", "velox-gen"}
	for _, a := range args {
		words = append(words, shellQuote(a))
	}
	return strings.Join(words, " ")
}

// shellQuote is s as a POSIX shell word: itself when the shell neither splits
// nor expands it, else in single quotes, with each single quote in it
// closed, escaped and reopened.
func shellQuote(s string) string {
	if s != "" && strings.Trim(s, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_@%+=:,./-") == "" {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// runGenerateVerify is verify for a generated package: it builds a program in
// the module of the output package that calls velox.CheckEntity for every
// entity and join entity of the schema package at pattern, and
// velox.CheckRelation for every relation, which only the handle of a relation
// can resolve: the generated metadata names no relation's target.
func runGenerateVerify(f genFlags, pattern, dir string, env []string, stdout, stderr io.Writer) int {
	fail := func(err error) int {
		_, _ = fmt.Fprintf(stderr, "velox-gen verify: %v\n", err)
		return 1
	}
	pkg, err := f.packageName(dir)
	if err != nil {
		return fail(err)
	}
	gm, err := loadModel(dir, pattern, f.outDir(dir), pkg, env)
	if err != nil {
		return fail(err)
	}
	out := f.outDir(dir)
	if fi, err := os.Stat(out); err != nil || !fi.IsDir() {
		return fail(fmt.Errorf("%s is not a directory; run velox-gen to generate it first", relPath(dir, out)))
	}
	mod, err := moduleDir(dir, out, env)
	if err != nil {
		return fail(err)
	}
	// The plugins' Go files are compiled with the package, as they are on
	// disk; they must be the files the plugins write now, and so must their
	// re-exports. A plugin path that collides with a file of velox-gen's
	// fails as it does in generate.
	o, err := buildOutput(f, gm, pattern, dir, out, pkg, env, stderr)
	if err != nil {
		return fail(err)
	}
	outPath := o.cfg.GenPath
	check := slices.Sorted(maps.Keys(o.plugin))
	if o.cfg.Split {
		for _, p := range check {
			if q := filepath.Join(out, filepath.Base(p)); filepath.Dir(p) == filepath.Join(out, codegen.EntityDir) && o.want[q] != nil {
				check = append(check, q)
			}
		}
	}
	for _, p := range check {
		if filepath.Ext(p) != ".go" {
			continue
		}
		if got, err := os.ReadFile(p); err != nil || !bytes.Equal(got, o.want[p]) {
			_, _ = fmt.Fprintf(stderr, "velox-gen verify: %s is out of date; run velox-gen\n", relPath(dir, p))
			return 3
		}
	}
	types := make([]string, len(gm.names))
	for i, n := range gm.names {
		types[i] = "g." + n
	}
	rels := make([]string, len(gm.rels))
	for i, r := range gm.rels {
		rels[i] = "g." + r
	}
	// An interrupt stops the check program, and its directory is removed.
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	imports := [][2]string{{"g", outPath}}
	return runProgram(ctx, mod, checkProgram(imports, types, rels), env, stdout, stderr)
}

// moduleDir is the directory of the module that holds the package at pattern.
func moduleDir(dir, pattern string, env []string) (string, error) {
	cmd := exec.Command("go", "list", "-f", "{{.Module.Dir}}", pattern)
	cmd.Dir = dir
	if env != nil {
		cmd.Env = env
	}
	var so, se bytes.Buffer
	cmd.Stdout, cmd.Stderr = &so, &se
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("go list %s: %w\n%s", pattern, err, strings.TrimRight(se.String(), "\n"))
	}
	mod := strings.TrimSpace(so.String())
	if mod == "" {
		return "", fmt.Errorf("%s is not in a module", pattern)
	}
	return mod, nil
}

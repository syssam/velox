// Package plugin is the protocol between velox-gen and a velox-gen plugin.
//
// velox-gen runs a plugin as a separate program, the way protoc does. It
// writes a [Request] as JSON to the plugin's standard input, and reads a
// [Response] as JSON from its standard output. The request holds the resolved
// [Model] of the schema package: the names, columns, Go types, relations,
// enums and raw annotations velox-gen itself generates from. A plugin never
// recomputes them.
//
// The response lists files to write into the output directory. A path is a
// bare file name, without a directory part, ending in .go or .graphqls.
// velox-gen adds the "Code generated by velox-gen. DO NOT EDIT." header line
// to each file, so a plugin's content does not include it. A non-empty Error
// fails the run, and nothing is written.
//
// The package imports only the standard library, so that a plugin depends on
// nothing else of velox.
//
// [Snake], [Plural], [Singular] and [GoName] are velox-gen's naming helpers,
// and they are frozen: they decide table, column and Go names, which live in
// databases and code, so a change to any output breaks users. The golden
// table testdata/names.golden pins them.

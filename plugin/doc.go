// Package plugin is the protocol between velox-gen and a velox-gen plugin.
//
// # Running a plugin
//
// A plugin is a program, a tool of the application's module that velox-gen
// runs as "go tool <name>" in the module's directory, the way protoc runs its
// plugins:
//
//	go get -tool example.com/velox-foo
//	go tool velox-gen -out gen -plugin velox-foo:mode=strict,out=pb ./schema
//
// velox-gen writes one [Request] as JSON to the plugin's standard input,
// closes it, and reads one [Response] as JSON from its standard output. The
// plugin's standard error is shown only when it exits non-zero. Repeated
// -plugin flags run several plugins, one after the other, each with its own
// request.
//
// # The request
//
//	{
//	  "plugin_protocol": 2,
//	  "generator": "velox-gen v2.0.0",
//	  "out_package": "gen",
//	  "out_path": "example.com/app/gen",
//	  "options": {"mode": "strict", "out": "pb"},
//	  "model": {"version": 2, "schema_path": "example.com/app/schema", "entities": [...], "enums": [...]}
//	}
//
// Its keys:
//
//   - plugin_protocol is [ProtocolVersion], the shape of the request and the
//     response and the rules below.
//   - generator names velox-gen and the version of velox2 it was built with,
//     "(devel)" when the build does not say. It is for messages: a file that
//     held it would change with every release.
//   - out_package and out_path are the name and the import path of the
//     generated package, the -out directory.
//   - options are the plugin's own options, from -plugin name:key=value,...;
//     absent when the flag gives none. velox-gen checks only their form:
//     keys are non-empty, distinct and hold no "=", and neither keys nor
//     values hold a comma. A plugin refuses a key it does not know, with an error.
//   - model is the resolved [Model] of the schema package: the names, columns,
//     Go types, relations, indexes, enums and raw annotations velox-gen itself
//     generates from. A plugin never recomputes them. In the model, the named
//     elements, [Entity], [Field], [Edge] and [Index], are held by pointer,
//     and small leaf records, such as [Check], by value. The model is
//     versioned apart, [ModelVersion]: its version changes when a field is
//     removed or changes meaning, not when one is added, so a plugin ignores
//     the JSON keys it does not know.
//
// # The response
//
//	{
//	  "plugin_protocol": 2,
//	  "files": [{"path": "pb/user.proto", "content": "syntax = \"proto3\";\n..."}],
//	  "warnings": ["field User.blob: bytes are not mapped, skipped"],
//	  "error": ""
//	}
//
// Its keys:
//
//   - plugin_protocol echoes the protocol the plugin speaks. velox-gen refuses
//     a response without it, or with another value, before it reads the rest:
//     a plugin of protocol 1 answered without it.
//   - files are written into the output directory. Path is a slash path
//     below it: not absolute, with no empty, "." or ".." segment, no
//     backslash and no NUL; its directories do not start with "." or "_", and
//     it ends in .go, .graphqls or .proto. velox-gen puts the header
//     "// Code generated by velox-gen. DO NOT EDIT." in front of each file
//     ("# ..." for .graphqls), followed by a blank line, so a plugin's
//     content does not include it.
//   - warnings are printed, one line each, as
//     "velox-gen: plugin <name>: warning: <text>". They never fail the run.
//   - a non-empty error fails the run, and nothing is written. The plugin
//     still exits 0: a non-zero exit is for a plugin that cannot answer.
//
// The run fails, before anything is written, when a path is refused, when two
// plugins, or one twice, write one path, when a path is one that velox-gen
// writes, or when a file of the user's, one without the header, is at it.
// Paths are compared as a case-insensitive file system does, over the whole
// path: pb/X.go and PB/x.go are one file, and pb/a.go and PB/b.go are in one
// directory, which is refused too. velox-gen then owns the files, as it owns
// its own: -check reports one that is out of date, and a run deletes one that
// no plugin writes any more, with each directory below the output directory
// that this leaves empty.
//
// # Versions
//
// [Main] and [Run] do the decoding, the checks and the encoding:
//
//	func main() {
//		plugin.Main(plugin.Supports{Protocol: 2, Model: 2}, generate)
//	}
//
//	func generate(req *plugin.Request) ([]plugin.File, []string, error) { ... }
//
// [Supports] holds the versions the plugin was written for, as literals.
// Built with a velox2 of another protocol or model, the plugin answers with
// an error that says to update it; given a request of another protocol, or a
// model of another version, it answers with an error that says to use
// velox-gen and the plugin of one velox2 release. A plugin that does not use
// Main makes the same checks itself, and always sets plugin_protocol. Tests
// call [Run] with a request in memory.
//
// # Naming
//
// [Snake], [Plural], [Singular] and [GoName] are velox-gen's naming helpers.
// They are frozen: they decide table, column and Go names, which live in
// databases and code. Their outputs never change within a major version, for
// any input; a change to any output needs a new major version. Helpers may be
// added. The golden table testdata/names.golden pins them.
//
// The package imports only the standard library, so that a plugin depends on
// nothing else of velox.
package plugin

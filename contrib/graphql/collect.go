// genEntityCollection generates a per-entity collection file for the entity sub-package.
// Contains the CollectMeta variable with FieldColumns and Edges, populated in init().
// The CollectFields method on *{Entity}Query is generated separately in query/ via genCollectionQueries.
func (g *Generator) genEntityCollection(t *gen.Type) *jen.File {
	if g.config.ORMPackage == "" {
		return nil
	}
	f := jen.NewFilePath(g.entityPkgPath(t))
	f.HeaderComment("Code generated by velox. DO NOT EDIT.")

	f.ImportName(runtimePkgPath, "runtime")

	metaVar := t.Name + "CollectMeta"

	// Package-level CollectMeta variable (exported for query/ package access).
	f.Commentf("%s holds GraphQL field collection metadata for %s.", metaVar, t.Name)
	f.Var().Id(metaVar).Qual(runtimePkgPath, "CollectMeta")

	// Generate init() to populate CollectMeta.
	g.genEntityCollectionInit(f, t, metaVar)

	return f
}

// collectionNodes returns the types that get GraphQL field collection: a
// CollectMeta in their entity package and a CollectFields method on their
// query. It is the one definition both the generator and markCollectFields
// use.
func collectionNodes(nodes []*gen.Type) []*gen.Type {
	return (&Generator{}).filterNodes(nodes, SkipType)
}

// markCollectFields marks every collection type's graphql annotation with
// CollectFields, before the core generator runs, so it adds
// CollectFields(ctx, satisfies...) (XxxQuerier, error) to entity.XxxQuerier
// — a list resolver then calls it on Query() without asserting the concrete
// query type. The core reads annotations as map[string]any (it cannot import
// this package), the same channel RelayConnection uses for Paginate.
func markCollectFields(nodes []*gen.Type) {
	for _, t := range collectionNodes(nodes) {
		m, ok := t.Annotations[AnnotationName].(map[string]any)
		if !ok {
			data, err := json.Marshal(extractGraphQLAnnotation(t.Annotations))
			if err != nil {
				continue
			}
			if err := json.Unmarshal(data, &m); err != nil {
				continue
			}
		}
		m["CollectFields"] = true
		if t.Annotations == nil {
			t.Annotations = make(map[string]any)
		}
		t.Annotations[AnnotationName] = m
	}
}

// genCollectionQueries generates a single gql_collection.go in the query/ package
// containing CollectFields methods for all entity query types.
func (g *Generator) genCollectionQueries(nodes []*gen.Type) *jen.File {
	if g.config.ORMPackage == "" || len(nodes) == 0 {
		return nil
	}
	queryPkg := g.config.ORMPackage + "/query"
	f := jen.NewFilePathName(queryPkg, "query")
	f.HeaderComment("Code generated by velox. DO NOT EDIT.")

	f.ImportName("context", "context")
	f.ImportName(runtimePkgPath, "runtime")
	f.ImportName(gqlrelayPkg, "gqlrelay")

	for _, t := range nodes {
		entityPkg := g.entityPkgPath(t)
		f.ImportName(entityPkg, g.entityPkgName(t))

		queryType := t.QueryName()
		metaVar := t.Name + "CollectMeta"

		// CollectFields method on *{Entity}Query — local type in query/ package.
		f.Comment("CollectFields tells the query-builder to project the columns and")
		f.Comment("eager-load the edges the GraphQL selection of the resolver in ctx")
		f.Comment("reads. Call it in resolvers that return entities; Paginate collects")
		f.Comment("on its own. It is part of the entity's Querier interface, so it is")
		f.Comment("reachable from Query() without a type assertion.")
		f.Func().Params(
			jen.Id("q").Op("*").Id(queryType),
		).Id("CollectFields").Params(
			jen.Id("ctx").Qual("context", "Context"),
			jen.Id("satisfies").Op("...").String(),
		).Params(
			jen.Qual(g.config.ORMPackage+"/entity", t.Name+"Querier"),
			jen.Error(),
		).Block(
			jen.Return(
				jen.Id("q"),
				jen.Qual(gqlrelayPkg, "CollectFields").Call(
					jen.Id("ctx"),
					jen.Id("q"),
					jen.Op("&").Qual(entityPkg, metaVar),
					jen.Id("satisfies").Op("..."),
				),
			),
		)

		// CollectMeta lets the collector recurse into this query when it is
		// eager-loaded as another entity's edge (gqlrelay.MetaCollectable).
		f.Commentf("CollectMeta returns the GraphQL field collection metadata of %s.", t.Name)
		f.Func().Params(
			jen.Id("q").Op("*").Id(queryType),
		).Id("CollectMeta").Params().Op("*").Qual(runtimePkgPath, "CollectMeta").Block(
			jen.Return(jen.Op("&").Qual(entityPkg, metaVar)),
		)
	}

	return f
}

// genEntityCollectionInit generates an init() function that populates
// CollectMeta.FieldColumns and CollectMeta.Edges for GraphQL field collection.
// The generated code lives in the entity sub-package, so field constants use
// local (unqualified) references.
func (g *Generator) genEntityCollectionInit(f *jen.File, t *gen.Type, metaVar string) {
	// Collect scalar fields (GraphQL name → DB column).
	filteredFields := g.filterFields(t.Fields, SkipType)

	// Collect edges.
	filteredEdges := g.filterEdges(t.Edges, SkipType)

	f.Func().Id("init").Params().BlockFunc(func(grp *jen.Group) {
		// FieldColumns: map GraphQL field name → DB column name.
		grp.Id(metaVar).Dot("FieldColumns").Op("=").Map(jen.String()).String().ValuesFunc(func(d *jen.Group) {
			for _, fld := range filteredFields {
				gqlName := g.graphqlFieldName(fld)
				// Field constants are local to the entity sub-package.
				d.Lit(gqlName).Op(":").Id("Field" + pascal(fld.Name))
			}
		})

		// CollectedFor: GraphQL field name (a custom resolver) → the columns
		// it needs, from graphql.CollectedFor annotations. Iterates every
		// field, not just the exposed ones — hiding a column from the
		// GraphQL type while collecting it for a resolver is the point.
		if collected := collectedForColumns(g, t); len(collected) > 0 {
			grp.Id(metaVar).Dot("CollectedFor").Op("=").Map(jen.String()).Index().String().ValuesFunc(func(d *jen.Group) {
				for _, name := range slices.Sorted(maps.Keys(collected)) {
					cols := make([]jen.Code, 0, len(collected[name]))
					for _, col := range collected[name] {
						cols = append(cols, jen.Id("Field"+pascal(col)))
					}
					d.Lit(name).Op(":").Values(cols...)
				}
			})
		}

		// InterfaceFields: GraphQL interface field → contributing edge keys
		// and the type conditions its selection may use.
		if groups, err := g.interfaceFieldGroups(t); err == nil && len(groups) > 0 {
			grp.Id(metaVar).Dot("InterfaceFields").Op("=").Map(jen.String()).Qual(runtimePkgPath, "InterfaceFieldMeta").ValuesFunc(func(d *jen.Group) {
				for _, ifc := range groups {
					keys := make([]jen.Code, 0, len(ifc.Edges))
					sat := []jen.Code{}
					if ifc.InterfaceName != "" {
						sat = append(sat, jen.Lit(ifc.InterfaceName))
					}
					for _, e := range ifc.Edges {
						keys = append(keys, jen.Lit(camel(e.Name)))
						sat = append(sat, jen.Lit(g.graphqlTypeName(e.Type)))
					}
					d.Lit(ifc.FieldName).Op(":").Values(jen.Dict{
						jen.Id("Edges"):     jen.Index().String().Values(keys...),
						jen.Id("Satisfies"): jen.Index().String().Values(sat...),
						jen.Id("FastPath"):  jen.Lit(g.hasFKFastPath(t, ifc)),
					})
				}
			})
		}

		// Edges: map GraphQL edge name → EdgeMeta.
		if len(filteredEdges) > 0 {
			grp.Id(metaVar).Dot("Edges").Op("=").Map(jen.String()).Qual(runtimePkgPath, "EdgeMeta").ValuesFunc(func(d *jen.Group) {
				for _, e := range filteredEdges {
					edgeName := camel(e.Name)
					// Mirrors genEntityEdge's choice: a unique edge is never
					// a connection.
					relay := !e.Unique && g.config.RelayConnection && g.hasRelayConnection(e.Type)
					// genConnectionEdgeMethod emits the loaded-edge fast path
					// exactly when the target's ID orders in memory.
					pagesLoaded := relay && idCompareFunc(e.Type, g.goEntityName(e.Type)) != nil

					// Only a key on this entity's own table belongs in its
					// projection: for O2M the key is on the target table and
					// for M2M on the join table, and selecting either from
					// this table is invalid SQL.
					var fkCols []jen.Code
					if e.OwnFK() {
						for _, col := range e.Rel.Columns {
							fkCols = append(fkCols, jen.Lit(col))
						}
					}

					// Bare {...} value, not runtime.EdgeMeta{...} — keeps the
					// output gofmt -s simplified so format passes don't churn it.
					d.Lit(edgeName).Op(":").Values(jen.Dict{
						jen.Id("Name"):        jen.Lit(e.Name),
						jen.Id("Target"):      jen.Lit(e.Type.Table()),
						jen.Id("Unique"):      jen.Lit(e.Unique),
						jen.Id("Relay"):       jen.Lit(relay),
						jen.Id("PagesLoaded"): jen.Lit(pagesLoaded),
						jen.Id("FKColumns"):   jen.Index().String().Values(fkCols...),
						jen.Id("Inverse"):     jen.Lit(e.Inverse),
					})
				}
			})
		}
	})
}

// collectedForColumns returns, for each GraphQL field name named in a
// graphql.CollectedFor annotation on t's fields, the schema field names to
// collect for it, in schema declaration order.
func collectedForColumns(g *Generator, t *gen.Type) map[string][]string {
	out := map[string][]string{}
	for _, fld := range t.Fields {
		for _, name := range g.getFieldAnnotation(fld).GetCollectedFor() {
			out[name] = append(out[name], fld.Name)
		}
	}
	return out
}

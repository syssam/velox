const pgInvoices = `CREATE TABLE velox_otel.invoices (created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
	id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, org_id bigint NOT NULL, number text NOT NULL,
	total double precision NOT NULL, paid boolean NOT NULL, paid_at timestamptz, note text NOT NULL, data bytea NOT NULL)`

// TestPgxPreparesACommentedStatementOnce: spec success criterion 3. The SQL
// comment is stable per call site, so pgx's statement cache prepares a call
// site's statement once; another call site is another statement, and a tag
// the comment does not list changes nothing.
func TestPgxPreparesACommentedStatementOnce(t *testing.T) {
	dsn := os.Getenv("VELOX_TEST_POSTGRES")
	if dsn == "" {
		t.Skip("VELOX_TEST_POSTGRES is not set")
	}
	bg := context.Background()
	admin, err := pgx.Connect(bg, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = admin.Close(bg) }()
	for _, q := range []string{"DROP SCHEMA IF EXISTS velox_otel CASCADE", "CREATE SCHEMA velox_otel", pgInvoices} {
		if _, err := admin.Exec(bg, q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	t.Cleanup(func() { _, _ = admin.Exec(bg, "DROP SCHEMA IF EXISTS velox_otel CASCADE") })

	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	cfg.MaxConns = 1 // pg_prepared_statements is per session
	cfg.ConnConfig.RuntimeParams["search_path"] = "velox_otel"
	pool, err := pgxpool.NewWithConfig(bg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	defer pool.Close()
	db := velox.OpenPgx(pool, veloxotel.Options(veloxotel.Config{
		TracerProvider: sdktrace.NewTracerProvider(),
		App:            "otel-test",
		CommentTags:    []string{"route"},
	})...)
	prepared := func() (n int) {
		t.Helper()
		// The simple protocol, so that this query is not prepared itself.
		err := pool.QueryRow(bg, `SELECT count(*) FROM pg_prepared_statements WHERE statement LIKE '%FROM "invoices"%/*app=%'`,
			pgx.QueryExecModeSimpleProtocol).Scan(&n)
		if err != nil {
			t.Fatal(err)
		}
		return n
	}

	route := velox.WithTags(velox.WithTenant(bg, int64(1)), "route", "GET /invoices/{id}")
	for i := range 3 { // one call site, three times, each with another unlisted tag
		c := velox.WithTags(route, "user", string(rune('a'+i)))
		if _, err := db.Query[testmodel.Invoice]().Where(I.ID.EQ(1)).Limit(1).All(c); err != nil {
			t.Fatal(err)
		}
	}
	if n := prepared(); n != 1 {
		t.Errorf("one call site prepared %d statements, want 1", n)
	}
	if _, err := db.Query[testmodel.Invoice]().Where(I.ID.EQ(1)).Limit(1).All(route); err != nil {
		t.Fatal(err)
	}
	if n := prepared(); n != 2 {
		t.Errorf("two call sites prepared %d statements, want 2", n)
	}
}

// TestPgxOmitCallersPreparesOnce: with App and OmitCallers, one shape run
// from two call sites is one SQL text, so pgx prepares one statement.
func TestPgxOmitCallersPreparesOnce(t *testing.T) {
	dsn := os.Getenv("VELOX_TEST_POSTGRES")
	if dsn == "" {
		t.Skip("VELOX_TEST_POSTGRES is not set")
	}
	bg := context.Background()
	admin, err := pgx.Connect(bg, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = admin.Close(bg) }()
	for _, q := range []string{"DROP SCHEMA IF EXISTS velox_otel CASCADE", "CREATE SCHEMA velox_otel", pgInvoices} {
		if _, err := admin.Exec(bg, q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	t.Cleanup(func() { _, _ = admin.Exec(bg, "DROP SCHEMA IF EXISTS velox_otel CASCADE") })

	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	cfg.MaxConns = 1 // pg_prepared_statements is per session
	cfg.ConnConfig.RuntimeParams["search_path"] = "velox_otel"
	pool, err := pgxpool.NewWithConfig(bg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	defer pool.Close()
	db := velox.OpenPgx(pool, veloxotel.Options(veloxotel.Config{
		TracerProvider: sdktrace.NewTracerProvider(),
		App:            "otel-test",
		OmitCallers:    true,
	})...)
	c := velox.WithTenant(bg, int64(1))
	if _, err := db.Query[testmodel.Invoice]().Where(I.ID.EQ(1)).Limit(1).All(c); err != nil { // call site one
		t.Fatal(err)
	}
	if _, err := db.Query[testmodel.Invoice]().Where(I.ID.EQ(1)).Limit(1).All(c); err != nil { // call site two
		t.Fatal(err)
	}
	var n int
	// The simple protocol, so that this query is not prepared itself.
	err = pool.QueryRow(bg, `SELECT count(*) FROM pg_prepared_statements WHERE statement LIKE '%FROM "invoices"%/*app=%'`,
		pgx.QueryExecModeSimpleProtocol).Scan(&n)
	if err != nil {
		t.Fatal(err)
	}
	if n != 1 {
		t.Errorf("two call sites prepared %d statements, want 1", n)
	}
}

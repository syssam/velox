// TestUpDropTableThroughRebuiltChild: with foreign keys on, DROP TABLE p deletes
// c's rows at once, and c's rebuild later in the file copies none: a child counts
// as gone only when it is gone by the drop. With foreign keys off the rows stay,
// and a rebuild that lets go of the key accounts for it.
func TestUpDropTableThroughRebuiltChild(t *testing.T) {
	d := velox.SQLite
	const rebuild = `DROP TABLE p;
CREATE TABLE velox_new_c (id integer NOT NULL, p integer, PRIMARY KEY (id));
INSERT INTO velox_new_c (id, p) SELECT id, p FROM c;
DROP TABLE c;
ALTER TABLE velox_new_c RENAME TO c;
`
	setup := func(t *testing.T, head string) (*sql.DB, fstest.MapFS) {
		t.Helper()
		db, _ := freshDB(t, d)
		base := dirOf(t, d, files("0001_base.sql", "CREATE TABLE p (id integer NOT NULL, PRIMARY KEY (id));\nCREATE TABLE c (id integer NOT NULL, p integer, PRIMARY KEY (id), FOREIGN KEY (p) REFERENCES p (id) ON DELETE CASCADE);\n"))
		mustUp(t, db, base)
		mustExec(t, db, "INSERT INTO p VALUES (1), (2)")
		mustExec(t, db, "INSERT INTO c VALUES (1, 1), (2, 2)")
		return db, extend(t, base, d, files("0002_drop.sql", head+rebuild))
	}

	db, fsys := setup(t, "-- velox:allow drop-table\n-- velox:drops c.(p)\n")
	_, err := migrate.Up(context.Background(), db, fsys)
	var e *migrate.Error
	if !errors.As(err, &e) || e.Code != "unmodeled" || !strings.Contains(err.Error(), "the table c has a foreign key") {
		t.Fatalf("Up: %v; c has %d rows", err, count(t, db, "c"))
	}
	if n := count(t, db, "c"); n != 2 {
		t.Errorf("c has %d rows", n)
	}

	db, fsys = setup(t, "-- velox:foreign-keys off\n-- velox:drops c.(p)\n")
	if _, err := migrate.Up(context.Background(), db, fsys); err != nil {
		t.Fatalf("Up with foreign keys off: %v", err)
	}
	if n := count(t, db, "c"); n != 2 {
		t.Errorf("foreign keys off: c has %d rows", n)
	}
}

// TestLintFileDropsAndPartitions: a domain, type or collation dropped takes
// columns with CASCADE, and a partition its rows; Up said nothing of them.
func TestLintFileDropsAndPartitions(t *testing.T) {
	for _, c := range []struct {
		d     velox.Dialect
		sql   string
		codes []string // "<code> <target>"
	}{
		{velox.Postgres, "DROP DOMAIN IF EXISTS x CASCADE", []string{"drop-domain x"}},
		{velox.Postgres, "DROP DOMAIN a, app.b", []string{"drop-domain a", "drop-domain app.b"}},
		{velox.Postgres, "DROP TYPE mood CASCADE", []string{"drop-type mood"}},
		{velox.Postgres, "DROP COLLATION c1", []string{"drop-collation c1"}},
		{velox.MySQL, "ALTER TABLE t TRUNCATE PARTITION p0, p1", []string{"delete-rows t.p0", "delete-rows t.p1"}},
		{velox.MySQL, "ALTER TABLE t TRUNCATE PARTITION ALL", []string{"delete-rows t.ALL"}},
		{velox.MySQL, "ALTER TABLE t DROP PARTITION p0", []string{"drop-partition t.p0"}},
		{velox.MySQL, "ALTER TABLE t ADD PARTITION (PARTITION p9 VALUES LESS THAN (9))", nil},
		{velox.Postgres, "DROP INDEX x", nil},
	} {
		f, err := migrate.ParseFile(c.d, "0002_x.sql", []byte(c.sql+";\n"))
		if err != nil {
			t.Fatal(err)
		}
		findings, err := migrate.LintFile(c.d, f)
		if err != nil {
			t.Errorf("%s: %v", c.sql, err)
		}
		var got []string
		for _, fd := range findings {
			if fd.Class != migrate.Destructive {
				t.Errorf("%s: %v", c.sql, fd)
			}
			got = append(got, fd.Code+" "+fd.Target)
		}
		if !slices.Equal(got, c.codes) {
			t.Errorf("%s: %v, want %v", c.sql, got, c.codes)
		}
		for _, fd := range findings {
			f, err := migrate.ParseFile(c.d, "0002_x.sql", []byte("-- velox:allow "+fd.Code+" "+fd.Target+"\n"+c.sql+";\n"))
			if err != nil {
				t.Fatalf("the directive of %s: %v", fd.Code, err)
			}
			if blocked := migrate.Blocked([]migrate.Finding{fd}, f.Directives.Allow); len(blocked) != 0 {
				t.Errorf("%s is not allowed by its directive", fd.Code)
			}
		}
	}
	// Render's own DROP TYPE, of an enum type no column uses, is not a hand edit.
	generated := func(sql string) []migrate.Finding {
		f, err := migrate.ParseFile(velox.Postgres, "0002_x.sql", []byte("-- Generated by velox-gen migrate diff.\n"+sql+";\n"))
		if err != nil {
			t.Fatal(err)
		}
		findings, err := migrate.LintFile(velox.Postgres, f)
		if err != nil {
			t.Fatal(err)
		}
		return findings
	}
	if findings := generated("DROP TYPE mood"); len(findings) != 0 {
		t.Errorf("a generated DROP TYPE: %v", findings)
	}
	if findings := generated("DROP TYPE mood CASCADE"); len(findings) != 1 {
		t.Errorf("a generated DROP TYPE … CASCADE: %v", findings)
	}
}

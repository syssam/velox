// genHeader is the first line Dir.Add writes.
const genHeader = "-- Generated by velox-gen v0.1.0 migrate diff. Review before applying; velox.sum checks it.\n"

func parseFile(t *testing.T, d velox.Dialect, path, src string) migrate.File {
	t.Helper()
	f, err := migrate.ParseFile(d, path, []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	return f
}

// wantFileError checks err is a "file" *Error at pos with reason.
func wantFileError(t *testing.T, what string, err error, pos, reason string) {
	t.Helper()
	var e *migrate.Error
	if !errors.As(err, &e) || e.Code != "file" || e.Pos != pos || e.Reason != reason {
		t.Errorf("%s: error %v, want %s: %s", what, err, pos, reason)
	}
}

func TestParseFileName(t *testing.T) {
	f := parseFile(t, velox.Postgres, "0002_add_users_email.sql", "SELECT 1;")
	if f.Version != 2 || f.Name != "add_users_email" || f.Path != "0002_add_users_email.sql" {
		t.Errorf("version %d, name %q, path %q", f.Version, f.Name, f.Path)
	}
	if f := parseFile(t, velox.Postgres, "00012_x.sql", ""); f.Version != 12 || f.Name != "x" {
		t.Errorf("00012_x.sql: version %d, name %q", f.Version, f.Name)
	}
	for _, path := range []string{"001_x.sql", "0001-x.sql", "0001_X.sql", "0001_x.txt", "99999999999999999999_x.sql", "dir/0001_x.sql"} {
		_, err := migrate.ParseFile(velox.Postgres, path, []byte("SELECT 1;"))
		wantFileError(t, path, err, path, "the name is not <version>_<name>.sql, with a version of at least four digits and a name of a-z, 0-9 and _")
	}
	if _, err := migrate.ParseFile(99, "0001_x.sql", nil); err == nil {
		t.Error("an unknown dialect is accepted")
	}
}

func TestParseFileDirectives(t *testing.T) {
	var notDestructive string
	if _, err := migrate.ParseAllow("add-index"); err != nil {
		notDestructive = err.(*migrate.Error).Reason
	}
	for _, c := range []struct {
		d    velox.Dialect
		src  string
		want migrate.Directives
	}{
		{velox.Postgres, "-- velox:no-transaction\nSELECT 1;", migrate.Directives{NoTransaction: true}},
		{velox.MySQL, "-- velox:no-transaction\nSELECT 1;", migrate.Directives{NoTransaction: true}},
		{velox.SQLite, "-- velox:foreign-keys off\nSELECT 1;", migrate.Directives{ForeignKeysOff: true}},
		{velox.Postgres, "-- velox:lock-timeout 5s\nSELECT 1;", migrate.Directives{LockTimeout: 5 * time.Second, LockTimeoutSet: true}},
		{velox.MySQL, "-- velox:lock-timeout 1m30s\nSELECT 1;", migrate.Directives{LockTimeout: 90 * time.Second, LockTimeoutSet: true}},
		{velox.Postgres, "-- velox:lock-timeout 0\nSELECT 1;", migrate.Directives{LockTimeoutSet: true}},
		{velox.SQLite, "-- velox:allow drop-column users.legacy\n-- velox:allow drop-table\nSELECT 1;", migrate.Directives{Allow: []migrate.Allow{{Code: "drop-column", Target: "users.legacy"}, {Code: "drop-table"}}}},
		{velox.Postgres, "--  velox:no-transaction\nSELECT 1;", migrate.Directives{}}, // a comment, not a directive
	} {
		if got := parseFile(t, c.d, "0001_x.sql", c.src).Directives; !reflect.DeepEqual(got, c.want) {
			t.Errorf("%v %q: %+v, want %+v", c.d, c.src, got, c.want)
		}
	}
	for _, c := range []struct {
		d      velox.Dialect
		src    string
		line   string
		reason string
	}{
		{velox.Postgres, "-- velox:transaction\nSELECT 1;", "1", `unknown directive "transaction"`},
		{velox.Postgres, "-- velox:\nSELECT 1;", "1", `unknown directive ""`},
		{velox.Postgres, "-- velox:no-transaction now\n", "1", `malformed directive "no-transaction now": no-transaction takes no argument`},
		{velox.SQLite, "-- velox:foreign-keys on\n", "1", `malformed directive "foreign-keys on": write foreign-keys off`},
		{velox.Postgres, "-- velox:lock-timeout\n", "1", `malformed directive "lock-timeout": write lock-timeout <duration>, as 5s`},
		{velox.Postgres, "-- velox:lock-timeout 5\n", "1", `malformed directive "lock-timeout 5": time: missing unit in duration "5"`},
		{velox.Postgres, "-- velox:lock-timeout -1s\n", "1", `malformed directive "lock-timeout -1s": the duration is negative`},
		{velox.Postgres, "-- velox:allow\n", "1", `malformed directive "allow": write allow <code> [<target>]`},
		{velox.Postgres, "-- velox:allow drop-table a b\n", "1", `malformed directive "allow drop-table a b": write allow <code> [<target>]`},
		{velox.Postgres, "-- velox:allow add-index users\n", "1", `malformed directive "allow add-index users": ` + notDestructive},
		{velox.Postgres, "-- velox:allow drop-table=posts\n", "1", `malformed directive "allow drop-table=posts": write allow <code> [<target>]`},
		{velox.Postgres, "-- velox:unit now\n", "1", `malformed directive "unit now": unit takes no argument`},
		{velox.Postgres, "-- velox:no-transaction\n-- velox:no-transaction\n", "2", "no-transaction is given twice"},
		{velox.Postgres, "-- velox:lock-timeout 1s\n-- velox:lock-timeout 2s\n", "2", "lock-timeout is given twice"},
		{velox.Postgres, "SELECT 1;\n-- velox:lock-timeout 1s\n", "2", "lock-timeout comes after a statement; only unit can"},
		{velox.SQLite, "-- velox:no-transaction\n", "1", "no-transaction is refused on SQLite: a file outside a transaction would run unlocked"},
		{velox.Postgres, "-- velox:foreign-keys off\n", "1", "foreign-keys off is SQLite's only"},
		{velox.MySQL, "-- velox:foreign-keys off\n", "1", "foreign-keys off is SQLite's only"},
		{velox.SQLite, "-- velox:lock-timeout 5s\n", "1", "lock-timeout is refused on SQLite, whose lock wait is the runner's"},
		{velox.Postgres, "SELECT 1;\n-- velox:unit\nSELECT 2;", "2", "unit is only for a file run statement by statement: a MySQL file, or a no-transaction one"},
		{velox.SQLite, "-- velox:unit\nSELECT 2;", "1", "unit is only for a file run statement by statement: a MySQL file, or a no-transaction one"},
		{velox.Postgres, "SELECT 'x", "1", "unterminated string literal"},
		{velox.Postgres, "SELECT 1;\nSELECT 2; -- velox:unit\n", "2", "a directive must start its line"},
	} {
		_, err := migrate.ParseFile(c.d, "0001_x.sql", []byte(c.src))
		wantFileError(t, c.d.String()+" "+c.src, err, "0001_x.sql:"+c.line, c.reason)
	}
}

func TestParseFileUnits(t *testing.T) {
	f := parseFile(t, velox.Postgres, "0001_x.sql", "-- velox:no-transaction\nSELECT 1;\n-- velox:unit\nSELECT 2;\nSELECT 3;\n-- velox:unit\nSELECT 4;\n")
	if want := []int{0, 1, 3}; !reflect.DeepEqual(f.Units, want) {
		t.Errorf("no-transaction: units %v, want %v", f.Units, want)
	}
	if want := []string{"SELECT 1", "SELECT 2", "SELECT 3", "SELECT 4"}; !reflect.DeepEqual(f.Statements, want) {
		t.Errorf("statements %q, want %q", f.Statements, want)
	}
	if want := []int{2, 4, 5, 7}; !reflect.DeepEqual(migrate.FileLines(f), want) {
		t.Errorf("lines %v, want %v", migrate.FileLines(f), want)
	}
	if f := parseFile(t, velox.MySQL, "0001_x.sql", "SELECT 1; SELECT 2; SELECT 3;"); !reflect.DeepEqual(f.Units, []int{0, 1, 2}) {
		t.Errorf("MySQL: units %v", f.Units)
	}
	if f := parseFile(t, velox.MySQL, "0001_x.sql", "-- velox:unit\nSELECT 1; SELECT 2;\n-- velox:unit\n-- velox:unit\nSELECT 3;"); !reflect.DeepEqual(f.Units, []int{0, 2}) {
		t.Errorf("MySQL with units: units %v", f.Units)
	}
	if f := parseFile(t, velox.Postgres, "0001_x.sql", "SELECT 1; SELECT 2;"); f.Units != nil {
		t.Errorf("in a transaction: units %v", f.Units)
	}
}

func TestParseFileCRLF(t *testing.T) {
	src := genHeader + "-- velox:no-transaction\n-- velox:lock-timeout 5s\n\n-- velox:unit\n-- review: x\nSELECT 'a\nb';\n-- velox:unit\nSELECT 2;\n"
	lf := parseFile(t, velox.Postgres, "0001_x.sql", src)
	crlf := parseFile(t, velox.Postgres, "0001_x.sql", strings.ReplaceAll(src, "\n", "\r\n"))
	if !reflect.DeepEqual(lf, crlf) {
		t.Errorf("CRLF differs:\n%+v\n%+v", crlf, lf)
	}
	if !strings.HasPrefix(lf.Sum, "h1:") || len(lf.Sum) != len("h1:")+44 {
		t.Errorf("sum %q", lf.Sum)
	}
	if other := parseFile(t, velox.Postgres, "0001_x.sql", src+"\n"); other.Sum == lf.Sum {
		t.Error("an added line leaves the sum")
	}
}

func TestParseFileBackslash(t *testing.T) {
	for src, want := range map[string]bool{
		`INSERT INTO t VALUES ('a\\b')`:       true,
		`INSERT INTO t VALUES ("a\\b")`:       true,
		"INSERT INTO `a\\b` VALUES (1)":       false,
		"-- a \\ b\nINSERT INTO t VALUES (1)": false,
		"INSERT INTO t VALUES ('ab') # \\":    false,
		"INSERT INTO t VALUES ('ab')":         false,
	} {
		if got := migrate.FileBackslash(parseFile(t, velox.MySQL, "0001_x.sql", src)); got != want {
			t.Errorf("%q: backslash %v, want %v", src, got, want)
		}
	}
	if migrate.FileBackslash(parseFile(t, velox.Postgres, "0001_x.sql", `SELECT E'a\\b'`)) {
		t.Error("PostgreSQL: backslash set")
	}
}

func TestParseFileDquote(t *testing.T) {
	for src, want := range map[string]bool{
		`INSERT INTO t VALUES ("a")`:         true,
		`INSERT INTO t VALUES ('"a"')`:       false,
		"INSERT INTO `\"a` VALUES (1)":       false,
		"-- \"a\"\nINSERT INTO t VALUES (1)": false,
	} {
		if got := migrate.FileDquote(parseFile(t, velox.MySQL, "0001_x.sql", src)); got != want {
			t.Errorf("%q: dquote %v, want %v", src, got, want)
		}
	}
	if migrate.FileDquote(parseFile(t, velox.Postgres, "0001_x.sql", `SELECT "a"`)) {
		t.Error("PostgreSQL: dquote set")
	}
}

func TestParseFileBOM(t *testing.T) {
	src := genHeader + "-- velox:no-transaction\nSELECT 1;\n"
	plain := parseFile(t, velox.Postgres, "0001_x.sql", src)
	bom := parseFile(t, velox.Postgres, "0001_x.sql", "\xEF\xBB\xBF"+src)
	if !reflect.DeepEqual(bom, plain) {
		t.Errorf("BOM differs:\n%+v\n%+v", bom, plain)
	}
	if !migrate.FileGenerated(bom) || !bom.Directives.NoTransaction {
		t.Errorf("BOM: generated %v, directives %+v", migrate.FileGenerated(bom), bom.Directives)
	}
	if !reflect.DeepEqual(migrate.FileLines(bom), []int{3}) {
		t.Errorf("BOM: lines %v", migrate.FileLines(bom))
	}
	nobom := parseFile(t, velox.Postgres, "0001_x.sql", "-- velox:no-transaction\nSELECT 1;")
	withbom := parseFile(t, velox.Postgres, "0001_x.sql", "\xEF\xBB\xBF-- velox:no-transaction\r\nSELECT 1;")
	if !reflect.DeepEqual(nobom, withbom) {
		t.Errorf("BOM and CRLF differ:\n%+v\n%+v", withbom, nobom)
	}
}


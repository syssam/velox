// A File is one migration file of a directory.
type File struct {
	Version    uint64
	Name       string // "add_users_email"
	Path       string // "0002_add_users_email.sql"
	Sum        string // "h1:…", as the history holds it: see historySum
	Directives Directives
	Statements []string
	Units      []int // the index of each unit's first statement

	lines     []int // the line, from 1, of each statement's first token
	backslash bool  // MySQL: a string literal holds a backslash
	dquote    bool  // MySQL: a "…" literal, which ANSI_QUOTES would read as a name
	generated bool  // the first line is the header Dir.Add writes ("-- Generated by velox-gen "); LintFile reads it
}

// fileName is a migration file's name: its version and name.
var fileName = regexp.MustCompile(`^([0-9]{4,})_([a-z0-9_]+)\.sql$`)

// generatedPrefix starts the first line of a file Dir.Add writes.
const generatedPrefix = "-- Generated by velox-gen "

// ParseFile reads the migration file at path, data its content, as d reads
// it. A leading UTF-8 byte order mark is dropped and CRLF is read as LF.
// The name is <version>_<name>.sql, the version a decimal of at least four
// digits and the name of a-z, 0-9 and _. Each directive starts its line,
// and all come before the first statement, but unit, which starts a
// group of statements in a file run statement by statement: a MySQL file,
// or a PostgreSQL no-transaction one. In such a file, Units holds the index
// of each unit's first statement, and a statement before the first unit
// line is a unit alone; a file run in a transaction has none. An allow
// directive's target is one word, or in Go's double quotes when it has white
// space or starts with a double quote.
//
// Its errors are *Error values with Code "file" and Pos "<path>:<line>"
// (the path alone for a bad name): a bad name, an unterminated quote,
// comment or dollar quote, on SQLite or MySQL a statement that starts a
// trigger, a MySQL procedure, function or event, or a BEGIN … END block,
// or on PostgreSQL a BEGIN ATOMIC body or a psql meta-command line (one
// that starts with a backslash, as pg_dump 18's \restrict does), whose body
// or line the split cannot read as SQL, a directive inside a statement or
// not at the start of its line, or one that is unknown, malformed, given twice (but
// allow and unit), after the first statement (but unit) or refused on d.
// An unknown d is Code "dialect".
func ParseFile(d velox.Dialect, path string, data []byte) (File, error) {
	if d != velox.Postgres && d != velox.MySQL && d != velox.SQLite {
		return File{}, &Error{Code: "dialect", Pos: path, Reason: fmt.Sprintf("ParseFile has no dialect %s", d)}
	}
	m := fileName.FindStringSubmatch(path)
	var version uint64
	ok := m != nil
	if ok {
		v, err := strconv.ParseUint(m[1], 10, 64)
		version, ok = v, err == nil
	}
	if !ok {
		return File{}, &Error{Code: "file", Pos: path, Reason: "the name is not <version>_<name>.sql, with a version of at least four digits and a name of a-z, 0-9 and _"}
	}
	data = asText(data)
	f := File{Version: version, Name: m[2], Path: path}
	f.generated = strings.HasPrefix(string(data), generatedPrefix)
	s := splitter{d: d, src: string(data)}
	refuse := func(line int, format string, args ...any) error {
		return &Error{Code: "file", Pos: path + ":" + strconv.Itoa(line), Reason: fmt.Sprintf(format, args...)}
	}
	if err := s.run(); err != nil {
		e := err.(*Error)
		e.Pos = path + ":" + e.Pos
		return File{}, e
	}
	f.backslash, f.dquote = s.backslash, s.dquote
	f.Sum = historySum(data, s.out)
	seen := map[string]bool{}
	unitLine := 0     // the first unit line
	unitNext := false // a unit line since the last statement
	inUnit := false   // a unit line came before
	var starts []int  // the statements that start a unit
	for _, p := range s.out {
		if p.SQL != "" {
			if unitNext || !inUnit {
				starts = append(starts, len(f.Statements))
			}
			unitNext = false
			f.Statements = append(f.Statements, p.SQL)
			f.lines = append(f.lines, p.Line)
			continue
		}
		fields := strings.Fields(p.Directive)
		word := ""
		if len(fields) > 0 {
			word = fields[0]
		}
		malformed := func(how string) error { return refuse(p.Line, "malformed directive %q: %s", p.Directive, how) }
		switch word {
		case "no-transaction", "foreign-keys", "lock-timeout", "allow", "drops", "unit":
		default:
			return File{}, refuse(p.Line, "unknown directive %q", word)
		}
		if word != "unit" {
			if len(f.Statements) > 0 {
				return File{}, refuse(p.Line, "%s comes after a statement; only unit can", word)
			}
			if word != "allow" && word != "drops" && seen[word] {
				return File{}, refuse(p.Line, "%s is given twice", word)
			}
			seen[word] = true
		}
		dd := &f.Directives
		switch word {
		case "no-transaction":
			if len(fields) != 1 {
				return File{}, malformed("no-transaction takes no argument")
			}
			if d == velox.SQLite {
				return File{}, refuse(p.Line, "no-transaction is refused on SQLite: a file outside a transaction would run unlocked")
			}
			dd.NoTransaction = true
		case "foreign-keys":
			if len(fields) != 2 || fields[1] != "off" {
				return File{}, malformed("write foreign-keys off")
			}
			if d != velox.SQLite {
				return File{}, refuse(p.Line, "foreign-keys off is SQLite's only")
			}
			dd.ForeignKeysOff = true
		case "lock-timeout":
			if len(fields) != 2 {
				return File{}, malformed("write lock-timeout <duration>, as 5s")
			}
			t, err := time.ParseDuration(fields[1])
			switch {
			case err != nil:
				return File{}, malformed(err.Error())
			case t < 0:
				return File{}, malformed("the duration is negative")
			case d == velox.SQLite:
				return File{}, refuse(p.Line, "lock-timeout is refused on SQLite, whose lock wait is the runner's")
			}
			dd.LockTimeout, dd.LockTimeoutSet = t, true
		case "allow":
			code, target, ok := allowParts(p.Directive)
			if !ok {
				return File{}, malformed("write allow <code> [<target>]")
			}
			as, err := ParseAllow(code)
			switch {
			case err != nil:
				return File{}, malformed(err.(*Error).Reason)
			case len(as) != 1 || as[0].Code != code:
				return File{}, malformed("write allow <code> [<target>]")
			}
			dd.Allow = append(dd.Allow, Allow{Code: code, Target: target})
		case "drops":
			target, ok := dropsTarget(p.Directive)
			if !ok {
				return File{}, malformed("write drops <target>")
			}
			dd.Drops = append(dd.Drops, target)
		case "unit":
			if len(fields) != 1 {
				return File{}, malformed("unit takes no argument")
			}
			if unitLine == 0 {
				unitLine = p.Line
			}
			unitNext, inUnit = true, true
		}
	}
	byStatement := d == velox.MySQL || f.Directives.NoTransaction
	if unitLine > 0 && !byStatement {
		return File{}, refuse(unitLine, "unit is only for a file run statement by statement: a MySQL file, or a no-transaction one")
	}
	if byStatement {
		f.Units = starts
	}
	return f, nil
}

// historySum is what the history records of a file and compares it with: sum of
// data without its allow and drops lines, which say what the file accepts and
// change no statement. So an environment that applied a file does not stop when
// another needs a directive added to it. velox.sum is over the whole file.
func historySum(data []byte, pieces []piece) string {
	var skip []int // the lines left out, from 1, in order
	for _, p := range pieces {
		if fields := strings.Fields(p.Directive); len(fields) > 0 && (fields[0] == "allow" || fields[0] == "drops") {
			skip = append(skip, p.Line)
		}
	}
	if len(skip) == 0 {
		return sum(data)
	}
	var kept []byte
	for i, line := range bytes.SplitAfter(data, []byte("\n")) {
		if !slices.Contains(skip, i+1) {
			kept = append(kept, line...)
		}
	}
	return sum(kept)
}

// allowParts reads an allow directive: its code and its target, one word or
// Go's double-quoted form, which allowTarget writes for any other.
func allowParts(directive string) (code, target string, ok bool) {
	rest := strings.TrimLeftFunc(strings.TrimPrefix(directive, "allow"), unicode.IsSpace)
	i := strings.IndexFunc(rest, unicode.IsSpace)
	if i < 0 {
		return rest, "", rest != ""
	}
	code, rest = rest[:i], strings.TrimSpace(rest[i:])
	if strings.HasPrefix(rest, `"`) {
		if t, err := strconv.Unquote(rest); err == nil {
			return code, t, true
		}
	}
	return code, rest, !strings.ContainsFunc(rest, unicode.IsSpace)
}

// dropsTarget reads a drops directive's target, as an allow directive's.
func dropsTarget(directive string) (string, bool) {
	rest := strings.TrimSpace(strings.TrimPrefix(directive, "drops"))
	if strings.HasPrefix(rest, `"`) {
		if t, err := strconv.Unquote(rest); err == nil {
			return t, true
		}
	}
	return rest, rest != "" && !strings.ContainsFunc(rest, unicode.IsSpace)
}

// allowTarget is target as an allow directive writes it: as it is when it is
// one word that does not start with a double quote, so that any legal
// identifier reads back and a plain one's line does not change.
func allowTarget(target string) string {
	if strings.ContainsFunc(target, unicode.IsSpace) || strings.HasPrefix(target, `"`) {
		return strconv.Quote(target)
	}
	return target
}

// bom is the UTF-8 byte order mark some editors start a file with.
var bom = []byte("\xEF\xBB\xBF")

// asText is a file of the directory as it is read and hashed: without a
// leading UTF-8 byte order mark, and with each "\r\n" read as "\n".
func asText(data []byte) []byte {
	return bytes.ReplaceAll(bytes.TrimPrefix(data, bom), []byte("\r\n"), []byte("\n"))
}

// versionFile is the name of version's file: "<version>_<name>.sql", the
// version of at least four digits.
func versionFile(version uint64, name string) string {
	return fmt.Sprintf("%04d_%s.sql", version, name)
}

// sum is a file's hash: "h1:" and the padded standard base64 of the SHA-256
// of data as asText reads it.
func sum(data []byte) string {
	h := sha256.Sum256(asText(data))
	return "h1:" + base64.StdEncoding.EncodeToString(h[:])
}

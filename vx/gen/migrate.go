package gen

import (
	"bytes"
	"fmt"

	vgen "github.com/syssam/velox/compiler/gen"
	vsql "github.com/syssam/velox/compiler/gen/sql"
)

// migrate generates the migrate package: the tables of the schema and the
// functions that create them.
//
// The table definitions are rendered by velox's own migration generator, not
// by a second one written here: a database that velox migrated must be seen
// as up to date, column for column and constraint name for constraint name,
// and two generators of the same DDL drift (velox's two did, on the action
// and on the name of a foreign key).
func (g *generator) migrate(graph *vgen.Graph, files map[string][]byte) error {
	out, err := vsql.NewDialect(vgen.NewJenniferGenerator(graph, g.cfg.Target)).GenMigrate()
	if err != nil {
		return fmt.Errorf("vx: migrate: %w", err)
	}
	if out.Schema == nil {
		return nil
	}
	src, err := vgen.FormatJenFile(out.Schema, "migrate/schema.go")
	if err != nil {
		return fmt.Errorf("vx: migrate: %w", err)
	}
	// One header, this generator's: prune recognizes its files by it.
	src = bytes.TrimPrefix(src, []byte("// Code generated by velox. DO NOT EDIT.\n"))
	src = bytes.TrimPrefix(src, []byte("// Code generated by velox. DO NOT EDIT.\n"))
	files["migrate/schema.go"] = append([]byte(header), bytes.TrimLeft(src, "\n")...)

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString(`// Package migrate creates and updates the tables of the schema.
//
//	if err := migrate.Create(ctx, conn); err != nil { ... }
//
// Create compares the tables in the database with Tables and applies the
// difference; it adds and never drops unless asked to (WithDropColumn,
// WithDropIndex). WriteTo prints the statements instead of running them, to
// review them or to keep them as a migration file.
package migrate

import (
	"context"
	"fmt"
	"io"

	"github.com/syssam/velox/dialect/sql/schema"
	"` + ormPath + `"
)

var (
	// WithDropColumn lets the migration drop columns the schema no longer has.
	WithDropColumn = schema.WithDropColumn
	// WithDropIndex lets the migration drop indexes the schema no longer has.
	WithDropIndex = schema.WithDropIndex
	// WithForeignKeys says whether foreign keys are created (the default).
	WithForeignKeys = schema.WithForeignKeys
	// WithGlobalUniqueID gives every table its own range of ids.
	WithGlobalUniqueID = schema.WithGlobalUniqueID
)

// Create brings the tables of db up to date with the schema.
func Create(ctx context.Context, db *orm.DB, opts ...schema.MigrateOption) error {
	m, err := schema.NewMigrate(db.Driver(), opts...)
	if err != nil {
		return fmt.Errorf("migrate: %w", err)
	}
	return m.Create(ctx, Tables...)
}

// WriteTo writes the statements Create would run to w, and runs none.
func WriteTo(ctx context.Context, db *orm.DB, w io.Writer, opts ...schema.MigrateOption) error {
	m, err := schema.NewMigrate(&schema.WriteDriver{Driver: db.Driver(), Writer: w}, opts...)
	if err != nil {
		return fmt.Errorf("migrate: %w", err)
	}
	return m.Create(ctx, Tables...)
}
`)
	files["migrate/migrate.go"] = b.Bytes()
	return nil
}

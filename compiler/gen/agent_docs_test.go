package gen

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// AGENTS.md exists because every wrong use of this library found so far was
// a reader answering "where does X live" or "what does this API not do"
// from the wrong place. Prose in velox's own docs/ does not reach them:
// they are looking at generated code inside their own repository.
//
// These tests pin the content that carries that weight. They are content
// assertions rather than a golden file on purpose — a golden would be
// updated reflexively, and the point is that removing any of these lines
// should require an argument.
func renderDocs(t *testing.T, g *JenniferGenerator) string {
	t.Helper()
	var b strings.Builder
	g.renderAgentDocs(&b)
	return b.String()
}

func testDocsGenerator() *JenniferGenerator {
	return &JenniferGenerator{
		outDir: "/tmp/proj/velox",
		graph: &Graph{
			Config: &Config{},
			Nodes: []*Type{
				{Name: "Invoice"},
				{Name: "SalesOrder"},
			},
		},
	}
}

func TestAgentDocs_PointsAtThePerEntityClient(t *testing.T) {
	out := renderDocs(t, testDocsGenerator())

	assert.Contains(t, out, "client.Invoice.Intercept(...)",
		"the per-entity registration path must be named — a reader who only "+
			"finds Client.Intercept concludes fan-out is the only option and "+
			"never opens client/<entity>/")
	assert.Contains(t, out, "the API you want is often not in the package you opened")
	assert.Contains(t, out, "client/invoice/")
}

func TestAgentDocs_StatesTheInterceptorWriteGap(t *testing.T) {
	out := renderDocs(t, testDocsGenerator())

	require.Contains(t, out, "Row-level authorization")
	assert.Contains(t, out, "An interceptor never runs on a mutation",
		"the coverage gap is the whole reason a tenant filter built from "+
			"interceptors can delete another tenant's rows")
	assert.Contains(t, out, "HasXxxWith(...)",
		"edge-predicate subqueries are scoped by neither mechanism")
	assert.Contains(t, out, "invariant check",
		"over-scoping an invariant read corrupts data rather than leaking it")
}

func TestAgentDocs_ListsDeviationsFromEnt(t *testing.T) {
	out := renderDocs(t, testDocsGenerator())

	for _, want := range []string{
		"(*Entity).Update()",
		"Unwrap()",
		"Schema-level `Interceptors()` is rejected",
		"`Optional()` does not add a DB default",
	} {
		assert.Contains(t, out, want,
			"a reader assuming Ent semantics gets this wrong; it must be stated")
	}
}

func TestAgentDocs_InventoriesEntitiesAndEdges(t *testing.T) {
	g := testDocsGenerator()
	g.graph.Nodes[0].Edges = []*Edge{{Name: "lines", Type: g.graph.Nodes[1]}}

	out := renderDocs(t, g)

	assert.Contains(t, out, "## Entities (2)")
	assert.Contains(t, out, "lines→SalesOrder",
		"the edge inventory is generated because counting edges by hand across "+
			"a large schema is unreliable")
}

func TestAgentDocs_ReportsEnabledFeatures(t *testing.T) {
	g := testDocsGenerator()

	out := renderDocs(t, g)
	assert.Contains(t, out, "No optional features are enabled.")

	g.graph.Features = []Feature{FeaturePrivacy, FeatureIntercept}
	out = renderDocs(t, g)
	assert.Contains(t, out, "`"+FeaturePrivacy.Name+"`")
	assert.Contains(t, out, "`"+FeatureIntercept.Name+"`")
	assert.Contains(t, out, "may simply be absent rather than renamed",
		"a missing API is more often a disabled feature than a renamed one")
}

func TestAgentDocs_IsMarkedGenerated(t *testing.T) {
	out := renderDocs(t, testDocsGenerator())

	assert.True(t, strings.HasPrefix(out, "<!-- Code generated by velox. DO NOT EDIT. -->"),
		"the file must announce itself as generated — a hand-edited copy would "+
			"go stale silently, which is the failure mode it exists to prevent")
}

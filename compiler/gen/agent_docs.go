package gen

import (
	"fmt"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// agentDocsFile is the orientation document written into the generated
// output directory.
const agentDocsFile = "AGENTS.md"

// writeAgentDocs emits AGENTS.md next to the generated client.
//
// The audience is a coding agent — or a human — that has just opened a
// project using this client and needs to answer "where does X live" and
// "what does this API not do" without reading N generated packages.
//
// It exists because the failures this file describes were all found the
// expensive way. A reader looking for per-entity interceptor registration
// finds `Client.Intercept` in client.go, concludes that fan-out is the
// only path, and never reaches `client/<entity>/client.go` — one of
// potentially hundreds of directories. A reader who assumes velox matches
// Ent gets `field.Sensitive()` and row-scoping semantics wrong. Prose in
// docs/ does not help, because the reader is looking at generated code in
// their own repository, not at velox's.
//
// Being generated is the point: a hand-written note about a 400-entity
// client goes stale silently, and stale guidance is what produced the
// bugs in the first place. Everything here is derived from the graph.
func (g *JenniferGenerator) writeAgentDocs() error {
	var b strings.Builder
	g.renderAgentDocs(&b)

	outPath := filepath.Join(g.outDir, agentDocsFile)
	if _, err := WriteFileIfChanged(outPath, []byte(b.String()), 0o644); err != nil {
		return err
	}
	if rel, err := filepath.Rel(g.outDir, outPath); err == nil && rel != "" {
		g.manifestMu.Lock()
		g.generatedFiles = append(g.generatedFiles, rel)
		g.manifestMu.Unlock()
	}
	return nil
}

// renderAgentDocs writes the document body. Split out so the content is
// testable without touching the filesystem.
func (g *JenniferGenerator) renderAgentDocs(b *strings.Builder) {
	graph := g.graph
	// Derived from the generated client's import path, never from outDir:
	// `velox generate --check` renders into a temp directory and compares,
	// so any content that varies with the output location reads as drift.
	pkg := "velox"
	if graph.Package != "" {
		pkg = path.Base(graph.Package)
	}

	fmt.Fprintf(b, "<!-- Code generated by velox. DO NOT EDIT. -->\n\n")
	fmt.Fprintf(b, "# %s — generated velox client\n\n", pkg)
	fmt.Fprintf(b, "Every file in this directory is generated from the schema package. ")
	fmt.Fprintf(b, "Edits are overwritten on the next run; change the schema instead.\n\n")

	g.renderAgentDocsLayout(b, graph)
	g.renderAgentDocsAuthorization(b)
	g.renderAgentDocsDeviations(b)
	g.renderAgentDocsFeatures(b, graph)
	g.renderAgentDocsEntities(b, graph)
}

func (g *JenniferGenerator) renderAgentDocsLayout(b *strings.Builder, graph *Graph) {
	first := "Xxx"
	firstDir := "xxx"
	if len(graph.Nodes) > 0 {
		first = graph.Nodes[0].Name
		firstDir = graph.Nodes[0].PackageDir()
	}

	b.WriteString("## Where things live\n\n")
	b.WriteString("The client is split across packages so that a schema with hundreds of\n")
	b.WriteString("entities stays incrementally compilable. Consequence for the reader:\n")
	b.WriteString("**the API you want is often not in the package you opened.**\n\n")
	b.WriteString("| Package | Holds |\n|---|---|\n")
	fmt.Fprintf(b, "| `.` (root) | `Client`, `Tx`, `Open`, and the fan-out `Use`/`Intercept` |\n")
	fmt.Fprintf(b, "| `entity/` | entity structs, edge methods (`(*%s).QueryXxx()`), shared stores |\n", first)
	fmt.Fprintf(b, "| `client/%s/` | CRUD builders, mutations, **per-entity `Use`/`Intercept`** |\n", firstDir)
	fmt.Fprintf(b, "| `query/` | query builders (`%sQuery`) |\n", first)
	fmt.Fprintf(b, "| `%s/` | column constants, predicates (`%s.NameField.EQ(...)`) |\n", firstDir, firstDir)
	fmt.Fprintf(b, "| `predicate/` | predicate types |\n\n")
	fmt.Fprintf(b, "Registering a hook or interceptor for ONE entity uses the per-entity\n")
	fmt.Fprintf(b, "client, not the root one:\n\n")
	fmt.Fprintf(b, "```go\nclient.%s.Intercept(...)   // this entity only\nclient.Intercept(...)   %s// every entity — a typed intercept.Traverse%s\n"+
		"                        %s// registered here rejects the first query of any other type\n```\n\n",
		first, strings.Repeat(" ", len(first)), first, strings.Repeat(" ", len(first)))
}

func (g *JenniferGenerator) renderAgentDocsAuthorization(b *strings.Builder) {
	b.WriteString("## Row-level authorization: use `Policy()`, not interceptors\n\n")
	b.WriteString("Measured coverage, not intent:\n\n")
	b.WriteString("| Surface | `Intercept()` | `Policy()` |\n|---|---|---|\n")
	b.WriteString("| `All`/`Count`/`IDs`/`Exist`/`Only`/`First`/`Get` | yes | yes |\n")
	b.WriteString("| `Select`/`GroupBy`/`Aggregate` | yes | yes |\n")
	b.WriteString("| eager loading, edge queries, `Noder`, inside a `Tx` | yes | yes |\n")
	b.WriteString("| `Create` | **no** | yes |\n")
	b.WriteString("| `Update()`/`Delete()` by predicate | **no** | yes |\n")
	b.WriteString("| `HasXxxWith(...)` subqueries | **no** | **no** |\n\n")
	b.WriteString("An interceptor never runs on a mutation, so a tenant filter built only\n")
	b.WriteString("from interceptors can update and delete other tenants' rows. Express\n")
	b.WriteString("row-level authorization as a schema `Policy()` — `privacy.TenantFilterRule`\n")
	b.WriteString("covers reads and predicate-based writes in one registration. Interceptors\n")
	b.WriteString("are for query shaping.\n\n")
	b.WriteString("Two limits worth knowing before designing around either:\n\n")
	b.WriteString("- **Edge predicates are not scoped.** `HasXxxWith(...)` compiles to a\n")
	b.WriteString("  subquery built directly on a `*sql.Selector`; it never becomes a Query,\n")
	b.WriteString("  so no rule observes it. A caller can learn whether out-of-scope rows\n")
	b.WriteString("  exist by filtering through an edge.\n")
	b.WriteString("- **A row filter cannot tell a user-facing read from an invariant check.**\n")
	b.WriteString("  Narrowing a dependency `Exist()` before a delete, a uniqueness probe or\n")
	b.WriteString("  a lock acquisition does not leak data, it corrupts it: the guard reports\n")
	b.WriteString("  \"no dependents\" for rows outside the scope and the delete proceeds, with\n")
	b.WriteString("  nothing to detect it afterwards. Only the call site knows which kind a\n")
	b.WriteString("  read is. Interceptors are per-client, so one scoped client for request\n")
	b.WriteString("  handling and one unscoped client for internal checks expresses the split;\n")
	b.WriteString("  a `Policy()` is process-global and cannot.\n\n")
}

func (g *JenniferGenerator) renderAgentDocsDeviations(b *strings.Builder) {
	b.WriteString("## Where velox differs from Ent\n\n")
	b.WriteString("velox follows Ent closely, so the differences are the expensive part.\n\n")
	b.WriteString("- **No `(*Entity).Update()` / `(*Entity).Delete()`.** Use\n")
	b.WriteString("  `client.Xxx.UpdateOne(v)` — it uses the client's driver, so it is\n")
	b.WriteString("  unaffected by the transaction-driver footgun `Unwrap()` exists to patch.\n")
	b.WriteString("- **`Unwrap()` is not a no-op.** An entity returned from inside a\n")
	b.WriteString("  transaction carries the tx driver; reading an edge through it after\n")
	b.WriteString("  commit fails. Call `Unwrap()` before handing such an entity to code\n")
	b.WriteString("  that may read through it. It panics on a non-transactional entity.\n")
	b.WriteString("- **Schema-level `Interceptors()` is rejected at codegen time.** It would\n")
	b.WriteString("  apply to every client in the process, including one used for internal\n")
	b.WriteString("  invariant checks. Use `Policy()` or `client.Xxx.Intercept(...)`.\n")
	b.WriteString("- **`Optional()` does not add a DB default.** Pair it with `Default()`.\n")
	b.WriteString("- **An edge bound with `.Field(\"x_id\")` inherits `Optional`/`Immutable`\n")
	b.WriteString("  from that field** — declare nullability once, on the field.\n\n")
}

func (g *JenniferGenerator) renderAgentDocsFeatures(b *strings.Builder, graph *Graph) {
	b.WriteString("## Enabled in this project\n\n")
	// Features live on the embedded *Config, which a Graph built by hand
	// (tests, tooling) may not carry.
	if graph.Config == nil || len(graph.Features) == 0 {
		b.WriteString("No optional features are enabled.\n\n")
		return
	}
	names := make([]string, 0, len(graph.Features))
	for _, f := range graph.Features {
		names = append(names, f.Name)
	}
	sort.Strings(names)
	b.WriteString("Code for features not listed here is not generated, so an API you\n")
	b.WriteString("expect may simply be absent rather than renamed.\n\n")
	for _, n := range names {
		fmt.Fprintf(b, "- `%s`\n", n)
	}
	b.WriteString("\n")
}

func (g *JenniferGenerator) renderAgentDocsEntities(b *strings.Builder, graph *Graph) {
	fmt.Fprintf(b, "## Entities (%d)\n\n", len(graph.Nodes))
	if len(graph.Nodes) == 0 {
		return
	}
	b.WriteString("| Entity | Table | Package dir | Edges |\n|---|---|---|---|\n")
	for _, t := range graph.Nodes {
		edges := make([]string, 0, len(t.Edges))
		for _, e := range t.Edges {
			target := e.Name
			if e.Type != nil {
				target = e.Type.Name
			}
			edges = append(edges, fmt.Sprintf("%s→%s", e.Name, target))
		}
		list := strings.Join(edges, ", ")
		if list == "" {
			list = "—"
		}
		fmt.Fprintf(b, "| `%s` | `%s` | `%s/` | %s |\n", t.Name, t.Table(), t.PackageDir(), list)
	}
	b.WriteString("\n")
}
